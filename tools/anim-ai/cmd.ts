/**
 * Разбор команды движка — вынесен в отдельный модуль, чтобы его можно было проверить тестом:
 * импорт `server.ts` поднимает слушатель и выходит без ключа, а граница доверия обязана
 * проверяться без того и другого.
 */
/**
 * Разбор шаблона команды в argv. Кавычки уважаем, но НИКАКОЙ ОБОЛОЧКИ: промпт приходит от
 * пользователя, и запуск через `shell: true` означал бы выполнение чего угодно из текста запроса.
 * Подстановки идут в УЖЕ РАЗОБРАННЫЕ аргументы, поэтому пробелы и кавычки внутри промпта
 * остаются данными, а не синтаксисом.
 */
export function parseCmd(tpl: string): string[] {
  return [...tpl.matchAll(/"([^"]*)"|'([^']*)'|(\S+)/g)].map((m) => m[1] ?? m[2] ?? m[3] ?? '');
}
export function fillArgs(argv: readonly string[], vars: Record<string, string>): string[] {
  return argv.map((a) => a.replace(/\{(\w+)\}/g, (whole, k: string) => vars[k] ?? whole));
}
