import type { ConfigRegistry } from '@dm/shared';

/**
 * ⚠ ЛЕСТНИЦА ТИРОВ СЛОЖНОСТИ ДЛЯ ТЕСТОВ — СВОЙ СТЕНД, а не живые данные.
 *
 * В игре включён ОДИН тир («normal»): сложность растёт ГЛУБИНОЙ, а не выбором тира — остальные упразднены до того,
 * как под них придумают свой вызов и свою награду (решение владельца). Но сторожа комнаты про ВОРОТА тира (R7-06, R8-02),
 * про показ тира в окне спуска (R9-08) и про «тир открыт хоть одному голосовавшему» (C-12) требуют, чтобы тиров было
 * несколько и они открывались друг за другом: на одном включённом они проходили бы ВХОЛОСТУЮ. Поэтому такие файлы ставят
 * свою лестницу и не зависят от того, что включено в данных игры (и не сломаются, когда тиры вернутся другим рычагом).
 *
 * Поля берём из живых данных — добавится новое, стенд его не потеряет; меняются только `enabled` и `unlockFloor`.
 */
export function standDifficulties(cfg: ConfigRegistry): void {
  const gates: Record<string, number> = { easy: 0, normal: 5, hard: 10, nightmare: 12 };
  cfg.reload({
    difficulties: cfg.get('difficulties').map((d) => ({ ...d, enabled: true, unlockFloor: gates[d.id] ?? d.unlockFloor })),
  });
}
