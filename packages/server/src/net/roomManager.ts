        const key = runLedgerKey(save.run.config);
        // ⭐ R17-02: ДЕРЖАТЕЛЬ В ГОРОДЕ (НА АРЕНЕ) ЗАБЕГ ЖИВОМУ УЧАСТНИКУ ОТДАЁТ (`Room.yieldRun`) — «Продолжить» ведёт в новую комнату, прямо на
