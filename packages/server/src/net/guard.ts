  // Ковка и зачарование — у кузнеца, как и прочая кузница: из подземелья не куют (и сундук аккаунта там не открыт).
  craft: 'town',
  forgeEnchant: 'town',
  // Эскиз открывает деталь в журнале кузнеца — журнал в сундуке аккаунта, у кузнеца (R3-11).
  forgeSketch: 'town',
