import type { TownCommand } from '@dm/shared';

/**
 * Санитарные проверки команд (Ф3.1).
 *
 * ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ. План предполагал проверки движения — «дистанция за тик не больше
 * максимальной скорости», «позиция в проходимой клетке». Оказалось, проверять нечего: клиент
 * НЕ присылает позицию вообще. Он шлёт направление, сервер нормализует вектор (Ф0.6), берёт
 * скорость из своих статов и сам двигает игрока через `moveWithCollision`. Телепорт и спидхак
 * через ввод невозможны по построению, и добавлять сюда проверку было бы имитацией работы.
 *
 * ЧТО НАШЛОСЬ ВМЕСТО ЭТОГО. Команды города не были ничем ограничены по месту. Изменённый
 * клиент мог из подземелья продать лут, перековать вещь, распределить очки и — главное —
 * открыть общий сундук и переложить туда добычу. Последнее это не мелочь: смысл забега
 * в том, что добытое надо ДОНЕСТИ до города, а сундук посреди этажа обнуляет риск смерти
 * и заодно даёт удобную дорожку для мула.
 *
 * Нарушение не банит и не рвёт соединение: считаем и отвечаем отказом. Бан по одному сигналу
 * — это ложные срабатывания на своих же игроках (правило Ф3.3).
 */

/** Где команду разрешено выполнять. */
export type CmdScope = 'town' | 'any';

/**
 * Место каждой команды.
 *
 * ГРАНИЦА ПРОВЕДЕНА ПО ТОМУ, ЧТО КЛИЕНТ И ТАК ЗАПРЕЩАЕТ. Лавка, кузница и сундук открываются
 * только подходом к объекту города (`interactables`, радиус 40) — значит честный игрок туда
 * из подземелья не попадает никогда, и серверный запрет ему не мешает. А вот дерево скилов,
 * мастерство и журнал квестов открываются горячей клавишей где угодно: запрети мы их вне
 * города — сломали бы обычную игру тому, кто поднял уровень на этаже.
 *
 * То есть сервер здесь не вводит новое правило, а начинает СОБЛЮДАТЬ уже существующее.
 * Если правила изменятся (например «квесты сдаются только у доски»), менять надо эту карту,
 * а не разбрасывать проверки по обработчикам.
 */
const SCOPE: Record<TownCommand['cmd'], CmdScope> = {
  // Только город: за ними стоят объекты города.
  buy: 'town',
  sell: 'town',
  forgeUpgrade: 'town',
  forgeReroll: 'town',
  forgeSalvage: 'town',
  stashOpen: 'town',
  stashMove: 'town',
  // Разбор НА МЕСТЕ — смысл именно в том, чтобы не возвращаться в город (выход меньше, docs/ECONOMY.md ч3).
  salvage: 'any',
  // Везде: панели открываются горячей клавишей, запрет ломал бы честного игрока.
  respec: 'any',
  respecPassives: 'any',
  respecSkills: 'any',
  allocPassive: 'any',
  allocSkill: 'any',
  socketInsert: 'any',
  socketClear: 'any',
  acceptQuest: 'any',
  turnInQuest: 'any',
  equip: 'any',
  unequip: 'any',
  allocAttr: 'any',
  moveBelt: 'any',
  moveItem: 'any',
  bind: 'any',
  drop: 'any',
  pickup: 'any',
  useConsumable: 'any',
};

/** Разрешена ли команда в этой области. Неизвестная команда считается городской (строже). */
export function cmdAllowedIn(cmd: TownCommand['cmd'], area: 'town' | 'dungeon' | 'arena'): boolean {
  return (SCOPE[cmd] ?? 'town') === 'any' || area === 'town';
}

/**
 * Дедупликация команд по номеру (Ф2.5).
 *
 * Клиент нумерует команды. При обрыве связи он не знает, дошла ли последняя, и честный
 * клиент её повторит — а повтор «купить» это лишняя вещь за лишнее золото. Помним последние
 * номера и молча пропускаем уже выполненные.
 *
 * Окно намеренно маленькое: команды идут редко (это не ввод), а хранить историю за всю
 * сессию незачем — повтор случается сразу за оригиналом, а не через час.
 */
export class CommandDedup {
  private readonly seen = new Set<number>();
  private readonly order: number[] = [];
  constructor(private readonly limit = 64) {}

  /** true — команду надо выполнить; false — это повтор уже выполненной. */
  accept(id: number | undefined): boolean {
    // Клиент без нумерации (старая вкладка) обслуживается как раньше: лучше выполнить,
    // чем отказать живому игроку из-за отсутствия поля.
    if (id == null || !Number.isFinite(id)) return true;
    if (this.seen.has(id)) return false;
    this.seen.add(id);
    this.order.push(id);
    if (this.order.length > this.limit) this.seen.delete(this.order.shift()!);
    return true;
  }
}
