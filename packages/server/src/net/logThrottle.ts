/**
 * ⭐ R17-06: ГЛУШИТЕЛЬ ЛОГА — «НЕ ЧАЩЕ РАЗА В `ms`, С ЧИСЛОМ ПРОМОЛЧАННЫХ» (сбои записи сейва и свода забега, кадры с исключением, HTTP 500,
 * отказы маршрутизации гейтвея, шум команд игрока): поток одинаковых строк не топит лог.
 *
 * СРОК — ПО ЧАСАМ ПРОЦЕССА (`performance.now`, как бакеты частоты R3-15, таймеры комнат, аренда и бюджет слива R15-06, R16-06). Раньше каждый
 * из семи глушителей мерил его настенными (`Date.now() - lastAt`): шаг часов НАЗАД на S секунд (chrony makestep, откат снимка ВМ, ручная
 * правка) делал разность отрицательной, и S секунд подряд строки только считались промолчанными — час тишины в логе ровно тогда, когда по
 * нему разбирают инцидент с часами (и сомнение в аренде R15-06). Настенные часы остаются только у отметок, уходящих из процесса.
 */
export interface LogThrottle {
  /**
   * Строка сейчас — в лог или промолчана. В лог — хвост строки о промолчанных с прошлой («» — не было, иначе « (и ещё N с прошлого
   * сообщения)»); промолчана — `null` (и она в счёте).
   */
  pass(): string | null;
}

export function logThrottle(ms = 10_000): LogThrottle {
  let at = -Infinity;
  let muted = 0;
  return {
    pass(): string | null {
      const now = performance.now();
      if (now - at < ms) { muted++; return null; }
      const tail = muted ? ` (и ещё ${muted} с прошлого сообщения)` : '';
      at = now; muted = 0;
      return tail;
    },
  };
}
