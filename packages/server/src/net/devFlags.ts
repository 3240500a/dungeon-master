/**
 * ФЛАГИ РАЗРАБОТЧИКА — ЧИСТЫЕ РЕШЕНИЯ ПО ОКРУЖЕНИЮ ПРОЦЕССА.
 *
 * Вынесено из `room.ts` по той же причине, что `adminAccess.ts` из `index.ts`: решение «включён ли
 * флаг» обязано проверяться тестом без комнаты и базы. Окружение передаётся явно, а не читается
 * из `process.env` внутри, — тогда тест не трогает глобальное состояние процесса.
 */

type Env = Readonly<Record<string, string | undefined>>;

/**
 * Боевой ли процесс. Признак на весь сервер один — `NODE_ENV=production` (он же закрывает dev-роуты,
 * включает кэш ассетов и выключает наблюдатель файлов конфига, `index.ts`). Здесь сравнение терпимее
 * к написанию («Production», пробелы): ошибка в эту сторону лишь выключает флаг, а не открывает его.
 */
export const isProduction = (env: Env): boolean => (env.NODE_ENV ?? '').trim().toLowerCase() === 'production';

/**
 * D1: `DM_CRAFT_FULL_JOURNAL=1` — ворота журнала кузнеца открыты ВСЕМ игрокам (для проверок ковки
 * на стенде; в базу журнал уходит своим). ⚠ В продакшене флаг ИГНОРИРУЕТСЯ: забытый в окружении
 * боевого сервера, он раздал бы каталог ковки даром. Включает только ровно «1».
 */
export const craftFullJournalOn = (env: Env): boolean => env.DM_CRAFT_FULL_JOURNAL === '1' && !isProduction(env);

/**
 * Строка для лога при старте процесса: null — флаг не задан. Задан — громко в обоих случаях: на стенде
 * «ворота открыты», в продакшене «проигнорирован», чтобы забытый флаг был виден с первой секунды.
 */
export function craftFullJournalNotice(env: Env): string | null {
  if (env.DM_CRAFT_FULL_JOURNAL !== '1') return null;
  return isProduction(env)
    ? 'DM_CRAFT_FULL_JOURNAL=1 ПРОИГНОРИРОВАН: NODE_ENV=production — ворота журнала кузнеца у всех свои. Уберите флаг из окружения'
    : 'DM_CRAFT_FULL_JOURNAL=1 — ворота журнала кузнеца ОТКРЫТЫ для всех: только для стенда';
}
