/**
 * Аварийный выключатель для нагрузочного стенда: сотня ботов идёт с одного адреса и упирается
 * в лимит регистрации раньше, чем начнётся замер. Включается ТОЛЬКО явной переменной окружения,
 * которую ставит `loadtest/probe.ts`; в проде её не бывает, и при её появлении сервер шумит.
 */
const DISABLED = process.env.DM_RATELIMIT === 'off';
if (DISABLED) console.warn('[rateLimit] ЛИМИТЫ ЧАСТОТЫ ВЫКЛЮЧЕНЫ (DM_RATELIMIT=off) — только для нагрузочного стенда');

interface Bucket { tokens: number; at: number; }

/**
 * ⭐ R3-15: ВРЕМЯ БАКЕТОВ — МОНОТОННОЕ. Раньше по умолчанию брались настенные часы (`Date.now`), а прошедшее время не
 * ограничивалось снизу: шаг часов назад (chrony makestep, миграция или снимок ВМ, ручная правка) давал ОТРИЦАТЕЛЬНОЕ
 * «прошло» и списывал токены. Шаг на 1,5–2 с опустошал бакет потолка кадров у каждого играющего — и нода разом рвала
 * все соединения кодом 4008, а лимиты команд отказывали, пока часы не догонят. `performance.now` назад не ходит; а
 * время, переданное вызывающим «из прошлого», считается нулём прошедших секунд (см. `take`).
 */
const monotonicMs = (): number => performance.now();

export class RateLimiter {
  private readonly buckets = new Map<string, Bucket>();
  /**
   * Ноль, а не `Date.now()`: время приходит от вызывающего (в тестах — искусственное), и брать
   * старт из настенных часов значит сравнивать две разные шкалы. Первый вызов просто подметёт
   * пустую карту и задаст точку отсчёта.
   */
  private lastSweep = 0;

  /**
   * @param capacity сколько запросов подряд разрешено «в всплеске»
   * @param refillPerSec сколько токенов возвращается в секунду (средний допустимый поток)
   * @param idleMs через сколько простоя запись о ключе выбрасывается (чтобы карта не росла)
   */
  constructor(
    private readonly capacity: number,
    private readonly refillPerSec: number,
    private readonly idleMs = 10 * 60_000,
  ) {}

  /** Списать один токен. `false` — лимит исчерпан, запрос надо отклонить. */
  take(key: string, now = monotonicMs()): boolean {
    if (DISABLED) return true;
    this.sweep(now);
    let b = this.buckets.get(key);
    if (!b) { b = { tokens: this.capacity, at: now }; this.buckets.set(key, b); }
    // R3-15: момент раньше уже виденного — ноль прошедших секунд, а не долг; и точка отсчёта назад не уезжает.
    b.tokens = Math.min(this.capacity, b.tokens + (Math.max(0, now - b.at) / 1000) * this.refillPerSec);
    b.at = Math.max(b.at, now);
    if (b.tokens < 1) return false;
    b.tokens -= 1;
    return true;
  }

  /**
   * Есть ли токен — БЕЗ списания (R4-18: исчерпанный лимит промахов кода закрывает и попадания, иначе ответ «вошёл» против
   * «лимит» оставался бы подсказкой перебору).
   */
  peek(key: string, now = monotonicMs()): boolean {
    if (DISABLED) return true;
    const b = this.buckets.get(key);
    if (!b) return true;
    return Math.min(this.capacity, b.tokens + (Math.max(0, now - b.at) / 1000) * this.refillPerSec) >= 1;
  }

  /** Сколько секунд ждать до следующего разрешённого запроса — для заголовка Retry-After. */
  retryAfterSec(key: string, now = monotonicMs()): number {
    const b = this.buckets.get(key);
    if (!b || b.tokens >= 1) return 0;
    return Math.ceil((1 - b.tokens) / this.refillPerSec);
  }

  /** Забыть ключ (например, при успешном входе — чтобы не наказывать за прошлые опечатки). */
  reset(key: string): void { this.buckets.delete(key); }

  /**
   * ⭐ R9-10: вернуть ОДИН токен, списанный этим же запросом (`take` до дорогой работы, а итог оказался честным), — не выше
   * ёмкости. В отличие от `reset` прошлые списания остаются: верный пароль своего аккаунта не стирает неудачи адреса с чужими.
   */
  refund(key: string): void {
    const b = this.buckets.get(key);
    if (b) b.tokens = Math.min(this.capacity, b.tokens + 1);
  }

  get size(): number { return this.buckets.size; }

  /** Периодическая чистка простаивающих ключей: карта не должна расти вечно. */
  private sweep(now: number): void {
    if (now - this.lastSweep < 60_000) return;
    this.lastSweep = now;
    for (const [k, b] of this.buckets) if (now - b.at > this.idleMs) this.buckets.delete(k);
  }
}

/**
 * ⭐ R11-01: во сколько раз шире потолок каждой следующей ступени сети IPv6 (/64, /56, /48; `netTiers`) — и бакетов частоты
 * (`NetLimiter`), и суточного потолка аккаунтов. Абонент получает /64, дом — чаще /56, туннель (Hurricane Electric) бесплатно
 * отдаёт /48: 256 и 65 536 сетей /64. Ступень шире — потолок шире, но один на всю ступень.
 */
export const NET_WIDEN: readonly number[] = [1, 4, 16];

/**
 * ⭐ R11-01: КЛЮЧИ СТУПЕНЕЙ СЕТИ по ключу /64 (`ipBucket`, с приставкой вида `ip:` или без): /64, /56, /48. Не IPv6 (IPv4, петля,
 * ключ соединения, ник) — одна ступень, сам ключ.
 */
export function netTiers(key: string): string[] {
  const m = /^((?:[a-z]+:)?)([0-9a-f]{1,4}):([0-9a-f]{1,4}):([0-9a-f]{1,4}):([0-9a-f]{1,4})::\/64$/.exec(key);
  if (!m) return [key];
  const [, pre, a, b, c, d] = m;
  return [key, `${pre}${a}:${b}:${c}:${(parseInt(d!, 16) & 0xff00).toString(16)}::/56`, `${pre}${a}:${b}:${c}::/48`];
}

/**
 * ⭐ R11-01: ЛИМИТ СЕТИ АДРЕСА — СТУПЕНЯМИ. Ключ — сеть /64 (`ipBucket`, R5-25), но списание идёт и с её /56, и с её /48, у каждой
 * ступени свой бакет с потолком и скоростью шире в `NET_WIDEN` раз; не хватает на любой ступени — отказ, и не списано ничего.
 * Раньше ключом была только /64: абонент с домашней /56 менял /64 и получал 256 независимых бакетов входа, регистрации, поиска
 * ника, сессий, лобби и промахов кода (с бесплатной /48 — 65 536), и суточный потолок аккаунтов с них же — 1280 и 327 680 в сутки.
 * IPv4 и прочие ключи — одна ступень, как `RateLimiter`. Вид вызовов тот же, что у `RateLimiter`: зовущие ручки не меняются.
 */
export class NetLimiter {
  private readonly tiers: RateLimiter[];
  constructor(capacity: number, refillPerSec: number, idleMs?: number) {
    this.tiers = NET_WIDEN.map((k) => new RateLimiter(capacity * k, refillPerSec * k, idleMs));
  }
  take(key: string, now = monotonicMs()): boolean {
    if (DISABLED) return true;
    const keys = netTiers(key);
    if (!keys.every((k, i) => this.tiers[i]!.peek(k, now))) return false;
    keys.forEach((k, i) => this.tiers[i]!.take(k, now));
    return true;
  }
  peek(key: string, now = monotonicMs()): boolean {
    return netTiers(key).every((k, i) => this.tiers[i]!.peek(k, now));
  }
  retryAfterSec(key: string, now = monotonicMs()): number {
    return Math.max(0, ...netTiers(key).map((k, i) => this.tiers[i]!.retryAfterSec(k, now)));
  }
  refund(key: string): void { netTiers(key).forEach((k, i) => this.tiers[i]!.refund(k)); }
  reset(key: string): void { netTiers(key).forEach((k, i) => this.tiers[i]!.reset(k)); }
  get size(): number { return this.tiers.reduce((n, t) => n + t.size, 0); }
}

