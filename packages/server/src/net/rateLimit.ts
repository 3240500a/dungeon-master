/**
 * R3-07: кому ещё, кроме петли, верить в `X-Forwarded-For` — `DM_TRUST_PROXY`, адреса через запятую (балансировщик
 * или прокси на ДРУГОЙ машине). Петле верим всегда: это свой прокси uWS перед express и обратный прокси на той же
 * машине (Caddy, nginx) — чужой туда не встанет.
 */
const TRUSTED_PROXIES: ReadonlySet<string> = new Set((process.env.DM_TRUST_PROXY ?? '').split(',').map(normIp).filter(Boolean));

/** Адрес в одной записи: IPv4 внутри IPv6 (`::ffff:1.2.3.4`) — как IPv4, иначе у одного клиента было бы два ключа лимитов. */
function normIp(a: string): string {
  const s = a.trim();
  return /^::ffff:\d{1,3}(?:\.\d{1,3}){3}$/i.test(s) ? s.slice(7) : s;
}

/** Группы IPv6-адреса полной записью (восемь), IPv4 в хвосте — двумя группами; не адрес — `undefined`. */
function ipv6Groups(a: string): string[] | undefined {
  const tail4 = (g: string[]): string[] => {
    const last = g[g.length - 1];
    if (!last?.includes('.')) return g;
    const o = last.split('.').map(Number);
    if (o.length !== 4 || !o.every((n) => Number.isInteger(n) && n >= 0 && n <= 255)) return g;
    return [...g.slice(0, -1), ((o[0]! << 8) | o[1]!).toString(16), ((o[2]! << 8) | o[3]!).toString(16)];
  };
  const halves = a.split('::');
  if (halves.length > 2) return undefined;
  const head = halves[0] ? halves[0].split(':') : [];
  const tail = tail4(halves.length === 2 && halves[1] ? halves[1].split(':') : []);
  const groups = halves.length === 2 ? [...head, ...Array<string>(Math.max(0, 8 - head.length - tail.length)).fill('0'), ...tail] : tail4(head);
  return groups.length === 8 && groups.every((g) => /^[0-9a-f]{1,4}$/.test(g)) ? groups : undefined;
}

/**
 * ⭐ R5-25: КЛЮЧ ЛИМИТА ПО АДРЕСУ — СЕТЬ, А НЕ АДРЕС. IPv6 — по /64: провайдер выдаёт абоненту целую сеть, и новый адрес на
 * каждую попытку (и каждый сокет) давал новый пустой бакет — лимиты промахов кода, лобби, входа и регистрации не держали
 * никого. IPv4 и петля — как есть.
 */
export function ipBucket(addr: string): string {
  const a = normIp(addr).toLowerCase().replace(/^\[|\]$/g, '').replace(/%.*$/, '');
  if (!a.includes(':') || isLoopback(a)) return a;
  const g = ipv6Groups(a);
  return g ? `${g.slice(0, 4).map((x) => parseInt(x, 16).toString(16)).join(':')}::/64` : a;
}

/**
 * ⭐ R3-07: АДРЕС КЛИЕНТА — ключ лимитов входа и регистрации и суточного потолка аккаунтов с адреса.
 *
 * Раньше брался ПЕРВЫЙ адрес `X-Forwarded-For`, от кого бы заголовок ни пришёл, а прокси uWS пропускал заголовок
 * клиента насквозь: новый `X-Forwarded-For: 10.0.<n>.<m>` на каждую попытку — новый пустой бакет. Перебор пароля без
 * предела (и по scrypt на каждую попытку), регистрации и фермы аккаунтов — мимо лимитов. За nginx
 * (`$proxy_add_x_forwarded_for`) первым тоже стоит то, что прислал сам клиент.
 *
 * Теперь цепочка читается СПРАВА: собеседник сокета, за ним — адреса заголовка от последнего к первому. Пока
 * текущий адрес — доверенный прокси (петля или `DM_TRUST_PROXY`), шаг влево: этот адрес дописал прокси, которому мы
 * верим. Первый недоверенный — клиент; всё левее мог написать он сам. Собеседник не прокси — заголовок не читается.
 * `trusted` — для тестов.
 */
export function clientIp(
  headers: Record<string, string | string[] | undefined>, peer?: string, trusted: ReadonlySet<string> = TRUSTED_PROXIES,
): string {
  const fwd = headers['x-forwarded-for'];
  const chain = (Array.isArray(fwd) ? fwd.join(',') : fwd ?? '').split(',').map(normIp).filter(Boolean);
  let ip = peer ? normIp(peer) : undefined;
  while (ip && (isLoopback(ip) || trusted.has(ip)) && chain.length) ip = chain.pop();
  return ip || 'unknown';
}
