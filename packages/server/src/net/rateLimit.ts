/**
 * ⭐ R10-04: КЛЮЧИ, ЧЕСТНОСТЬ КОТОРЫХ ПРОЦЕСС УЖЕ ВИДЕЛ, — срок `ttlMs` с последнего подтверждения, не больше `max` (старейшие
 * вытесняются). Не пропуск и не кэш ответа: база спрашивается как прежде (отозванная сессия — 401, удалённый ник — «неверно»); ключ
 * лишь не платит бакет сети адреса, который платят неудачи, — и чужой поток неудач соседа не запирает. Подделать ключ нельзя:
 * сюда попадает только то, что база подтвердила (живая сессия, существующий ник).
 */
export class RecentKeys<V = true> {
  private readonly seen = new Map<string, { until: number; value: V }>();
  constructor(private readonly ttlMs: number, private readonly max: number) {}
  has(key: string, now = monotonicMs()): boolean {
    return this.get(key, now) !== undefined;
  }
  /** ⭐ R11-06: что база подтвердила вместе с ключом (у сессии — её аккаунт); ключа нет или срок вышел — `undefined`. */
  get(key: string, now = monotonicMs()): V | undefined {
    const e = this.seen.get(key);
    if (e === undefined) return undefined;
    if (e.until > now) return e.value;
    this.seen.delete(key);
    return undefined;
  }
  /** Подтверждено сейчас — срок заново, ключ — в хвост очереди вытеснения. */
  add(key: string, value: V = true as unknown as V, now = monotonicMs()): void {
    this.seen.delete(key);
    this.seen.set(key, { until: now + this.ttlMs, value });
    if (this.seen.size > this.max) this.seen.delete(this.seen.keys().next().value!);
  }
  delete(key: string): void { this.seen.delete(key); }
  get size(): number { return this.seen.size; }
}

/**
 * ⭐ R10-04: что процесс знает честным — мимо бакетов сети адреса (см. `RecentKeys`).
 * ⭐ R11-05: и то, что он знает С САМОГО СТАРТА: живые сессии и все ники базы гейтвей (и одиночный процесс) берёт при запуске
 * (`primeKnown`). Раньше знакомым становилось только предъявленное этому процессу, и после рестарта или деплоя (а сессии — и после
 * 12 ч простоя, ники — после суток) каждый честный токен и ник платил общий бакет адреса: поток чужих токенов или ников за общим
 * NAT запирал соседям ростер, маршрут к ноде и вход — а стать знакомым, не пройдя этот бакет, нельзя.
 */
export const known = {
  /**
   * Токены (отпечатком, `sessionKey`), чью сессию база подтвердила этому процессу: вход, регистрация, живой запрос, старт процесса.
   * Значение — аккаунт сессии (R11-06: потолок аккаунта списывается ДО базы). Срок — как у сессии (7 дней, продлеваемых входом).
   */
  sessions: new RecentKeys<string>(7 * 24 * 3600_000, 100_000),
  /** Ники (без регистра — как ищет база), которые нашлись в базе: вход, регистрация, старт процесса. Ник не исчезает — срока нет. */
  names: new RecentKeys(Infinity, 200_000),
};

/**
 * ⭐ R11-01: СКОЛЬКО scrypt ПРОЦЕСС ДЕРЖИТ СРАЗУ (идут и ждут своей очереди в `auth/password.ts`). Больше — «Сервер занят» (503) без
 * scrypt: пул libuv общий на процесс, и очередь из сотен сверок не должна копиться, даже если бюджет пропустил.
 */
const SCRYPT_INFLIGHT_MAX = 64;
const SCRYPT_KEY = 'all';
let scryptInflight = 0;

/**
 * ⭐ R11-01: ДОПУСК К scrypt — общий бюджет процесса (`limits.scrypt`) и потолок очереди. `admit` — до scrypt, синхронно (между
 * допуском и началом scrypt ожиданий нет); `done` — после, в любом исходе. `priority` — вход с токеном устройства: бюджет не
 * платит (его держат потолки ника), потолок очереди — да.
 */
export const scryptGate = {
  admit(priority = false): boolean {
    if (DISABLED) return true;
    if (scryptInflight >= SCRYPT_INFLIGHT_MAX) return false;
    if (!priority && !limits.scrypt.take(SCRYPT_KEY)) return false;
    scryptInflight++;
    return true;
  },
  done(): void { scryptInflight = Math.max(0, scryptInflight - 1); },
  retryAfterSec(): number { return Math.max(1, limits.scrypt.retryAfterSec(SCRYPT_KEY)); },
};

/**
 * R3-07: кому ещё, кроме петли, верить в `X-Forwarded-For` — `DM_TRUST_PROXY`, адреса через запятую (балансировщик
 * или прокси на ДРУГОЙ машине). Петле верим всегда: это свой прокси uWS перед express и обратный прокси на той же
 * машине (Caddy, nginx) — чужой туда не встанет.
 */
const TRUSTED_PROXIES: ReadonlySet<string> = new Set((process.env.DM_TRUST_PROXY ?? '').split(',').map(normIp).filter(Boolean));

/** Адрес в одной записи: IPv4 внутри IPv6 (`::ffff:1.2.3.4`) — как IPv4, иначе у одного клиента было бы два ключа лимитов. */
function normIp(a: string): string {
  const s = a.trim();
  return /^::ffff:\d{1,3}(?:\.\d{1,3}){3}$/i.test(s) ? s.slice(7) : s;
}

/** Группы IPv6-адреса полной записью (восемь), IPv4 в хвосте — двумя группами; не адрес — `undefined`. */
function ipv6Groups(a: string): string[] | undefined {
  const tail4 = (g: string[]): string[] => {
    const last = g[g.length - 1];
    if (!last?.includes('.')) return g;
    const o = last.split('.').map(Number);
    if (o.length !== 4 || !o.every((n) => Number.isInteger(n) && n >= 0 && n <= 255)) return g;
    return [...g.slice(0, -1), ((o[0]! << 8) | o[1]!).toString(16), ((o[2]! << 8) | o[3]!).toString(16)];
  };
  const halves = a.split('::');
  if (halves.length > 2) return undefined;
  const head = halves[0] ? halves[0].split(':') : [];
  const tail = tail4(halves.length === 2 && halves[1] ? halves[1].split(':') : []);
  const groups = halves.length === 2 ? [...head, ...Array<string>(Math.max(0, 8 - head.length - tail.length)).fill('0'), ...tail] : tail4(head);
  return groups.length === 8 && groups.every((g) => /^[0-9a-f]{1,4}$/.test(g)) ? groups : undefined;
}

/**
 * ⭐ R5-25: КЛЮЧ ЛИМИТА ПО АДРЕСУ — СЕТЬ, А НЕ АДРЕС. IPv6 — по /64: провайдер выдаёт абоненту целую сеть, и новый адрес на
 * каждую попытку (и каждый сокет) давал новый пустой бакет — лимиты промахов кода, лобби, входа и регистрации не держали
 * никого. IPv4 и петля — как есть. ⭐ R11-01: /64 — только первая ступень: лимиты сети списывают и её /56, и /48 (`NetLimiter`).
 */
export function ipBucket(addr: string): string {
  const a = normIp(addr).toLowerCase().replace(/^\[|\]$/g, '').replace(/%.*$/, '');
  if (!a.includes(':') || isLoopback(a)) return a;
  const g = ipv6Groups(a);
  return g ? `${g.slice(0, 4).map((x) => parseInt(x, 16).toString(16)).join(':')}::/64` : a;
}

/**
 * ⭐ R3-07: АДРЕС КЛИЕНТА — ключ лимитов входа и регистрации и суточного потолка аккаунтов с адреса.
 *
 * Раньше брался ПЕРВЫЙ адрес `X-Forwarded-For`, от кого бы заголовок ни пришёл, а прокси uWS пропускал заголовок
 * клиента насквозь: новый `X-Forwarded-For: 10.0.<n>.<m>` на каждую попытку — новый пустой бакет. Перебор пароля без
 * предела (и по scrypt на каждую попытку), регистрации и фермы аккаунтов — мимо лимитов. За nginx
 * (`$proxy_add_x_forwarded_for`) первым тоже стоит то, что прислал сам клиент.
 *
 * Теперь цепочка читается СПРАВА: собеседник сокета, за ним — адреса заголовка от последнего к первому. Пока
 * текущий адрес — доверенный прокси (петля или `DM_TRUST_PROXY`), шаг влево: этот адрес дописал прокси, которому мы
 * верим. Первый недоверенный — клиент; всё левее мог написать он сам. Собеседник не прокси — заголовок не читается.
 * `trusted` — для тестов.
 */
export function clientIp(
  headers: Record<string, string | string[] | undefined>, peer?: string, trusted: ReadonlySet<string> = TRUSTED_PROXIES,
): string {
  const fwd = headers['x-forwarded-for'];
  const chain = (Array.isArray(fwd) ? fwd.join(',') : fwd ?? '').split(',').map(normIp).filter(Boolean);
  let ip = peer ? normIp(peer) : undefined;
  while (ip && (isLoopback(ip) || trusted.has(ip)) && chain.length) ip = chain.pop();
  return ip || 'unknown';
}
