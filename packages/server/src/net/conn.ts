/**
 * Соединение игрока глазами игровой логики (Ф1.6).
 *
 * До этого `Room` и `RoomManager` работали напрямую с `WebSocket` из библиотеки `ws`. Замер
 * транспортов (стенд `loadtest`, отдельный бенч) показал, что тот же объём работы на
 * uWebSockets.js стоит процессу заметно меньше — но менять библиотеку в двух тысячах строк
 * игровой логики нельзя. Поэтому логика видит ТОЛЬКО этот интерфейс, а какая под ним
 * библиотека — решает `index.ts` по `DM_WS`.
 *
 * Интерфейс намеренно узкий: ровно то, чем игра пользуется, и ничего сверх.
 *  • тип данных определяет вид кадра: `string` уходит текстом, `Uint8Array` — двоичным;
 *  • от клиента приходят только текстовые кадры (JSON), поэтому `onMessage` отдаёт строку;
 *  • `onClose` зовётся ОДИН раз — и на нормальном закрытии, и на ошибке; ⭐ B3-V2: и на закрытии СЕРВЕРОМ (`close`) — сразу, не
 *    дожидаясь рукопожатия закрытия (у uWS так и было: `end` зовёт обработчик синхронно, у `ws` событие приходит до 30 с спустя);
 *  • ⭐ B3-V1: после `close` (и после закрытия транспортом) кадры клиента в игру не идут — закрытое соединение не действует;
 *  • объект соединения живёт всё соединение и годится ключом `Map`/`WeakMap`.
 */
export interface GameConn {
  /** Можно ли ещё слать. Ложь после закрытия — проверять перед отправкой. */
  readonly open: boolean;
  /** Отправить кадр. Не бросает: закрытое соединение молча игнорируется. */
  send(data: string | Uint8Array): void;
  /** Закрыть соединение с кодом (4001 — вытеснен, 4008 — превышен лимит частоты). Окончательно сразу: `open` — ложь, `onClose` позван. */
  close(code?: number, reason?: string): void;
  /** Подписка на входящие кадры. Зовётся один раз при подключении. */
  onMessage(cb: (raw: string) => void): void;
  /** Подписка на закрытие. Зовётся один раз при подключении. */
  onClose(cb: () => void): void;
  /**
   * Адрес клиента. Нужен телеметрии (Ф3.2): без него не проверить главную сигнатуру
   * ботоводства — пачку аккаунтов, входящих и выходящих синхронно с одного адреса.
   * За прокси адрес игрока стоит в `x-forwarded-for`, поэтому транспорт берёт его оттуда.
   */
  readonly ip: string;
  /**
   * ⭐ R13-08: пропуск маршрута из адреса сокета (`?lp=`, его ставит гейтвей в ответе `/api/route`) — сессия, которую гейтвей уже
   * проверил, на лобби ноды не платит бакет сети адреса (`RoomManager.authOwner`). Нет — как прежде.
   */
  readonly routePass?: string;
}

/** ⭐ R13-08: пропуск маршрута (`lp`) из адреса игрового сокета; кривой и слишком длинный — нет пропуска. */
export function routePassOf(url: string): string | undefined {
  const q = url.indexOf('?');
  if (q < 0 || url.length > 2048) return undefined;
  const v = new URLSearchParams(url.slice(q + 1)).get('lp');
  return v && v.length <= 64 ? v : undefined;
}

/** Что должен уметь транспорт: отдавать новые соединения игре. */
export type ConnHandler = (conn: GameConn) => void;

/**
 * Потолок неотправленного клиенту, байт. Кто не успевает читать — отключается, а не съедает
 * память сервера: подвисший главный поток браузера ведёт себя ровно так, и без потолка он
 * тянет сервер за собой.
 *
 * Порог общий для обоих транспортов: у uWS это `maxBackpressure`, у `ws` — проверка
 * `bufferedAmount` перед отправкой. `DM_MAX_BACKPRESSURE` нужен, чтобы механизм МОЖНО БЫЛО
 * ПРОВЕРИТЬ: на честных 16 МБ медленный клиент набирает потолок больше двадцати минут, и такой
 * тест никто не гоняет.
 */
export const MAX_BACKPRESSURE = Math.max(64 * 1024, Number(process.env.DM_MAX_BACKPRESSURE ?? 16 * 1024 * 1024));

/**
 * ⭐ R2-18: ПОТОЛОК ВХОДЯЩЕГО КАДРА, байт — общий для обоих транспортов. Клиент шлёт только маленькие JSON-кадры
 * (честные — меньше килобайта), всё крупное — повод закрыть соединение ДО разбора. У uWS это `maxPayloadLength`,
 * у `ws` — `maxPayload`: без него `ws` принимал кадр до 100 МБ целиком в память и отдавал в `JSON.parse` на главном
 * потоке — без входа, по кадру на сокет, пока тики всех комнат стоят.
 * ⭐ R6-05: 16 КБ, а не 64: самый большой честный кадр — спуск с 32 модификаторами алтаря — меньше 5 КБ даже кириллицей
 * (сторож — `roomManager.r6server.test.ts`), а всё, что потолок пропустил, разбирается на главном потоке. Вложенность до
 * разбора режет `roomManager` (`FRAME_BRACKETS_MAX`), размер ввода — тоже (`INPUT_FRAME_MAX`).
 */
export const MAX_FRAME_BYTES = 16 * 1024;

/**
 * ⭐ R4-13: ПУТЬ ИГРОВОГО СОКЕТА — `/ws` и `/ws/<номер>`, общий для обоих транспортов. За обратным прокси по путям
 * (DEPLOY.md §3a, вариант А) гейтвей отдаёт клиенту `wss://домен/ws/<i>`, а прокси (Caddy `reverse_proxy /ws/0 …`, как и
 * nginx с `proxy_pass` без пути) пересылает путь КАК ЕСТЬ. Нода слушала ровно `/ws`: `/ws/0` получал 404 (uWS) или 400
 * (`ws`), и кластер по документации был недоступен. Номер нода не сверяет — к ней ведёт прокси, а не путь.
 */
export function isGameWsPath(url: string): boolean {
  const q = url.indexOf('?');
  return /^\/ws(?:\/\d{1,4})?$/.test(q < 0 ? url : url.slice(0, q));
}
