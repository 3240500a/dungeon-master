import { NODE_DEAD_SEC } from './claimRule.js';

/**
 * ⭐ ENV1: АРЕНДА НОДЫ — сколько процесс ещё вправе держать своих героев и забеги, не подтвердив это реестру.
 *
 * Реестр отдаёт героев и забеги замолчавшей ноды другой через `NODE_DEAD_SEC` после её последнего удара сердца (R7-09, `claimRule.ts`) — так
 * задумано: иначе упавшая нода запирала бы своих героев навсегда. Но сама замолчавшая нода об этом не знала: пауза процесса (заморозка
 * машины, цикл событий, стоявший минуты), раздел с базой или с реестром — и она играла дальше. Её комнаты тикали и исполняли команды,
 * живые сессии писали, а тот же герой уже входил на соседней ноде, тот же забег шёл во второй комнате (a, b), сессия здесь становилась
 * зомби. Снимались её копии, только когда удар сердца снова доходил до реестра (`fenceLost`), а о потерянных забегах — строка в лог.
 *
 * Теперь нода держит АРЕНДУ: удар сердца, дошедший до реестра, продлевает её до `NODE_DEAD_SEC − LEASE_MARGIN_SEC` от момента ОТПРАВКИ
 * (строка ноды в реестре помечена не раньше — значит и отдать её героев реестр не может раньше конца аренды плюс запас). Интервалы меряются
 * одними часами процесса — постоянный сдвиг часов с базой в счёт не идёт; запас — на скачок часов и задержку удара. Кончается аренда —
 * нода себя отгораживает: ни тика, ни команды, ни записи (`Room`, `RoomManager`: `leaseLost`), даже если процесс проснулся после заморозки
 * позже срока и таймеры ещё не дошли до выхода, и выход без записи (`node.ts`). ⭐ R16 C-05: удар, дошедший ДО конца аренды, её продлевает —
 * и нода играет дальше (простой базы короче аренды не стоит ни забегов, ни сессий).
 *
 * Процесс вне кластера (одиночная роль, тесты) аренды не держит: `leaseLeft` — бесконечность, ничего не запрещено. У каждого процесса
 * (экземпляра графа модулей) аренда своя.
 *
 * ⭐ R15-06: СРОК АРЕНДЫ — ПО МОНОТОННЫМ ЧАСАМ ПРОЦЕССА (`performance.now`, как бакеты частоты R3-15). Раньше и отправка удара, и «сейчас»
 * брались настенными (`Date.now`): шаг часов вперёд на ~110 с (chrony makestep, миграция ВМ, ручная правка) кончал аренду разом — каждая
 * нода кластера выходила «без записи», хотя база и реестр были целы (недописанный прогресс терялся, а старт снимал забеги); шаг НАЗАД на
 * S секунд продлевал её на S — и она переживала `NODE_DEAD_SEC`, после которого реестр уже отдаёт её героев другой. Настенные часы теперь
 * только СОМНЕВАЮТСЯ (`leaseDoubted`): по ним аренда кончилась, а по часам процесса — нет. Так бывает и при шаге часов, и при простое машины,
 * который видят лишь настенные (ВМ на паузе: монотонные часы гостя стоят, а настенные потом догоняет chrony), — и отличить их может только
 * реестр. Нода в сомнении отгорожена, как без аренды (`leaseLost`), и тут же шлёт удар (`node.ts`, `checkLease`): дошёл — реестр её держит
 * (кого за время простоя отдали другой ноде, снимает тот же удар: `fenceLost`, `runsLost`), аренда продлена; не дошёл — выход без записи.
 *
 * ⭐ R16-02: «ДОШЁЛ — ЗНАЧИТ, РЕЕСТР ЕЁ ДЕРЖИТ» — НЕВЕРНО ПОСЛЕ ПРОСТОЯ ДОЛЬШЕ `NODE_DEAD_SEC`. За такой простой другая нода успевала не только
 * взять её героя и забег, но и ОТПУСТИТЬ (доиграл, ушёл из города), а уборка — снять строку ноды: продление вставляло закрепления и держание
 * забегов заново, за ней, — снимать ударом было уже нечего, и гейтвей вёл героя к её устаревшей копии. Поэтому каждый удар ноды с арендой
 * сперва спрашивает реестр, давно ли тот её видел, — по часам БАЗЫ (`nodeBeatAge`): дольше аренды или строки нет — выход без записи, как с
 * концом аренды. Это ловит и простой, при котором стояли все часы гостя (сомнения нет вовсе), — на первом же ударе по расписанию.
 */

/** Запас аренды до срока смерти ноды в реестре: скачок часов, задержка удара, выход процесса. */
export const LEASE_MARGIN_SEC = 8;
/** Аренда от отправки дошедшего удара сердца, мс. */
export const LEASE_MS = (NODE_DEAD_SEC - LEASE_MARGIN_SEC) * 1000;

/** ⭐ R15-06: часы срока аренды — монотонные часы процесса. */
const monoMs = (): number => performance.now();

/** Нода держит аренду (дошёл первый удар). */
let held = false;
/** Когда отправлен последний удар сердца, дошедший до реестра: по часам процесса и по настенным. */
let beatSentMono = 0;
let beatSentAt = 0;

/**
 * Удар сердца, отправленный в `sentMono` (часы процесса; `sentAt` — настенные в тот же миг), дошёл до реестра — аренда продлена. Держать
 * аренду начинает первый такой удар. Последний — по часам процесса: шаг настенных назад его не отменяет, а их отметку сдвигает вместе с ним.
 */
export function leaseBeat(sentAt: number, sentMono = monoMs()): void {
  if (held && sentMono <= beatSentMono) return;
  held = true;
  beatSentMono = sentMono;
  beatSentAt = sentAt;
}

/** Сколько аренды осталось по часам процесса, мс (может быть ≤ 0); процесс аренды не держит — бесконечность. */
export function leaseLeft(now = monoMs()): number {
  return held ? beatSentMono + LEASE_MS - now : Infinity;
}

/**
 * ⭐ R15-06: аренда ПОД СОМНЕНИЕМ — по настенным часам она кончилась, а по часам процесса ещё идёт (шаг часов вперёд или простой машины,
 * который видят лишь настенные). Решает реестр: нода шлёт удар (`node.ts`, `checkLease`), до его ответа — отгорожена (`leaseLost`).
 */
export function leaseDoubted(wall = Date.now()): boolean {
  return held && leaseLeft() > 0 && beatSentAt + LEASE_MS - wall <= 0;
}

/** Аренда кончилась (или под сомнением, R15-06): реестр вправе отдать героев и забеги ноды другой — ни тика, ни команды, ни записи. */
export function leaseLost(): boolean {
  return leaseLeft() <= 0 || leaseDoubted();
}
