/**
 * ⭐ R8-06: ПРАВИЛО «ГЕРОЯ ДЕРЖИТ НОДА» — ОДНО на вход (`registry.claimForJoin`) и сброс забегов на старте ноды
 * (`db.clearAllRuns`). Раньше у сброса было своё, короче: он щадил только героев ноды, ударившей сердцем за 10 с, а вход признаёт
 * ноду живой `NODE_DEAD_SEC`. База легла на 10–120 с, нода стартовала в этом окне — и снимала забег и поднимала версию героям,
 * которых вход ещё отдавал замолчавшей ноде: её живые сессии потом получали отказ по версии (массовый 4009), а недописанная
 * прощальная копия — «конфликт», то есть «записано», и пропадала молча (вещь, уже поднятая соседом по аккаунту, — у двоих).
 *
 * Модуль без импортов: его читают и реестр кластера, и слой базы, а цикла импортов тут быть не может.
 */

/**
 * ⭐ R7-09: сколько нода может молчать, прежде чем её ГЕРОЕВ можно забрать (`claimForJoin`). Живость для маршрута
 * (`NODE_STALE_SEC`) — не то же, что смерть: база легла на 10 с и дольше (рестарт, переключение) — сердцебиение не проходило,
 * а в памяти ноды жили копии, которые база не приняла (прощальная запись соседа по аккаунту уже легла). Забери их закрепление
 * другая нода в окне «база встала, нода ещё не ударила» — она прочла бы сейв ДО копии, а нода потом забыла бы копию (R6-06):
 * вещь у двоих. Срок — с запасом над восстановлением базы; упавшую ноду супервизор поднимает с тем же id, и своих героев она
 * берёт сразу, так что ждут только герои ноды, снятой насовсем. Уборка реестра (`sweepNodes`) раньше срока ноду не сносит.
 */
export const NODE_DEAD_SEC = 120;

/**
 * ⭐ R2-17: сколько закрепление ВХОДА держит героя без продления. Нода продлевает своих (живых, в грейсе, с
 * прощальной записью в полёте) каждые две секунды — `live_at`; полминуты без продления значат, что за
 * закреплением никакой сессии нет (вход сорвался, «Завершить» без сессии, снятие не нашло строку). Закрепление
 * маршрута (гейтвей, `claimChar`) `live_at` не ставит вовсе: оно — подсказка, куда вести, а не живой герой.
 */
export const CLAIM_IDLE_SEC = 30;

/**
 * SQL-условие «закрепление `claim` держит нода `node`» (имена — псевдонимы строк `char_claims` и `cluster_nodes` в запросе):
 * нода молчит не дольше `NODE_DEAD_SEC` и продлевала героя не раньше чем за `CLAIM_IDLE_SEC` до своего последнего удара (нода
 * продлевает своих перед ударом, `node.ts`; молчит — удары не идут, и признак не стареет, сколько бы база ни лежала).
 * `deadParam`/`idleParam` — номера параметров запроса со значениями `claimHeldParams()`.
 */
export function claimHeldSql(claim: string, node: string, deadParam: number, idleParam: number): string {
  return `${node}.beat_at > now() - ($${deadParam} || ' seconds')::interval`
    + ` AND ${claim}.live_at > ${node}.beat_at - ($${idleParam} || ' seconds')::interval`;
}

/** Значения параметров `claimHeldSql` — по порядку: срок смерти ноды, срок простоя закрепления. */
export function claimHeldParams(): [string, string] {
  return [String(NODE_DEAD_SEC), String(CLAIM_IDLE_SEC)];
}
