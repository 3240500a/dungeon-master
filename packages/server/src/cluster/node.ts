import { monitorEventLoopDelay } from 'node:perf_hooks';
import { counters, counterSnapshot, readGauges } from '../net/metrics.js';
import { heartbeat, releaseNode, touchClaims, touchRuns, initClusterSchema, nodeBeatAge } from './registry.js';
import { leaseBeat, leaseLeft, leaseDoubted, LEASE_MS } from './lease.js';

/**
 * Игровая нода (Ф4.3): процесс, который занимается ТОЛЬКО комнатами.
 *
 * Здесь живёт всё, что делает процесс частью кластера: сердцебиение в реестр, продление
 * закреплений своих игроков и корректный уход с деплоя (Ф4.5).
 *
 * ПРО СЛИВ НОДЫ. Просто убить процесс нельзя: у людей внутри идут забеги. Поэтому на SIGTERM
 * нода сперва помечается «сливаемой» — гейтвей перестаёт слать к ней новых, — и только потом
 * дописывает сейвы и выходит. Механизм грейс-реконнекта (он уже был) доводит остальное:
 * игрок вернётся в свою комнату, когда нода поднимется.
 */

const BEAT_MS = 2_000;

let draining = false;
let beat: ReturnType<typeof setInterval> | undefined;
/** Удар сердца вне расписания — объявить слив сразу (R3-12). Есть, пока нода в кластере. */
let beatNow: (() => Promise<void>) | undefined;
/** R4-28: нода снимается из реестра — новых ударов сердца нет, идущие дожидаются (`installNodeShutdown`). */
let stopped = false;
/** R4-28: удары сердца, ещё идущие в базу. */
const sending = new Set<Promise<void>>();
/** Слив ноды установлен (R3-12): выход процесса — только через него. */
let nodeShutdown = false;
/** ⭐ R16 C-05: аренда на исходе (сказано в лог) — дошедший удар её продлит, и нода играет дальше (`checkLease`). */
let leaseLow = false;
/** ⭐ R15-06: аренда под сомнением (настенные часы ушли вперёд) — удар сверки с реестром в пути (`checkLease`). */
let confirming = false;
/** ⭐ ENV1: как часто нода сверяет свою аренду (`lease.ts`), мс. */
const LEASE_CHECK_MS = 1_000;

/** Идёт ли слив: гейтвей это видит и перестаёт присылать новых игроков. */
export function isDraining(): boolean { return draining; }
/**
 * ⭐ R3-12: процессом выходит слив ноды — общий обработчик транспорта (`installShutdown`) уступает ему. Раньше на
 * SIGTERM срабатывали оба, и общий выходил первым — до снятия ноды из реестра и раньше, чем дожидался слив.
 */
export function nodeShutdownInstalled(): boolean { return nodeShutdown; }

/**
 * Подключить процесс к кластеру. `charIds` — те, кого нода держит прямо сейчас: их
 * закрепление продлевается, чтобы игрок при обрыве вернулся именно сюда, к своей комнате.
 * `onLost` (R2-05) — те из них, чьё закрепление уже у ЧУЖОЙ ноды: их копии здесь проиграли.
 * ⭐ V2: `heldRuns` — забеги, которые держат комнаты ноды (ключ, код комнаты): их держание за нодой (`run_locks`) продлевает тот же удар.
 * ⭐ ENV1: `opts.runsLost` — те из них, что реестр числит за другой нодой: комнаты ноды их отпускают (`RoomManager.fenceRuns`), а не только
 * строка в лог (⭐ перепрогон R15: из тех, что нода держит и после ответа продления, — по нынешнему держателю). `opts.lease` — нода держит аренду (`lease.ts`): дошедший удар её продлевает, а на исходе нода себя отгораживает сама
 * (`checkLease`). Роль `single` аренды не держит: отдать её героев некому. ⭐ R15-08: `opts.runsGone` — забеги снимка удара, которые комнаты
 * отпустили, пока шло продление (оно вставляет строку заново): их отпустить снова (`RoomManager.releaseRuns`); ⭐ перепрогон R15 — и те, что
 * взяла другая комната ноды (продление переписало строку на прежнюю): строку — на держателя.
 */
export async function joinCluster(
  nodeId: string, url: string, charIds: () => string[],
  loop: ReturnType<typeof monitorEventLoopDelay>,
  onLost?: (charIds: string[]) => void,
  onGone?: (charIds: string[]) => void,
  heldRuns?: () => { key: string; room: string }[],
  opts: {
    runsLost?: (runs: { key: string; room: string }[]) => void; runsGone?: (runs: { key: string; room: string }[]) => void; lease?: boolean;
  } = {},
): Promise<void> {
  await initClusterSchema();

  let lastTicks = counters.ticks;
  let lastRoomSeconds = counters.roomSeconds;
  let lastAt = Date.now();

  const beatOnce = async (): Promise<void> => {
    if (stopped) return;   // R4-28: нода уже снимается из реестра — её строку и закрепления не возвращаем
    const sentAt = Date.now();   // ⭐ ENV1: аренда — от отправки удара (строка ноды в реестре помечена не раньше)
    const sentMono = performance.now();   // ⭐ R15-06: срок аренды — по часам процесса
    // ⭐ R16-02: СПЕРВА СПРОСИТЬ РЕЕСТР, ДАВНО ЛИ ОН ВИДЕЛ НОДУ, — ПО ЧАСАМ БАЗЫ. Часы процесса простоя машины не видят (ВМ на паузе: монотонные
    // часы гостя стоят, а настенные потом догоняет chrony — или не догоняет никто), и аренда по ним «шла», хотя реестр уже счёл ноду мёртвой
    // (`NODE_DEAD_SEC`): её героя вошедший на соседней ноде доигрывал и отпускал, забег она брала и отпускала, уборка сносила строку ноды — а
    // удар проснувшейся продлевал своих вставкой (закрепление и держание забега вставали заново — за ней), бил сердцем и продлевал аренду.
    // Гейтвей вёл героя к её устаревшей копии в грейсе: «Соло» или истёкший грейс штрафовали его строку за забег, припаркованный на соседней
    // ноде по праву, «Продолжить» — в этаж, чьи сундуки и босс уже взяты. Теперь реестр не видел её дольше аренды (или строки нет) — выход без
    // записи, как с концом аренды: ни продления, ни удара. Здоровая нода бьёт каждые 2 с, а простой базы короче аренды возраст не превышает.
    // ⭐ R17-01: это — быстрый путь: ответ сверки может устареть на длину паузы машины (он ждал в буфере сокета), и последнее слово — у самого
    // удара (`leased`: ложится только одним запросом с той же проверкой, ниже).
    const leased = !!opts.lease && Number.isFinite(leaseLeft());
    if (leased) {
      const age = await nodeBeatAge(nodeId);
      if (age === null || age * 1000 >= LEASE_MS) {
        console.error(`[${nodeId}] ИНЦИДЕНТ: реестр не видел удара ноды ${age === null ? '(её строку уже сняла уборка)' : `${Math.round(age)} с`} — дольше аренды, а часы процесса этого не видели (простой машины): её героев и забеги реестр уже вправе был отдать — выход без записи`);
        process.exit(1);
        return;
      }
    }
    const g = readGauges();
    const cpu = process.cpuUsage();
    const now = Date.now();
    const dt = Math.max(0.001, (now - lastAt) / 1000);
    // Частота симуляции считается между двумя ударами сердца — по факту, а не по заданию.
    // Знаменатель — комнато-секунды за тот же интервал: паузы грейса не тикают, а число
    // комнат внутри интервала меняется, и «комнаты на момент замера» дают частоту, которой
    // не было (см. net/metrics.ts).
    const rs = counters.roomSeconds - lastRoomSeconds;
    const hz = rs > 0 ? (counters.ticks - lastTicks) / rs : 0;
    lastTicks = counters.ticks; lastRoomSeconds = counters.roomSeconds; lastAt = now;

    // ⭐ R7-09: СПЕРВА ПРОДЛИТЬ СВОИХ, ПОТОМ СЕРДЦЕ. Закрепление держится, пока на последнем ударе сердца нода держала героя
    // (`claimForJoin`): сердце раньше продления после долгого простоя базы — окно, где нода «жива», а герой «давно не
    // продлевался», и вход на соседнюю ноду забирал его вместе с правдой, которую нода держит недописанной копией. Продление
    // упало — сердце не бьётся: нода, не подтвердившая своих героев, живой их хозяйкой не выглядит.
    const held = charIds();
    const kept = await touchClaims(held, nodeId, !!opts.lease);   // ⭐ R16-02: с арендой — только пока реестр числит ноду живой
    // ⭐ V2: и забеги комнат ноды — правило держания у них то же (`claimRule.ts`), значит и продление — до удара сердца.
    const runs = heldRuns?.() ?? [];
    if (runs.length) {
      const keptRuns = await touchRuns(runs, nodeId, !!opts.lease);
      // ⭐ Перепрогон R15: чужими считаем только те, что нода держит и ПОСЛЕ ответа (по нынешнему держателю): забег, который комната отпустила,
      // пока продление шло в базу, законно взяла другая нода («Продолжить» героя там) — это не инцидент, и отпускать здесь нечего.
      const nowHeld = heldRuns?.() ?? [];
      const lostRuns = nowHeld.filter((r) => !keptRuns.has(r.key) && runs.some((s) => s.key === r.key));
      if (lostRuns.length) {
        console.error(`[${nodeId}] ИНЦИДЕНТ: забеги комнат ${lostRuns.map((r) => r.room).join(', ')} кластер числит за другой нодой — один забег идёт в двух местах`);
        // ⭐ ENV1: и комнаты их отпускают — сессии снимаются без записи, как проигравшие копии: правда забега там, где его держат.
        opts.runsLost?.(lostRuns);
      }
      // ⭐ R15-08: БЛИЗНЕЦ R4-28 ДЛЯ ЗАБЕГОВ. Продление (`touchRuns`) — вставка: забег, который комната отпустила между снимком и продлением
      // (кончился, брошен, вайп, комната ушла — её `DELETE` лёг раньше), оно возвращало в базу, а повторять отпуск было некому — сердце
      // его больше не продлевает, но нода бьётся, и держанием он числился ещё `CLAIM_IDLE_SEC`: «Продолжить» на соседней ноде слало к
      // исчезнувшей комнате. Тех, кого нода уже не держит, — отпустить снова (заново спросив, не взяла ли их комната). ⭐ Перепрогон R15: по
      // паре «забег, комната» — забег, который между снимком и продлением взяла ДРУГАЯ комната ноды, продление переписало на прежнюю.
      const still = new Set(nowHeld.map((r) => `${r.key}@${r.room}`));
      const goneRuns = runs.filter((r) => keptRuns.has(r.key) && !still.has(`${r.key}@${r.room}`));
      if (goneRuns.length) opts.runsGone?.(goneRuns);
    }
    const landed = await heartbeat(nodeId, url, {
      players: g.players, rooms: g.rooms,
      cpuSeconds: (cpu.user + cpu.system) / 1e6,
      rssBytes: process.memoryUsage().rss,
      loopP99: loop.percentile(99) / 1e6,
      tickHz: hz,
      draining,
      counters: counterSnapshot(),   // ⭐ E2E 30.09: счётчики процесса — гейтвею, в метрики кластера (`clusterMetrics`)
    }, leased);
    // ⭐ R17-01: УДАР НЕ ЛЁГ — РЕЕСТР УЖЕ СЧЁЛ НОДУ МЁРТВОЙ. Сверка в начале ответила «жива» до паузы машины (её ответ ждал в буфере сокета, пока
    // гость стоял, — часы процесса паузы не видели), а за паузу реестр отдал её героев и забеги другой, та их доиграла и отпустила. Раньше удар
    // был вставкой и оживлял строку: аренда продлевалась почти целой, `fenceLost` не находил чужого владельца (его уже отпустили), и следующий
    // удар вставлял закрепления и держание забегов заново — гейтвей вёл героя к её устаревшей копии. Теперь — выход без записи, как на сверке:
    // ни продления аренды, ни снятия копий по ответу, которому верить нельзя.
    if (leased && !landed) {
      console.error(`[${nodeId}] ИНЦИДЕНТ: удар сердца не лёг — реестр не видел ноду дольше аренды (или снял её строку), а сверка в начале удара этого не застала (простой машины после её ответа): выход без записи`);
      process.exit(1);
      return;
    }
    // ⭐ ENV1: удар дошёл — аренда продлена. ⭐ R16 C-05: только дошедший ДО её конца: после него реестр уже мог счесть ноду мёртвой (запас
    // аренды — на скачок часов), и её героев — отдать; такая нода не оживает, а уходит (`checkLease`). ⭐ R15-06: конец — по часам процесса;
    // аренду под сомнением (настенные часы ушли вперёд) дошедший удар снимает, ⭐ R16-02 — только если реестр видел ноду меньше аренды назад
    // (сверка в начале удара): тогда он её держит, а отданных, но ещё удержанных другой нодой, снял этот же удар (`fenceLost`, `runsLost`).
    if (opts.lease && leaseLeft() > 0) leaseBeat(sentAt, sentMono);
    loop.reset();
    // ⭐ R2-05: закрепление героя у другой ноды, а сессия здесь — проигравшая копия (нода подвисла, и её
    // закрепление забрали). Снимаем её, а не играем дальше: иначе две живые копии одного героя.
    const lost = held.filter((id) => !kept.has(id));
    if (lost.length) onLost?.(lost);
    // ⭐ R4-28: пока продление шло в базу, герой мог уйти, и снятие его закрепления прошло раньше продления — тогда продление
    // вернуло закрепление без сессии, и вход по коду на другой ноде получал отказ до 30 с. Тех, кого нода уже не держит, —
    // снять снова (в очереди героя: вернувшегося за это время не снимет).
    const still = new Set(charIds());
    const gone = held.filter((id) => kept.has(id) && !still.has(id));
    if (gone.length) onGone?.(gone);
  };
  const send = (): Promise<void> => {
    const run = beatOnce();
    sending.add(run);
    void run.finally(() => sending.delete(run)).catch(() => undefined);
    return run;
  };

  await send();
  beatNow = send;
  beat = setInterval(() => { void send().catch(() => undefined); }, BEAT_MS);
  beat.unref();
  if (opts.lease) setInterval(() => checkLease(nodeId), LEASE_CHECK_MS).unref();
}

/**
 * ⭐ ENV1: НОДА, НЕ ПОДТВЕРДИВШАЯ СЕБЯ РЕЕСТРУ, ОТГОРАЖИВАЕТ СЕБЯ САМА. Аренда (`lease.ts`) кончилась — удар сердца не доходил до реестра
 * `LEASE_MS` (раздел с базой, пауза процесса): ни тика, ни команды, ни записи (`leaseLost`), и выход без записи — до срока, после которого
 * реестр отдаёт её героев и забеги другой (супервизор поднимет её заново): писать поверх того, что уже могла записать другая нода, нельзя.
 * Раньше она играла дальше: герой, вошедший на соседней ноде, жил на двух, забег шёл в двух комнатах, и узнавала она об этом, только когда
 * удар снова доходил.
 * ⭐ R16 C-05: ДО КОНЦА АРЕНДЫ — ИГРА, А НЕ НЕОТМЕНЯЕМЫЙ СЛИВ. За 8 с до конца аренда начинала слив (`installNodeShutdown`: заморозка комнат,
 * снятие из реестра, выход), и удар, дошедший после (база вернулась на 105-й секунде простоя), аренду продлевал, но слива не отменял: все
 * ноды разом уходили и на старте снимали забеги своих героев (`clearAllRuns`) — хотя до `NODE_DEAD_SEC` забрать их не мог никто. А писать
 * тем сливом было нечем: удары не доходят, потому что база молчит, — те же записи падали бы. Теперь на исходе аренды — только строка в лог;
 * автосейв и дописка копий идут, как шли; дошедший удар аренду продлевает, и нода играет дальше; не дошёл до конца аренды — выход без записи.
 */
function checkLease(nodeId: string): void {
  if (stopped) return;
  const left = leaseLeft();
  // ⭐ R15-06: по настенным часам аренда кончилась, а по часам процесса — нет (шаг часов или простой машины, видный только им): нода
  // отгорожена (`leaseLost`), и решает реестр — удар сразу. Дошёл — аренда продлена, нода играет; не дошёл — выход без записи, как прежде.
  // ⭐ R16-02: «дошёл» — это и сверка в начале удара: реестр не видел ноду дольше аренды (простой машины, не шаг часов) — выход без записи там же.
  if (left > 0 && leaseDoubted()) {
    if (confirming) return;
    confirming = true;
    console.error(`[${nodeId}] настенные часы говорят, что аренда кончилась, а часы процесса — нет (шаг часов или простой машины): сверка с реестром`);
    const beat = beatNow ?? ((): Promise<void> => Promise.reject(new Error('нода не в кластере')));
    void beat().then(() => { confirming = false; }, (e: unknown) => {
      confirming = false;
      if (!leaseDoubted() && leaseLeft() > 0) return;   // аренду продлил удар по расписанию
      console.error(`[${nodeId}] ИНЦИДЕНТ: аренда ноды под сомнением, а удар сердца не дошёл до реестра — выход без записи:`, e);
      process.exit(1);
    });
    return;
  }
  if (left > DRAIN_GUARD_MS) {
    if (leaseLow) { leaseLow = false; console.log(`[${nodeId}] аренда ноды продлена — удар сердца снова доходит до реестра, нода играет дальше`); }
    return;
  }
  if (left <= 0) {
    console.error(`[${nodeId}] ИНЦИДЕНТ: аренда ноды кончилась (удар сердца не доходил до реестра ${Math.round((LEASE_MS - left) / 1000)} с) — выход без записи: героев и забеги ноды реестр вправе отдать другой`);
    process.exit(1);
    return;
  }
  if (!leaseLow) {
    leaseLow = true;
    console.error(`[${nodeId}] аренда ноды кончается через ${Math.round(left / 1000)} с — удар сердца не доходит до реестра; дошедший удар её продлит, иначе выход без записи`);
  }
}

/** Предохранитель слива ноды: дольше процесс не живёт, даже если база молчит (`TimeoutStopSec` юнита — больше, DEPLOY.md §3b). */
const DRAIN_GUARD_MS = 8_000;
/**
 * ⭐ R12-04: сколько из него дописка сейвов ждёт базу (`RoomManager.flushAll` — кругами): полсекунды остаются на снятие ноды из
 * реестра и выход.
 */
const DRAIN_FLUSH_MS = DRAIN_GUARD_MS - 500;
/** ⭐ ENV2: сколько слив оставляет на снятие ноды из реестра и выход после дописки. */
const DRAIN_EXIT_MS = DRAIN_GUARD_MS - DRAIN_FLUSH_MS;

/**
 * ⭐ ENV2: БЮДЖЕТ ДОПИСКИ СЛИВА — ДО КОНЦА АРЕНДЫ. Слив, начатый, пока база лежит (раздел, переключение), выходил через 8 с, даже если база
 * возвращалась на девятой: копии и свод забега уходили с процессом (ИНЦИДЕНТ R12-04). А писать можно, пока аренда ноды идёт (`lease.ts`: её
 * героев никто не заберёт) — круги дописки идут столько, но не дольше (после неё строку уже вправе писать другая нода). База жива — слив,
 * как и был, — миллисекунды: круги кончаются, как только всё легло. Нода аренды не держит (роль `single`) — прежние 7,5 с.
 * `TimeoutStopSec` юнита и срок супервизора — не меньше аренды (DEPLOY.md §3b, `supervisor.ts`).
 */
function drainBudget(): number {
  const left = leaseLeft();
  return Number.isFinite(left) ? Math.max(0, left - DRAIN_EXIT_MS) : DRAIN_FLUSH_MS;
}

/**
 * Слив ноды (Ф4.5): перестать принимать новых, дать сохраниться, уйти.
 * `flush` — запись прогресса всех комнат; ждать её обязательно (Ф2: запись асинхронная).
 *
 * R3-12: это ЕДИНСТВЕННЫЙ выход процесса ноды — общий обработчик транспорта ему уступает (`nodeShutdownInstalled`).
 * Порядок: слив объявлен сразу (удар сердца вне расписания — гейтвей перестаёт слать новых, не дожидаясь очередного
 * через две секунды; входы сюда отвечают «перезапускаемся»), сейвы дописаны, нода и её закрепления сняты из
 * реестра, выход. Всё — под одним предохранителем. ⭐ ENV2: дописка — до конца аренды ноды (`drainBudget`), а не 7,5 с. ⭐ R16 C-05: аренда
 * на исходе слива не начинает (`checkLease`): её конец — выход без записи, а дошедший до него удар — игра дальше.
 */
export function installNodeShutdown(nodeId: string, flush: (budgetMs: number) => Promise<unknown>): void {
  nodeShutdown = true;
  let leaving = false;
  const shutdown = (why: unknown = 'сигнал'): void => {
    // ⭐ R5-08: повторный сигнал (systemd шлёт SIGTERM всей группе, супервизор — свой, npm и tsx пересылают свой) — только в
    // лог: слив уже идёт и выйдет сам.
    if (leaving) { console.log(`[${nodeId}] повторный сигнал остановки — слив уже идёт`); return; }
    leaving = true;
    draining = true;
    // ⭐ ENV2: дописка — до конца аренды (база лежит — круги ждут её), а не 7,5 с; предохранитель — за ней.
    const budget = drainBudget();
    console.log(`[${nodeId}] слив (${String(why)}): новых игроков не принимаю, дописываю сейвы (не дольше ${Math.round(budget / 1000)} с)…`);
    // Предохранитель: если база молчит, всё равно выходим — иначе рестарт подвиснет.
    const done = (): never => process.exit(0);
    const guard = setTimeout(done, budget + DRAIN_EXIT_MS);
    void (async () => {
      try {
        // Объявление слива — рядом с записью, а не перед ней: молчащая база не должна съедать время сейвов.
        const announce = (beatNow?.() ?? Promise.resolve()).catch((e: unknown) => console.warn(`[${nodeId}] объявить слив не удалось:`, e));
        await flush(budget);   // ⭐ R12-04: база моргнула — сейвы дописываются кругами, пока не кончится бюджет
        await announce;
        // ⭐ R4-28: удары сердца — ДО снятия ноды: новых нет, идущие дописаны. Раньше удар по расписанию, ушедший в базу до
        // снятия, ложился после него — строка ноды и закрепления всех её игроков возвращались, и гейтвей ещё десять секунд
        // слал их на мёртвую ноду (а другие ноды им отказывали «герой на другом узле»).
        stopped = true;
        if (beat) clearInterval(beat);
        await Promise.allSettled([...sending]);
        await releaseNode(nodeId);
      } catch (e) {
        console.error(`[${nodeId}] при сливе:`, e);
      } finally {
        clearTimeout(guard);
        if (beat) clearInterval(beat);
        done();
      }
    })();
  };
  // ⭐ R5-08: `on`, а не `once`. `once` снимал обработчик первым же сигналом, и ВТОРОЙ SIGTERM (а при деплое по DEPLOY.md их
  // приходит несколько) убивал процесс действием по умолчанию посреди записи сейвов: без дописанных копий и `releaseNode`.
  process.on('SIGINT', shutdown);
  process.on('SIGTERM', shutdown);
}
