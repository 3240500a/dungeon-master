/**
 * СНИМОК ДЕФОЛТОВ. Нужен затем, что `GAIT`/`POSE` — ГЛОБАЛЬНЫЕ объекты, которые конфиг персонажа
 * накладывает поверх. Без сброса к дефолтам смена персонажа тащит чужие значения по ключам, которых
 * в новом конфиге нет, а свёртка локтя (она прибавляет) при каждой пересборке куклы прибавляла бы
 * ещё раз. Редактор так делает с самого начала — теперь так же делает и игра.
 */
export const GAIT_BASE: Record<string, number> = { ...GAIT } as unknown as Record<string, number>;
export const POSE_BASE: Record<string, number> = { ...POSE };

/**
 * Амплитуда маха в ЯКОРЯХ панели: ходьба (drive 1.0) и бег (drive 1.4) — те скорости, на которых
 * настраивают. ЧИСЛА ЗАМОРОЖЕНЫ НАРОЧНО: свёртка локтя (`foldElbow`) обязана давать один и тот же
 * результат при любых настройках, иначе она перестанет быть идемпотентной — покрутил амплитуду маха,
 * перезагрузил конфиг, и база локтя уехала. Это дефолты `swingBase`/`swingSpeed`: 0.45 + 1.0·0.4 и
 * 0.45 + 1.4·0.4.
 */
const AMP_WALK = 0.85, AMP_RUN = 1.01;

/**
 * ТРИ МЕСТА, ГДЕ ГНУЛСЯ ЛОКОТЬ, СКЛАДЫВАЮТСЯ В ОДНУ БАЗУ.
 *
 * Итоговый угол был суммой трёх независимых ручек: `GX.elbowBend` (ретаргет), `POSE.armEl` (база) и
 * `POSE.armElWalk` × амплитуда хода (добавка на ходу). Три ползунка на один угол — это не гибкость,
 * а невозможность понять, который крутить. Складываем в базу, остаётся две ручки: база и амплитуда.
 *
 * ИДЕМПОТЕНТНО: слагаемые обнуляются, поэтому повторный вызов прибавляет ноль. Редактор сохраняет уже
 * свёрнутое состояние, значит следующая загрузка снова прибавит ноль. Зовётся ОБОИМИ клиентами (игра
 * `applyGaitConfig`, редактор `applyGaitCfg`) — иначе они разъедутся ровно на этот угол.
 *
 * `armElWalk` был помножен на амплитуду хода, а база — нет, поэтому свёртка точна В ЯКОРЯХ панели
 * (ходьба и бег) и приблизительна между ними: там, где никто не настраивает.
 */
export function foldElbow(gx: { elbowBend: number; elbowBendRun?: number }): void {
  const rd = (k: string, base: number): [number, number] => { const p = ASYM[k]; return p ? [p[0], p[1]] : [base, base]; };
  const wr = (k: string, v: [number, number]): number => {
    if (Math.abs(v[0] - v[1]) < 1e-9) { delete ASYM[k]; return v[0]; }
    ASYM[k] = [v[0], v[1]]; return v[0];
  };
  const eb = rd('elbowBend', gx.elbowBend), ebR = rd('elbowBendRun', gx.elbowBendRun ?? gx.elbowBend);
  const w = rd('armElWalk', POSE.armElWalk);
  const el = rd('armEl', POSE.armEl), elR = rd('armElRun', POSE.armElRun);
  POSE.armEl = wr('armEl', [el[0] + eb[0] + w[0] * AMP_WALK, el[1] + eb[1] + w[1] * AMP_WALK]);
  POSE.armElRun = wr('armElRun', [elR[0] + ebR[0] + w[0] * AMP_RUN, elR[1] + ebR[1] + w[1] * AMP_RUN]);
  delete ASYM['elbowBend']; delete ASYM['elbowBendRun']; delete ASYM['armElWalk'];
  gx.elbowBend = 0; if (gx.elbowBendRun !== undefined) gx.elbowBendRun = 0;
  POSE.armElWalk = 0;
}

/**
 * ⭐ ДОЛЯ СТОРОНЫ `+X` СТРАЙФА (карта `STRAFE_R`/`@sr`, она же СВОЯ ЛЕВАЯ сторона персонажа — см.
 * «ТАБЛИЦА ИСТИНЫ «СТОРОНА»»), 0..1: `smoothstep` по УЗКОЙ ПОЛОСЕ вокруг нулевой боковой скорости.
 *
 * ⚠ ПОЧЕМУ НЕ ПРОСТО ЗНАК (`latPlusX`). У процедурного пути НЕТ кроссфейда (в отличие от клипового,
 * где смену стороны страйфа гасит `colFade`), поэтому жёсткий знак дал бы СТУПЕНЬКУ настроек ровно на
 * переходе: за один кадр ручка прыгнула бы с левого числа на правое. Ступенька в настройках позы
 * читается как рывок корпуса — та же грабля, из-за которой `backMix` считается через боковитость.
 *
 * Ровно в нуле обе доли равны 0.5, то есть сумма всегда `st` и на самом переходе сторона ничего не
 * решает. Практически там и `strafeMix` = 0 (ход строго вперёд/спиной боковитость не поднимает), но
 * полагаться на это нельзя: при вырожденных порогах (`strafeTo` = 0) `strafeMix` возвращает 1 сразу.
 *
 * Полоса — в ЕДИНИЦАХ НАПРАВЛЕНИЯ (вход `mLat` — компонента единичного вектора хода), не в u/с:
 * иначе ширина перехода зависела бы от скорости, и на ходьбе он был бы вчетверо резче, чем на бегу.
 */
export const STRAFE_SIDE_BAND = 0.06;
export const strafeSide = (mLat: number): number => {
  const u = clamp(mLat / (2 * STRAFE_SIDE_BAND) + 0.5, 0, 1);
  return u * u * (3 - 2 * u);
};

/** Боковитость хода 0..1 по углу между направлением движения и продольной осью тела (`strafeFrom`..`strafeTo`). */
export const strafeMix = (mFwd: number, mLat: number): number => {
  const ang = Math.atan2(Math.abs(mLat), Math.abs(mFwd)) * 180 / Math.PI;
  const a = GAIT.strafeFrom, b = GAIT.strafeTo;
  if (b - a < 1e-3) return ang >= b ? 1 : 0;
  const u = clamp((ang - a) / (b - a), 0, 1);
  return u * u * (3 - 2 * u);
};

/**
 * ПОДЪЁМ НОСКА В ПЕРЕНОСЕ, 0..1 по доле переноса `t`.
 *
 * Ноль на отрыве и ноль на приземлении — иначе стопа дёрнулась бы в обоих концах: на отрыве она
 * ещё на полу, на приземлении её тут же забирает заземление и кладёт плоско. Пик стоит там, где
 * скажет `ph`: клиренс нужен не в середине, а там, где стопа реально ближе всего к полу, и у
 * разной длины шага это разный момент.
 */
export const toeCurve = (t: number, ph: number): number => {
  const p = clamp(ph, 0.05, 0.95);
  const u = t < p ? (t / p) * 0.5 : 0.5 + ((t - p) / (1 - p)) * 0.5;
  return Math.sin(Math.PI * clamp(u, 0, 1));
};

/**
 * «НАЗАДНОСТЬ» 0..1 — единица на чистом ходе спиной, ноль на ходе вперёд и на чистом боку.
 *
 * Считается ЧЕРЕЗ боковитость, а не своим отдельным порогом. Два независимых порога неминуемо
 * разошлись бы, и на границе колонки либо перекрыли друг друга, либо обе молчали; здесь же сумма
 * честная по построению — чем боковее ход, тем больше распоряжается страйф-колонка.
 *
 * Второй множитель (продольность) нужен ради НЕПРЕРЫВНОСТИ у самой границы бока: без него при
 * странно выставленных порогах (`strafeTo` за 90°) на переходе вперёд↔назад была бы ступенька,
 * а ступенька в настройках позы читается как рывок корпуса.
 */
export const backMix = (mFwd: number, mLat: number): number => {
  if (mFwd >= 0) return 0;
  const lon = Math.abs(mFwd) / Math.max(1e-6, Math.hypot(mFwd, mLat));
  return Math.min(1 - strafeMix(mFwd, mLat), lon);
};

