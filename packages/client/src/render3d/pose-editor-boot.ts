/** Boot редактора: СНАЧАЛА вход администратора, потом тянем с сервера конфиг (классы/монстры) + контент
 *  поз-редактора в localStorage, ПОТОМ грузим редактор (он на старте читает localStorage — ростер/клипы/гейты).
 *  Единая истина = сервер. Тело в async-IIFE (не top-level await): иначе прод-таргет es2020 не собирает. */
import { syncPoseFromServer, syncConfigFromServer } from './poseServer.js';
import { ensureAdmin } from '../devAuth.js';

void (async (): Promise<void> => {
  // ВХОД ПЕРВЫМ ДЕЙСТВИЕМ, до синка и до отрисовки. Раньше вход спрашивался лениво — только когда
  // человек пытался что-то сохранить, — и инструмент выглядел открытым для всех, кто дотянулся
  // до порта. `ensureAdmin` не возвращается, пока не вошли админом.
  //
  // `null` = сервера нет. Это НЕ отказ в доступе: редактор умеет работать оффлайн на рабочей копии
  // (см. `poseServer`), и терять инструмент из-за упавшего сервера нельзя. Публиковать всё равно
  // не выйдет — это решает сервер, когда поднимется.
  const me = await ensureAdmin();
  if (!me) console.warn('[pose-editor] сервер недоступен — работаем на локальной рабочей копии, публикация не пройдёт');

  // ⚠ `compareBodies` — ТОЛЬКО здесь: сверка тел отставших ключей тянет всё тело `/api/pose` (≈ 0.9 МБ), и смысл
  // она имеет там, где есть бейдж «на сервере новее» и кнопка «взять серверное», то есть в редакторе. Игра
  // (`game3d-boot.ts`) зовёт синк без него — см. шапку `syncPoseFromServer`.
  await Promise.all([syncConfigFromServer(), syncPoseFromServer({ compareBodies: true })]);
  await import('./pose-editor.js');
})();
