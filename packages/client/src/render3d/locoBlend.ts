/**
 * ПОЛЗУНОК «ПРОЦЕДУРНО ↔ КЛИП» (Ф4) — выбор клипа и фаза для него. Чистая часть, без сцены.
 *
 * ГЛАВНОЕ РЕШЕНИЕ ФАЗЫ: клип сэмплируется НЕ своим таймером, а фазой планировщика. Планировщик
 * остаётся часами и опорой даже на единице ползунка, и из этого следуют обе вещи, ради которых всё
 * затевалось:
 *  • стопы не скользят — планты по-прежнему ставит он, клип лишь придаёт форму;
 *  • настройки персонажа (длина шага, доля опоры, каденция) ПЕРЕТАЙМЛИВАЮТ чужой клип. Это и есть
 *    «из двух купленных паков неограниченное число вариантов»: свой таймер у клипа сделал бы его
 *    неизменяемым, и ползунки перестали бы на него влиять.
 *
 * Фаза планировщика — π на шаг, значит 2π на полный цикл (левая + правая). Клип локомоции авторится
 * ровно на цикл, поэтому `u = (фаза mod 2π) / 2π`.
 */

/** Четыре направления вместо восьми — решение Ф0: диагонали закрывает доворот таза. */
export type LocoDir = 'fwd' | 'back' | 'strafe_L' | 'strafe_R';

/**
 * ⭐ СКОРОСТИ ЗАПЕКАНИЯ НАБОРА — одна правда для запекателя (`GAIT_PRESETS`) и для часов режима «только клипы».
 * Там клип идёт по ПРОЙДЕННОМУ ПУТИ: его цикл = скорость, на которой он снят, × его период. Разойдись эти
 * числа у запекателя и рантайма — стопы поехали бы по полу ровно на разницу (сторож в `clipOnly.test.ts`).
 */
export const LOCO_BAKE_MAXSPD = 120;
/**
 * ⭐⭐ РЕШЕНИЕ АВТОРА (17.09): ходьба запекается на 40 u/с, бег — на 120 u/с, и оба — ЧИСТЫМИ.
 *
 * Было 0.42 / 0.85 от максимума = 50.4 / 102 u/с. ЗАМЕР (планировщик воина, speedWalk 40 / speedRun 115): на 50.4
 * ось ходьба↔бег стоит на sb 0.139, на 102 — на 0.827. То есть «ходьба» несла 14 % беговых настроек, а «бег» —
 * 17 % шаговых, и ни один клип не был тем видом, который автор настраивал на вкладке «Бег» (превью там — 40.8 и
 * 114 u/с, sb 0.011 / 0.987). На 40 и 120 при умолчаниях sb ровно 0 и 1 — условие см. `GAIT_PRESETS` в `clipBake.ts`.
 *
 * ИГРА: базовая скорость воина 80 u/с (`balance.json` moveSpeedBase), в атаке ×0.4 = 32, штраф брони до 44, с
 * бонусами скорости до ~130–140, рывок 200. Поэтому бег играет на 100 % веса уже с 80 u/с (`LOCO_RUN_FULL_SPD`),
 * только медленнее (темп 80/120), а между 40 и 80 ходьба перетекает в бег (`locoRunWeight`). Позже возможен
 * промежуточный набор, снятый на 80.
 */
export const LOCO_BAKE_WALK_SPD = 40;
export const LOCO_BAKE_RUN_SPD = 120;
export const LOCO_RUN_FULL_SPD = 80;
/** Те же скорости ДОЛЯМИ максимума — в них пишет пресеты запекатель и показывает редактор: 1/3 и 1. */
export const LOCO_WALK = LOCO_BAKE_WALK_SPD / LOCO_BAKE_MAXSPD, LOCO_RUN = LOCO_BAKE_RUN_SPD / LOCO_BAKE_MAXSPD;
/**
 * ⚠ ЛЕГАСИ: доли, на которых снят ВЕСЬ набор до 17.09 (коммиты b11b042 … ea59571 — 0.42 и 0.85 не менялись ни разу).
 * У тех клипов поля `bakeSpeed` нет, и темп им нужен тот, на котором их сняли, — иначе до перезапекания стопы
 * поехали бы на разницу: 50.4 → 40 это −21 % длины цикла, 102 → 120 это +18 %.
 */
const LEGACY_WALK = 0.42, LEGACY_RUN = 0.85;
/**
 * Скорость (u/с), на которой снят клип набора. Клип её ПОМНИТ (`Clip.bakeSpeed`, пишет запекатель); старый клип без
 * поля — по имени, легаси-долями: `run_*` 102, остальное 50.4. Непозитивное/битое число считается отсутствующим:
 * длина цикла 0 остановила бы часы, и стопы стояли бы на месте, пока тело едет.
 */
export const bakedLocoSpeed = (c: { name: string; bakeSpeed?: number }): number =>
  typeof c.bakeSpeed === 'number' && Number.isFinite(c.bakeSpeed) && c.bakeSpeed > 0
    ? c.bakeSpeed
    : (/^run_/.test(c.name) ? LEGACY_RUN : LEGACY_WALK) * LOCO_BAKE_MAXSPD;
/**
 * ⭐⭐ ТЕМП ЧАСОВ (u/с): `tempoSpeed`, если шаг клипа правили после съёма (его пишет редактор, `strideTempo.syncClipTempo`:
 * шаг короче — темп чаще в ту же пропорцию), иначе скорость съёма `bakedLocoSpeed`. Доля опоры и всё остальное читают
 * именно `bakedLocoSpeed` — правка шага меняет только темп.
 */
export const clipTempoSpeed = (c: { name: string; bakeSpeed?: number; tempoSpeed?: number }): number =>
  typeof c.tempoSpeed === 'number' && Number.isFinite(c.tempoSpeed) && c.tempoSpeed > 0 ? c.tempoSpeed : bakedLocoSpeed(c);
/**
 * ⭐ ВЕС БЕГА КЛИПОВ ПО СКОРОСТИ (u/с): 0 до 40, линейно, 1 с 80 и выше — по решению автора (см. выше).
 * Это ось `sb` бленда клипов в режиме «только клипы»; к оси планировщика (`speedWalk/speedRun` = 40/115) она
 * отношения не имеет: у планировщика на 80 было бы sb 0.533, и игра никогда не видела бы бег целиком.
 */
export const locoRunWeight = (spd: number): number =>
  clamp01((spd - LOCO_BAKE_WALK_SPD) / (LOCO_RUN_FULL_SPD - LOCO_BAKE_WALK_SPD));

/** Фаза планировщика (рад, π на шаг) → нормализованное время клипа 0..1. */
export function locoPhaseU(phase: number): number {
  const TAU = Math.PI * 2;
  let u = phase % TAU;
  if (u < 0) u += TAU;
  return u / TAU;
}

/**
 * Направление по движению В КАДРЕ ТЕЛА. Складка к ближайшей оси — та же, что у доворота таза:
 * ход спиной это шаг назад, а не разворот. Порог страйфа берётся снаружи (`GAIT.strafeFrom/To`),
 * чтобы у клипов и у страйф-колонки настроек была ОДНА граница, а не две расходящиеся.
 */
/**
 * ⭐⭐ ПОЗА ЛОКОМОЦИИ — БЛЕНД ПО ТЕМ ЖЕ ОСЯМ, ЧТО И ПРОЦЕДУРНЫЕ НАСТРОЙКИ, А НЕ ВЫБОР ОДНОГО КЛИПА.
 *
 * ⚠ ЗДЕСЬ БЫЛ ПОРОГ («угол больше `strafeFrom` → страйф-клип, иначе вперёд») и второй порог по
 * скорости (`sb > 0.5` → бег). Именно они и давали дёрганье: на пороге клип подменялся МГНОВЕННО,
 * то есть поза прыгала целиком за один кадр. ЗАМЕР (скачок позы за кадр, воин, запечённый набор):
 *
 *      ровный бег            32° · подмен 0
 *      разгон шаг→бег        34° · подмен 1  ← весь максимум пришёлся на кадр подмены
 *      у порога ходьба/бег   61° · подмен 3  ← то же
 *      у порога страйфа      52° · подмен 4  ← то же
 *
 * Так это и решают в индустрии: не «выбрать клип», а **блендить несколько по непрерывным осям**
 * (Blend Space в Unreal, Blend Tree в Unity), синхронизировав их фазу (Sync Group). У нас обе
 * половины уже есть: планировщик СЧИТАЕТ эти оси для своих колонок настроек (`sb` ходьба→бег,
 * `st` страйфовость, `bt` назадность — все непрерывные, `strafeMix`/`backMix` — гладкие), а общие
 * часы — его же фаза шага. Поэтому клип-слой берёт ТЕ ЖЕ ОСИ и ТУ ЖЕ ФАЗУ, и порогам взяться неоткуда.
 *
 * ПОРЯДОК НАЛОЖЕНИЯ — как у `locoVal` (`pose.ts`), один в один: база вперёд (walk↔run по `sb`),
 * поверх колонка страйфа ×`st`, поверх колонка «назад» ×`bt`. Иначе слой клипов и слой настроек
 * спорили бы о том, что сейчас играет.
 *
 * ⚠ Л/П страйфа и вперёд/назад остаются ДИСКРЕТНЫМ выбором — и это не порог: сторона выбирается
 * знаком боковой скорости, а вес этой колонки в ноль-точке равен нулю (`strafeMix(0) = 0`), то есть
 * подмена происходит там, где её не видно.
 */
export interface LocoAxes {
  /** Ходьба (0) ↔ бег (1) — та же ось, что у колонок настроек. */
  sb: number;
  /** Страйфовость 0…1 (`strafeMix`). */
  st: number;
  /** Назадность 0…1 (`backMix`). */
  bt: number;
}

function clamp01(v: number): number { return v < 0 ? 0 : v > 1 ? 1 : v; }   // function — её зовёт `locoRunWeight` выше по файлу

/**
 * ⭐⭐ ВЕСА НАПРАВЛЕНИЯ ДЛЯ КЛИПОВ — ГЕОМЕТРИЧЕСКИЕ, БЕЗ МЁРТВОЙ ЗОНЫ.
 *
 * Жалоба: «бежишь наискосок — таз доворачивает не до конца, и ноги скользят; должен быть бег вперёд,
 * смешанный с приставным шагом». Так и было: колонки клипов брали вес страйфа из `st` планировщика,
 * а это СТИЛЕВОЙ порог его колонок настроек — `strafeMix` равен НУЛЮ до `strafeFrom` (45°) и доходит
 * до единицы к `strafeTo` (80°). Для настроек это правильно (ширину стойки не надо менять на 10°
 * отклонения), а для клипа — нет: клип «вперёд» ведёт стопу строго вперёд по тазу. Доворот таза
 * упирается в `warpMax` (50°), и на ходе под 90° остаток в 40° клип отыгрывал ЧИСТЫМ бегом вперёд.
 *
 * ЗАМЕР (бег, доворот включён, боковой снос маховой стопы с линии хода, ед/кадр):
 *
 *      ход   остаток   планировщик   клипы (было)
 *      50°      0°        0.015         0.025
 *      65°     15°        0.157         0.399
 *      80°     30°        0.222         0.770
 *      90°     40°        0.219         0.991   ← в 4.5 раза сильнее планировщика
 *
 * Вес клипа должен ПОВТОРЯТЬ НАПРАВЛЕНИЕ, а не стиль. Если стопа в клипе «вперёд» уходит на шаг по оси
 * тела, а в страйфе — на шаг вбок, то смесь с долей `w` ведёт её под углом `atan(w/(1−w))`; чтобы он
 * совпал с ходом `θ`, нужно `w = sinθ / (sinθ + cosθ)` — то есть доли модулей составляющих хода:
 * `|бок| / (|вперёд| + |бок|)`. Это обычные веса четырёхнаправленного бленда (кардинальные клипы).
 *
 * Считается ОТ ОСЕЙ ДОВЁРНУТОГО ТАЗА: доворот и бленд делят работу — доворот снимает сколько может,
 * бленд досыпает ровно остаток. Задняя полуплоскость — через ту же страйф-колонку (см. порядок наложения
 * в `blendLocoPose`): страйф = 1, назад = доля продольной составляющей.
 */
export function locoDirWeights(fwd: number, lat: number): { st: number; bt: number } {
  const af = Math.abs(fwd), al = Math.abs(lat), sum = af + al;
  if (sum < 1e-6) return { st: 0, bt: 0 };                 // стоим — направления нет, играет база
  const side = al / sum;
  return fwd >= 0 ? { st: side, bt: 0 } : { st: 1, bt: af / sum };
}

export function blendLocoPose<P>(
  pick: (dir: LocoDir, fast: boolean) => P | null,
  axes: LocoAxes,
  latPlusX: boolean,
  blend: (a: P, b: P, t: number) => P,
): P | null {
  const sb = clamp01(axes.sb), st = clamp01(axes.st), bt = clamp01(axes.bt);
  /**
   * Одна колонка направления: ходьба и бег, сблендённые по `sb`.
   *
   * ⚠ ЕСЛИ ОДНОЙ ИЗ ДВУХ СКОРОСТЕЙ НЕТ — играет та, что есть, ДАЖЕ если её вес сейчас нулевой.
   * Запёк только ходьбовый страйф и побежал боком — честнее сыграть его (фазу всё равно задаёт
   * планировщик, он и перетаймит), чем уронить колонку и уехать в бег ВПЕРЁД: направление важнее
   * каденции. Поймано тестом «вес перетекает, а не подменяет направление».
   *
   * Сэмплируем ЛЕНИВО: на чистой скорости — один клип, два только в зоне бленда или когда первого нет.
   */
  const col = (dir: LocoDir): P | null => {
    const fast = sb >= 0.5;
    const first = pick(dir, fast);                      // сторона с бóльшим весом
    const both = sb > 0.001 && sb < 0.999;
    const second = both || !first ? pick(dir, !fast) : null;
    if (!first) return second;
    if (!second) return first;
    return blend(fast ? second : first, fast ? first : second, sb);   // порядок аргументов: ходьба → бег
  };
  // База нужна только пока её вес не съеден колонками: на чистом страйфе/ходе спиной она не читается.
  let out = st > 0.999 || bt > 0.999 ? null : col('fwd');
  if (st > 0.001) { const s = col(latPlusX ? 'strafe_R' : 'strafe_L'); if (s) out = out ? blend(out, s, st) : s; }
  if (bt > 0.001) { const b = col('back'); if (b) out = out ? blend(out, b, bt) : b; }
  return out ?? col('fwd');
}

/**
 * Имя клипа по конвенции из плана: `walk_fwd` / `run_strafe_L` и так далее.
 *
 * Конвенция, а не жёсткая привязка: узел графа может указать на любой клип (Ф1.2), а это — умолчание,
 * с которого всё работает без единой записи в конфиге.
 */
export function locoClipName(dir: LocoDir, fast: boolean): string {
  return `${fast ? 'run' : 'walk'}_${dir}`;
}

/**
 * ⭐⭐ ВСЁ, ЧТО ДВИЖОК МОЖЕТ СПРОСИТЬ: четыре направления × ходьба/бег. Ровно эти имена и обязан
 * покрывать набор запекания — иначе запечёшь клипы, которых никто не читает, и наоборот.
 *
 * ⚠ Этот список — ЕДИНСТВЕННАЯ правда о составе набора. Он же кормит сторожа расхождения
 * (`locoSet.test.ts`) и список запекания в редакторе, поэтому «добавил направление» = одна правка.
 */
export const LOCO_DIRS: readonly LocoDir[] = ['fwd', 'back', 'strafe_L', 'strafe_R'];
export const LOCO_NAMES: readonly string[] =
  [false, true].flatMap((fast) => LOCO_DIRS.map((d) => locoClipName(d, fast)));

/**
 * Имена-кандидаты при ПОИСКЕ: нынешняя конвенция, затем историческая.
 *
 * ⚠ Историческое имя страйфа — без префикса скорости (`strafe_L`): запекатель делал ОДИН страйф на
 * сторону, и он подходит обеим скоростям — другого у автора всё равно нет. Смена конвенции не должна
 * обнулять уже запечённое (та же логика, что у имён стоек: `stanceNameCandidates`).
 */
export function locoClipNames(dir: LocoDir, fast: boolean): string[] {
  const out = [locoClipName(dir, fast)];
  if (dir === 'strafe_L' || dir === 'strafe_R') out.push(dir);
  return out;
}

/**
 * ⭐⭐ НАБОР ЛОКОМОЦИИ — ОДИН НА ВСЕ ОРУЖИЯ, С ВОЗМОЖНОСТЬЮ ПЕРЕКРЫТЬ ЕГО ПООРУЖНО.
 *
 * Порядок: точный набор ЭТОГО оружия → безоружный (`none`) → любой, что есть. Так «запёк без оружия»
 * работает везде, а «запёк отдельно под двуручник» бьёт базу — ровно как у стоек предметов.
 *
 * ⚠ РАНЬШЕ ОРУЖИЕ НЕ УЧАСТВОВАЛО ВОВСЕ: поиск шёл по имени и персонажу, и `find` отдавал ПЕРВЫЙ
 * подходящий клип — то есть набор был не «общий» и не «пооружный», а «какой раньше лёг в массив».
 */
/** Тег БАЗОВОГО набора: он играет под всеми оружиями, пока им не запечён свой (`findLocoClip`: точный → это → любой). */
export const BASE_LOCO_WEAPON = 'none';

/**
 * ⭐⭐ ПЕРСОНАЖ-ДОНОР НАБОРА ХОДА — КРИТИЧЕСКИЙ КОНТЕНТ.
 *
 * ЗАМЕР 19.09, опровергший посылку плана «игра уже ходит только клипами»: `clipOnly` требует
 * `hasLocoSet()`, а игроки (`gamePlayerDoll`) собирались вообще БЕЗ донора — донора получали только
 * монстры. Значит каждый класс без СВОЕГО запечённого `run_fwd`/`walk_fwd` уезжал в игре на процедурный
 * планировщик, и это не редкий угол: свой набор запечён у воина, классов семь.
 *
 * ⚠ ДОНОР ОДАЛЖИВАЕТ ТОЛЬКО ПОХОДКУ. Обычный `fallbackId` подменяет ВЕСЬ контент персонажа — стойки,
 * удары, привязки состояний, вид предметов (`readAnimCfg` берёт у донора конфиг ЦЕЛИКОМ, а не по
 * недостающим ключам). Раздать такой донор игрокам значило бы молча отдать магу воинские стойки и
 * воинскую классификацию предметов. Поэтому донор ХОДА — отдельная, более узкая цепочка: она работает
 * только в `locoClip`, а всё своё у персонажа остаётся своим.
 */
export const BASE_GAIT_CHAR = 'warrior';

/**
 * ⚠⚠ КАКОЙ ТЕГ ОРУЖИЯ ПОЛУЧАЕТ ЗАПЕКАЕМЫЙ НАБОР ХОДА.
 *
 * Правило живёт ЗДЕСЬ, рядом с поиском набора по тегу, а не в редакторе: тег и поиск — две половины одного
 * решения, и разъехаться они обязаны вместе или никак. В редакторе оно было двумя строчками в обработчике
 * кнопки и проверялось только чтением исходника — то есть сторож видел наличие функции, а не её смысл.
 *
 * ⚠ ПОЧЕМУ НЕ «ТЕКУЩЕЕ ОРУЖИЕ ПАНЕЛИ». Запекатель принудительно гасит авторскую стойку
 * (`setLayerBakeOverride`) — руки в клипе походки безоружные ВСЕГДА, чем бы ни позировали. Тег «меч» описывал
 * бы не клип, а случайное состояние редактора. Дальше ключ дедупа библиотеки — тройка (имя, персонаж, ОРУЖИЕ):
 * второе запекание при другом выборе кладёт ВТОРОЙ набор рядом, а не заменяет первый, и `findLocoClip` начинает
 * выдавать разным оружиям РАЗНЫЕ клипы под одним именем. Автор видит «перезапёк, а половина не доехала».
 *
 * Пооружный набор законен (двуручник ходит иначе), но это ЯВНОЕ решение: тяжёлое оружие меняет НОГИ, не руки.
 */
export const gaitBakeTag = (perWeapon: boolean, weapon: string): string =>
  (perWeapon && weapon ? weapon : BASE_LOCO_WEAPON);

export function findLocoClip<T extends { name: string; character?: string; weapon?: string }>(
  clips: readonly T[], name: string, character: string, weapon: string,
): T | null {
  let exact: T | null = null, base: T | null = null, any: T | null = null;
  for (const c of clips) {
    if (c.name !== name || c.character !== character) continue;
    if (c.weapon === weapon) { exact = c; break; }              // точнее уже не будет — выходим
    if (c.weapon === 'none') base ??= c;
    any ??= c;
  }
  return exact ?? base ?? any;
}

// ── СЕКЦИИ: старт → цикл → остановка (Ф5б) ───────────────────────────────────────────────────────

/** Что именно играет слой локомоции прямо сейчас. */
export type LocoSection = 'start' | 'loop' | 'stop' | 'idle';

export interface LocoSectionState {
  section: LocoSection;
  /** Собственное время секции (сек). У цикла его нет — им правит фаза планировщика. */
  t: number;
}

/**
 * Шаг машины секций. Чистая: ей дают состояние, «двигаемся ли», dt и границы — она возвращает новое.
 *
 * ⚠ РАЗГОН И ОСТАНОВКА ИДУТ ПО СВОЕМУ ВРЕМЕНИ, а цикл — по фазе планировщика, и это не
 * непоследовательность. У разгона нет «фазы шага»: он и есть выход на неё из нуля, и привязать его к
 * фазе значило бы растянуть или сжать его до неузнаваемости на каждой скорости. У цикла наоборот:
 * своё время сделало бы его неперетаймливаемым, и настройки персонажа перестали бы на него влиять.
 *
 * Возврат из остановки сразу в разгон (передумал на полпути) намеренно НЕ делается: доигрывать нечего,
 * персонаж уже поехал — уходим в разгон с нуля, это честнее, чем прыгнуть в середину цикла.
 */
export interface SectionBounds { loopStart: number; loopEnd: number; dur: number; hasStart: boolean; hasStop: boolean }

export function stepLocoSection(st: LocoSectionState, moving: boolean, dt: number, sec: SectionBounds): LocoSectionState {
  const t = st.t + dt;
  if (moving) {
    switch (st.section) {
      case 'loop': return { section: 'loop', t: 0 };
      case 'start': return t >= sec.loopStart ? { section: 'loop', t: 0 } : { section: 'start', t };
      // Из покоя и из остановки — на разгон с нуля. Возврат из остановки в середину цикла намеренно
      // НЕ делается: доигрывать там нечего, а прыжок в середину читается как рывок.
      default: return sec.hasStart ? { section: 'start', t: 0 } : { section: 'loop', t: 0 };
    }
  }
  switch (st.section) {
    case 'loop': return sec.hasStop ? { section: 'stop', t: 0 } : { section: 'idle', t: 0 };
    case 'stop': return t >= Math.max(0, sec.dur - sec.loopEnd) ? { section: 'idle', t: 0 } : { section: 'stop', t };
    case 'start': return { section: 'idle', t: 0 };   // отпустили на разгоне — доигрывать нечего
    default: return { section: 'idle', t: 0 };
  }
}

/**
 * Время внутри клипа для текущей секции (сек).
 *
 * Цикл берёт фазу планировщика (см. `locoPhaseU`) и растягивается ровно на секцию цикла, разгон и
 * остановка — своё время, обрезанное по границам секции.
 */
export function sectionClipTime(st: LocoSectionState, plannerU: number, sec: { loopStart: number; loopEnd: number }, dur: number): number {
  if (st.section === 'start') return Math.min(st.t, sec.loopStart);
  if (st.section === 'stop') return Math.min(sec.loopEnd + st.t, dur);
  return sec.loopStart + plannerU * Math.max(0, sec.loopEnd - sec.loopStart);
}
