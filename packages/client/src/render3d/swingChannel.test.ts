import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import * as path from 'node:path';

/**
 * ⭐⭐ ОСТАТОЧНЫЕ КАНАЛЫ ПЛАНИРОВЩИКА (Э14): опора, окно, трасса, мёртвые ручки.
 *
 * После вырезания планировщика в игре осталось несколько мест, где он ещё «числился источником».
 * Часть из них врала МОЛЧА, и это хуже отсутствия: панель, по которой ищут причину, называла не тот слой.
 */
const SRC = (f: string): string => readFileSync(path.join(__dirname, f), 'utf8');
const RT = SRC('poseRuntime.ts');

describe('каналы опоры и трасса', () => {
  /**
   * ⚠⚠ ПОЧЕМУ НЕЛЬЗЯ БРАТЬ КАНАЛ ИЗ СМЕСИ. `__swing` БИНАРНЫЙ, а `blendTwo` считает ОТСУТСТВУЮЩИЙ
   * канал НУЛЁМ. Значит смесь клипа ревизии 3 (канал есть) со старым (канала нет) на 50/50 даёт ровно
   * 0.5, и порог `< 0.5` объявляет ОПОРНУЮ ногу маховой — фиксация отпускает стопу ровно там, где она
   * стоит. Ровно ради этого канал берётся с ВЕДУЩЕГО клипа (Highest Weighted Animation в Unreal),
   * и фолбэк на смесь сводил это на нет.
   */
  it('⭐⭐ КАНАЛ ОПОРЫ — ТОЛЬКО С ВЕДУЩЕГО КЛИПА, ФОЛБЭКА НА СМЕСЬ НЕТ', () => {
    const i = RT.indexOf('if (leadSwing) this.clipContact');
    expect(i, '⚠ разбор чтения опоры сломался').toBeGreaterThan(0);
    const code = RT.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*/g, '');
    expect(code.includes('leadSwing ?? locoPose[SWING_KEY]'),
      '⚠ фолбэк на смешанный канал вернулся: бленд размазывает бинарный флаг в дробь').toBe(false);
  });

  it('⭐ НЕТ КАНАЛА — ОКНО ПО ДОЛЕ, и кадр ПОМЕЧЕН «опора угадана»', () => {
    // Окно по доле — живой фолбэк для импортного мокапа и клипов до ревизии 3; удалять его нельзя
    // (это уже проверено падением сторожа доли опоры). Но отличать его от канала — обязательно.
    const code = RT.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*/g, '');
    expect(code.includes('this.swingGuessed = true'), 'кадр помечается').toBe(true);
    expect(code.includes('get swingSource()'), 'источник опоры читается наружу').toBe(true);
    expect(code.includes('clipDuty >= 0 ?'),
      '⚠ мёртвый тернарник вернулся: `clipDuty` присваивается безусловно в том же кадре').toBe(false);
  });

  /**
   * ⚠⚠ СТРОКА ТРАССЫ ВРАЛА. Единственная строка про ноги писала «планировщик шагов», а в режиме клипов
   * `legMag` прибит в 0 — то есть панель показывала «планировщик, 0 %» и ни слова про клип хода.
   * Отлаживать «почему нога едет» по такой панели нельзя: она называет не тот слой.
   */
  it('⭐⭐ ТРАССА НАЗЫВАЕТ НАСТОЯЩИЙ ИСТОЧНИК НОГ, А НЕ ПЛАНИРОВЩИК', () => {
    const i = RT.indexOf("traceRow('НОГИ / ТАЗ'");
    expect(i, '⚠ строка трассы про ноги исчезла').toBeGreaterThan(0);
    const row = RT.slice(i, i + 700);
    expect(row.includes("clipOnly ? 'клип хода'"), '⚠ в режиме клипов источник обязан называться клипом').toBe(true);
    expect(row.includes('опора УГАДАНА'), 'угаданная опора видна в трассе').toBe(true);
    expect(row.includes('НЕТ КЛИПА ХОДА'), '⚠ «клипа нет, персонаж скользит» обязано быть видно').toBe(true);
    expect(RT.includes('layerTrace.swingGuessed = this.swingGuessed'), 'флаг едет в трассу').toBe(true);
    // ⚠ И ДО отрисовки строки: её пишет сам `gaitToHumanoid`, флаг после него показывал бы ПРОШЛЫЙ кадр.
    expect(RT.indexOf('layerTrace.swingGuessed = this.swingGuessed'))
      .toBeLessThan(RT.indexOf('gaitToHumanoid(this.human, this.weaponGroups()'));
  });

  it('⭐ ОДИН КАНАЛ, А НЕ ВСЯ ПОЗА: чтение опоры не собирает риг целиком', () => {
    // Было `clipPoseAt(lead, u)[SWING_KEY]` — полная поза ведущего клипа (все кости + slerp каждой)
    // ради одного числа, поверх уже собранной позы смеси, на каждую куклу каждый кадр.
    expect(RT.includes('clipChannelAt(lead, u, SWING_KEY'), 'читается один канал').toBe(true);
    expect(RT.includes('clipPoseAt(lead, u)[SWING_KEY]'), '⚠ полная поза ради одного канала вернулась').toBe(false);
  });
});

describe('мёртвые в игре ручки помечены честно', () => {
  /**
   * ⚠⚠ `gndIn`/`gndOut`/`footPlant`/`gndLag` в ИГРЕ не действуют и перезапеканием НЕ оживают: веса
   * заземления там жёстко `[1, 1]`, потому что канал опоры БИНАРЕН — он говорит ГДЕ опора, но не КАК
   * мягко в неё входить. Непрерывной доли опорной фазы в клипах нет вовсе.
   *
   * План предлагал либо перевести их на `__swing`, либо честно пометить. Перевести нечем: нужен НОВЫЙ
   * непрерывный канал в клипе, то есть новая ревизия запекателя и перезапекание всего набора — а автор
   * как раз перезапекает по другому поводу. Помечено.
   */
  /**
   * ⚠⚠ ЭТОТ СТОРОЖ Я НАПИСАЛ С НЕВЕРНОЙ ПОСЫЛКОЙ И ТУТ ЖЕ ПОЙМАЛСЯ НА НЕЙ САМ.
   *
   * Первая версия требовала подписи «только редактор» у ЧЕТЫРЁХ ручек, включая `gndLag`. Но они
   * РАЗНЫЕ: `gndIn`/`gndOut`/`footPlant` идут через `groundWeights`/`plantWeights`, а те в игре
   * жёстко `[1,1]` — значит мертвы. А `gndLag` передаётся В ИГРЕ напрямую в `renderRagdollGhost`
   * (`gamePlayerDoll.ts`) — значит действует, и подпись «только редактор» была бы новой ложью
   * вместо старой. Поймал это замер списка рантаймовых ручек (`runtimeKnobs.test.ts`), а не глаз.
   */
  it('⭐⭐ ТРИ ОКОННЫЕ РУЧКИ ПОДПИСАНЫ «ТОЛЬКО РЕДАКТОР», А `gndLag` — НЕТ', () => {
    const ed = SRC('pose-editor.ts');
    for (const k of ['gndIn', 'gndOut', 'footPlant']) {
      const i = ed.indexOf(`'${k}'`);
      expect(i, `ручка ${k} не найдена`).toBeGreaterThan(0);
      const line = ed.slice(ed.lastIndexOf('\n', i) + 1, ed.indexOf('\n', i));
      expect(line.includes('только редактор'),
        `⚠ ${k} снова выглядит рабочей: автор будет её крутить, видеть перемену в редакторе и не понимать, ` +
        'почему в игре её нет').toBe(true);
    }
    const g = ed.indexOf("'gndLag'");
    const gLine = ed.slice(ed.lastIndexOf('\n', g) + 1, ed.indexOf('\n', g));
    expect(gLine.includes('только редактор'),
      '⚠ `gndLag` В ИГРЕ ДЕЙСТВУЕТ (передаётся в `renderRagdollGhost`) — подпись «только редактор» ' +
      'была бы новой ложью вместо старой').toBe(false);
    expect(ed.includes('ТОЛЬКО РЕДАКТОР — три ОКОННЫЕ ручки'), 'есть и общее пояснение').toBe(true);
  });

  it('⚠ и веса заземления в игре действительно жёсткие — подпись не врёт', () => {
    expect(RT.includes('this.clipOnly ? ONE_ONE : this.plannerGroundW()'), 'заземление').toBe(true);
    expect(RT.includes('this.clipOnly ? ONE_ONE : this.plannerPlantW()'), 'постановка').toBe(true);
  });
});
