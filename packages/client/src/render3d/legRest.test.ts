import { describe, it, expect } from 'vitest';
import { PoseDriver, HIP_DX } from './pose.js';

/**
 * ⭐ РАЗМЕРЫ ТЕЛА ПЛАНИРОВЩИК БЕРЁТ ИЗ РИГА, А НЕ ИЗ КОНСТАНТ.
 *
 * Длина бедра/голени и полуширина таза были зашиты числами процедурного манекена
 * (`L_THIGH 15`, `L_SHIN 13.5`, `HIP_DX 3.6`). ЗАМЕР рига рыцаря после переимпорта:
 * бедро **14.088**, голень **14.421**, полутаз **3.867** — то есть сумма ноги совпадала
 * (28.509 против 28.5) и потому выглядела «правильной», а ПРОПОРЦИЯ внутри ноги была
 * сдвинута (бедро −6 %, голень +7 %) и таз уже нашего на 7 %.
 *
 * Раньше расхождение подпирал коэффициент `rigK` — планировщик замерял отношение
 * «факт/намерение» на каждом приземлении и подгонял им свои пороги. Теперь длины настоящие,
 * и второй масштаб поверх них считал бы поправку ДВАЖДЫ, поэтому `rigK` удалён.
 *
 * Сторож проверяет ровно это: размеры — ПОЛЕ рига, и решение ноги от них действительно зависит.
 */
describe('размеры ноги — из рига, а не константы', () => {
  const RIG = { thigh: 14.088, shin: 14.421, hipHalfW: 3.867, hipDropY: -3.670 };   // замер рыцаря (рест-поза модели)

  /** Несколько кадров привода на месте: вернуть углы и боковой вынос обеих ног. */
  function stand(legRest: PoseDriver['legRest']): { hip: number; kn: number; lat: number } {
    const d = new PoseDriver();
    d.legRest = legRest;
    d.setMove(0);
    for (let i = 0; i < 12; i++) { d.setWorld(0, 0, 0, 0, 0); d.update(1 / 60); }
    return { hip: d.out.hipL, kn: d.out.knL, lat: d.out.hipLatL };
  }

  it('умолчание — процедурный манекен, прежние константы бит в бит', () => {
    expect(new PoseDriver().legRest).toBeNull();
  });

  it('⭐ размеры рига РЕАЛЬНО меняют решение ноги (иначе поле декоративное)', () => {
    const base = stand(null);
    const rig = stand(RIG);
    const d = Math.abs(base.hip - rig.hip) + Math.abs(base.kn - rig.kn) + Math.abs(base.lat - rig.lat);
    expect(d, '⚠ планировщик игнорирует размеры рига — значит они снова взяты из констант').toBeGreaterThan(0.01);
  });

  it('при РАВНЫХ константам размерах поведение прежнее бит в бит', () => {
    // Подмена «риг = ровно наш манекен» обязана быть тождественной: иначе поле не фолбэк, а сдвиг.
    const same = stand({ thigh: 15, shin: 13.5, hipHalfW: HIP_DX, hipDropY: 0 });
    const base = stand(null);
    expect(same.hip).toBeCloseTo(base.hip, 12);
    expect(same.kn).toBeCloseTo(base.kn, 12);
    expect(same.lat).toBeCloseTo(base.lat, 12);
  });

  it('ПРОПОРЦИЯ внутри ноги важна, а не только её сумма', () => {
    // 14.088 + 14.421 = 28.509 ≈ 28.5 — сумма та же, но колено сгибается иначе.
    // Это и есть причина, по которой «нога вроде правильной длины», а походка не сходится.
    const ours = stand({ thigh: 15, shin: 13.5, hipHalfW: HIP_DX, hipDropY: 0 });
    const rig = stand({ thigh: 14.088, shin: 14.421, hipHalfW: HIP_DX, hipDropY: 0 });
    expect(Math.abs(ours.kn - rig.kn), '⚠ IK берёт длины звеньев мимо рига').toBeGreaterThan(1e-4);
  });

  it('полуширина таза рига двигает ЯКОРЬ бедра', () => {
    // ⚠ Стоя без замера стойки плант берётся из того же `hipHalf`, поэтому стопа оказывается ровно
    // под бедром и боковой угол равен нулю при любой ширине таза. Чтобы увидеть якорь, стойку задаём
    // ЯВНО (как это делает `measureStancePlants`) — тогда вынос стопы от бедра считается по-разному.
    const at = (hipHalfW: number): number => {
      const d = new PoseDriver();
      d.legRest = { ...RIG, hipHalfW };
      d.setStance(5, 0, -5, 0);
      d.setMove(0);
      for (let i = 0; i < 12; i++) { d.setWorld(0, 0, 0, 0, 0); d.update(1 / 60); }
      return d.out.hipLatL;
    };
    expect(Math.abs(at(2) - at(8)), '⚠ якорь бедра не из рига').toBeGreaterThan(1e-3);
  });
  it('⭐ СУСТАВ БЕДРА НИЖЕ ТАЗА — иначе ногу просят длиннее, чем она есть', () => {
    // Замер рыцаря: таз 35.049, лодыжка 2.892 — пролёт 32.157 при ноге 28.509. Не достаёт 3.648,
    // ровно на снос сустава (офсет `LeftUpperLeg.y` = −3.67). Без поправки IK каждый кадр
    // упирается в предел вытяжения, и вклад ручек походки съедает упор.
    const flat = stand({ ...RIG, hipDropY: 0 });
    const real = stand(RIG);
    expect(Math.abs(flat.kn - real.kn), '⚠ снос сустава бедра не учтён — нога решается от таза, а не от сустава').toBeGreaterThan(1e-3);
  });
});
