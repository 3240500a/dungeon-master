/**
 * ⭐⭐ ПОВОРОТ НА МЕСТЕ КЛИПАМИ — квантованный шагами 45° / 90° / 180°. Чистая часть, без сцены.
 *
 * Жалоба: «стоишь и поворачиваешься — подшагов нет». Замер показал причину раньше любых клипов
 * поворота: планировщик шаги ДЕЛАЛ (45° → 2 шага, 90° → 3, 180° → 6), но слой клипов бега накрывал
 * ноги застывшим кадром ходьбы и стоя тоже — стопа не отрывалась от пола вовсе (подъём 0.00 против
 * 6.5 у планировщика). Это чинится в `PosePlayer` воротами по движению; а здесь — то, о чём просили:
 * запечённые повороты, которые играют сами.
 *
 * КАК ЭТО ДЕЛАЮТ В ИНДУСТРИИ (Turn In Place, UE5 Lyra): пока стоим, НИЗ стоит на месте, а ВЕРХ
 * доворачивается к прицелу — копится «остаток» (у нас это та же скрутка корпуса). Когда остаток
 * перешёл порог, играет клип поворота нужной величины, и таз поворачивается ПО КРИВОЙ ИЗ КЛИПА — ровно
 * так, как в нём переступают ноги. Поэтому стопы и таз не могут разойтись: их ведёт один источник.
 *
 * Почему клип ведёт таз, а не наоборот (как у бега, где часы — фаза планировщика): у поворота нет
 * периодической фазы, а связь «угол таза ↔ момент шага» держится только внутри самого клипа. Сэмплируй
 * клип по углу живого таза — и при другой скорости доворота ноги поедут не в такт.
 *
 * ⭐⭐ КОГДА РЕШАТЬ — ВАЖНЕЕ, ЧЕМ ЧТО ИГРАТЬ. Жалоба: «в игре сразу начинает поворачивать на 45° и
 * поворачивает за несколько подходов». ЗАМЕР (прицел ведётся мышью с разгоном и торможением):
 *
 *      рывок 180° за 0.2 с   → 45° на 0.07 с → 90° → 45°   (три клипа, первый — пока мышь ещё едет)
 *      рывок 90° за 0.15 с   → 45° на 0.07 с → 45°
 *      плавно 180° за 1 с    → 45° → 90° → 45°
 *
 * Причина: поворот запускался в тот же кадр, когда остаток перешагнул 35°, — то есть в самом начале
 * движения мыши, и выбирался по ЭТОМУ, ещё растущему остатку.
 *
 * КАК ДЕЛАЮТ В ИНДУСТРИИ. Lyra (UE5) копит смещение таза стоя и запускает поворот, только когда оно
 * больше 50°, а величину (90 или 180) выбирает по накопленному; продолжаешь крутить — после поворота
 * запускается следующий. Плагин TurnInPlace (Vaei) задаёт на режим мин./макс. угол и выбирает шаг
 * (60/90/135/180) по углу, а при упоре в максимум ускоряет поворот. Общая мысль — решение принимается по
 * ИТОГУ движения прицела, а не по его первому кадру.
 *
 * У нас это три правила (`shouldCommitTurn`):
 *  1. ПРИЦЕЛ УСПОКОИЛСЯ (`TURN_SETTLE_SEC`) и остаток больше порога доворота профиля (`twist.threshold` —
 *     та же ручка, что у процедурного доворота на вкладке «Повороты»);
 *  2. ВЕРХ УПЁРСЯ в предел скрутки дольше `TURN_URGENT_SEC` — мышь ещё едет, но ждать дальше значит
 *     выворачивать спину (так решается непрерывное вращение);
 *  3. ПРИЦЕЛ ДАВНО СТОИТ (`relaxTime` профиля) — довернуть и небольшой остаток, чтобы не стоять перекрученным.
 *
 * Величина — БЛИЖАЙШАЯ к остатку (`pickTurn`), а не наибольшая «до которой дорос»: 70° → 90°, 60° → 45°.
 * Недовёрнутая или перевёрнутая разница остаётся скруткой корпуса — клип НЕ растягивается под угол,
 * иначе опорные стопы крутились бы по полу на разницу.
 */
import { clipPoseAt, clipDur, ROOT_YAW, type Clip } from './clipModel.js';

/** Величины поворотов, от большей к меньшей: выбирается наибольшая, до которой дорос остаток. */
export const TURN_ANGLES_DEG = [180, 90, 45] as const;
/** Наименьший остаток, который вообще стоит доворачивать: номинал самого маленького клипа минус этот запас. */
export const TURN_SLACK_DEG = 10;
/** Прицел считается успокоившимся, когда почти не двигался столько секунд (мышь доехала). */
export const TURN_SETTLE_SEC = 0.1;
/** Сколько верх может простоять в упоре скрутки, пока мышь ещё едет, прежде чем поворот начнётся без ожидания. */
export const TURN_URGENT_SEC = 0.12;

/**
 * ⭐⭐ ПОРА ЛИ ПОВОРАЧИВАТЬ (см. шапку — три правила). Чистая функция: вход — остаток и таймеры, выход — да/нет.
 * `stableFor` — сколько прицел стоит; `pinnedFor` — сколько верх упирается в предел скрутки.
 */
export function shouldCommitTurn(residual: number, stableFor: number, pinnedFor: number, twist: { threshold: number; relaxTime: number }): boolean {
  const a = Math.abs(residual);
  if (stableFor >= TURN_SETTLE_SEC && a >= twist.threshold) return true;
  if (pinnedFor >= TURN_URGENT_SEC) return true;
  const minTurn = (Math.min(...TURN_ANGLES_DEG) - TURN_SLACK_DEG) * Math.PI / 180;
  return stableFor >= twist.relaxTime && a >= minTurn;
}

/**
 * Сторона поворота — по той же конвенции, что страйф (`strafe_R` ↔ положительная боковая скорость):
 * `R` = рыск растёт. Одна конвенция на весь набор, иначе `turn_R` и `strafe_R` смотрели бы в разные стороны.
 */
export const turnClipName = (deg: number, right: boolean): string => `turn_${right ? 'R' : 'L'}_${deg}`;

/** Все имена поворотов, которые может спросить рантайм, — единственная правда о составе набора. */
export const TURN_NAMES: readonly string[] =
  TURN_ANGLES_DEG.flatMap((d) => [turnClipName(d, false), turnClipName(d, true)]);

/**
 * Какой поворот играть под этот остаток (рад, со знаком): БЛИЖАЙШИЙ по величине из запечённых, при
 * равенстве — больший (меньше повторных подходов). `null` — остаток меньше наименьшего доворота или
 * поворотов нет. Разница с остатком — хоть недолёт, хоть перелёт — уходит в скрутку корпуса.
 */
export function pickTurn(residual: number, has: (name: string) => boolean): { name: string; deg: number; right: boolean } | null {
  const a = Math.abs(residual) * 180 / Math.PI, right = residual > 0;
  if (a < Math.min(...TURN_ANGLES_DEG) - TURN_SLACK_DEG) return null;
  let best: { name: string; deg: number; right: boolean } | null = null, bestErr = Infinity;
  for (const deg of TURN_ANGLES_DEG) {                   // от большего к меньшему → при равенстве остаётся больший
    const name = turnClipName(deg, right);
    if (!has(name)) continue;
    const err = Math.abs(a - deg);
    if (err < bestErr - 1e-9) { best = { name, deg, right }; bestErr = err; }
  }
  return best;
}

/** Ключ позы с флагами переноса ног клипа: `[левая, правая, 0]`, 1 = нога в воздухе. */
export const SWING_KEY = '__swing';

/** Накопленный поворот корня клипа на времени `t` (рад). Нет канала — 0. */
export function turnYawAt(clip: Clip, t: number): number {
  const dur = clipDur(clip) || 1;
  return clipPoseAt(clip, Math.min(1, Math.max(0, t / dur)))[ROOT_YAW]?.[0] ?? 0;
}

/**
 * Какие стопы клип держит на полу на времени `t` — для заземления.
 *
 * ⚠ БЕЗ ЭТОГО ПОДЪЁМ СТОПЫ ИЗ КЛИПА СЪЕСТ ЗАЗЕМЛЕНИЕ. Оно решает «кого прижимать к полу» по флагам
 * планировщика, а на время поворота ноги у планировщика отобраны — он считает обе опорными и положил
 * бы маховую ногу клипа плоско на пол.
 */
export function turnSupportAt(clip: Clip, t: number): [boolean, boolean] {
  const dur = clipDur(clip) || 1;
  const s = clipPoseAt(clip, Math.min(1, Math.max(0, t / dur)))[SWING_KEY];
  return s ? [s[0] < 0.5, s[1] < 0.5] : [true, true];
}
