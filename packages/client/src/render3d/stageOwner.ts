/**
 * ВЛАДЕЛЕЦ АСИНХРОННОЙ СБОРКИ: что собрано — то обязано быть убрано.
 *
 * Жалоба, ради которой это заведено: «после того как я нажал тест, появился ещё один меш». В сцене
 * поз-редактора оставалась ВТОРАЯ игровая кукла — белая, в бинд-позе (её никто не ведёт), ровно в
 * начале координат, поверх манекена.
 *
 * ⚠ Причина не в кукле и не в сцене, а в форме владения. Было так: одна ссылка `doll`, сборка
 * АСИНХРОННАЯ (физика + конфиг + GLB — это секунды), а снятие — `if (doll) remove(doll)`. Отсюда две
 * дыры сразу:
 *
 * 1. **Гейт смотрел на РЕЗУЛЬТАТ, а не на НАМЕРЕНИЕ.** Флаг «вкладка активна» поднимался в КОНЦЕ
 *    сборки, поэтому уход с вкладки во время загрузки не останавливал ничего: `stop()` не звался,
 *    сборка спокойно доезжала и добавляла куклу в сцену уже НА ЧУЖОЙ вкладке.
 * 2. **Две гонящиеся сборки клали ДВЕ куклы, а ссылка оставалась на последней.** Второй `start()`
 *    (ушли и вернулись; или просто любая перерисовка панели, пока идёт загрузка) запускал вторую
 *    сборку, и предыдущая кукла становилась сиротой — снять её было уже нечем.
 *
 * Поэтому здесь два правила, и оба структурные, а не «не забыть проверить флаг»:
 * • всё собранное СНАЧАЛА попадает в список владения и только потом проверяется на актуальность —
 *   значит устаревшее не «теряется», а штатно сносится;
 * • снаружи гейтится НАМЕРЕНИЕ (`wanted`), а не `active`.
 */

export interface StageOwner {
  /**
   * Хотим ли мы быть собранными. ⚠ ВНЕШНИЙ ГЕЙТ ОБЯЗАН СМОТРЕТЬ СЮДА, а не на `active`: между
   * `start()` и `active` лежит вся асинхронная загрузка, и в этом окне «не активен» ≠ «не нужен».
   */
  readonly wanted: boolean;
  /** Собрано и готово к кадру. */
  readonly active: boolean;
  /** Сколько построенного сейчас живо. Больше единицы не бывает — на это есть тест. */
  readonly liveCount: number;
  start(): Promise<void>;
  stop(): void;
  /** Пересобрать (сменили персонажа/оружие). Пока не нужны — ничего не делает. */
  rebuild(): Promise<void>;
}

export interface StageSpec<T> {
  /**
   * Собрать. `alive()` — «мы всё ещё нужны»: проверять ПОСЛЕ каждого `await`, чтобы не тащить
   * дорогую загрузку в пустоту. Вернуть `null` = собрались ни во что.
   *
   * ⚠ Возврат можно НЕ страховать: что бы ни вернулось, владелец либо оставит это себе, либо
   * снесёт через `drop`. Забыть убрать за собой физически нельзя.
   */
  build(alive: () => boolean): Promise<T | null>;
  /** Снять построенное со сцены и освободить. Зовётся РОВНО ОДИН раз на каждый успешный `build`. */
  drop(v: T): void;
  /** Захват общих ресурсов (клавиатура, мышь, орбита) — на входе. */
  on?(): void;
  /** Отдать их обратно — на выходе. Зовётся и тогда, когда собраться не успели. */
  off?(): void;
}

export function makeStageOwner<T>(spec: StageSpec<T>): StageOwner {
  let want = false;
  let active = false;
  let gen = 0;              // поколение: всё, что не последнее, обязано умереть
  const live = new Set<T>();   // ⚠ НАБОР, а не одна ссылка: гонка кладёт сюда обе сборки, снимаются обе

  const clear = (): void => {
    active = false;
    for (const v of [...live]) spec.drop(v);
    live.clear();
  };
  /** Снять РОВНО СВОЁ. ⚠ Не `clear()`: устаревшая сборка может доехать ПОЗЖЕ актуальной и снесла бы её. */
  const dropOne = (v: T): void => { if (live.delete(v)) spec.drop(v); };

  const run = async (): Promise<void> => {
    const my = ++gen;
    clear();
    const v = await spec.build(() => my === gen && want);
    if (v === null || v === undefined) return;
    live.add(v);                                     // сперва во владение, потом проверки — иначе сирота
    if (my !== gen || !want) { dropOne(v); return; } // устарели, пока собирались
    active = true;
  };

  return {
    get wanted() { return want; },
    get active() { return active; },
    get liveCount() { return live.size; },

    async start(): Promise<void> {
      if (want) return;        // уже идём — повторный вызов НЕ запускает вторую сборку
      want = true;
      spec.on?.();
      await run();
    },

    stop(): void {
      if (!want && !live.size) return;
      want = false;
      gen++;                   // сборка в полёте увидит это и снимет за собой
      spec.off?.();
      clear();
    },

    async rebuild(): Promise<void> { if (want) await run(); },
  };
}
