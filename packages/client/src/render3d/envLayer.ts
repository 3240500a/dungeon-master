import type * as THREE from 'three';

/**
 * Снести всех детей группы (геометрии — `dispose`). Смена области сносит так группы окружения, предметов и трупов.
 * Материалы не трогает: у окружения они общие (кэш кита, `getMaterial`), свои материалы предметов освобождает `removeProp`.
 */
export function clearGroup(g: THREE.Object3D): void {
  for (let i = g.children.length - 1; i >= 0; i--) { const c = g.children[i]!; c.traverse((o) => (o as THREE.Mesh).geometry?.dispose?.()); g.remove(c); }
}

/**
 * ⭐ R15-01: ПЕРЕСОБРАТЬ СЛОЙ ОКРУЖЕНИЯ — И ТОЛЬКО ЕГО.
 *
 * Окружение области (пол, стены, колонны, декор, лестница вниз — `env3d.buildEnvironment`) строится дважды: сразу
 * боксами и ещё раз, когда догрузится GLB-тайлсет биома (`online3d.loadEnvForBiome`, всегда ПОЗЖЕ `buildArea`). Раньше
 * пересборка сносила всю группу пола — а в ней жили и предметы области, которые рисует `buildArea`: лестницы выходов,
 * портал возврата, створки дверей, рычаги, сундуки, столбики NPC и портал города. На первом узле крипты за страницу они
 * исчезали до смены области, а `[E]` и метки миникарты оставались на пустом месте; запертая дверь выглядела полом, а
 * сервер держал клетку (невидимая стена); `removeProp` по снятым мешам больше ничего не делал.
 *
 * Теперь у окружения своя группа (`envGroup`): её пересобирают `buildArea`, догрузка кита и DEV `rebuildEnv`, а группу
 * предметов (`floorGroup`) сносит одна смена области. `build` кладёт меши в переданную группу и возвращает свой итог
 * (факелы окружения).
 */
export function rebuildEnvLayer<T>(envGroup: THREE.Object3D, build: (parent: THREE.Object3D) => T): T {
  clearGroup(envGroup);
  return build(envGroup);
}
