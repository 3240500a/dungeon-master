import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { facingFrom } from './playerInput.js';

/**
 * ⭐⭐ СВОЙ ФЕЙСИНГ РИСУЕТСЯ ПРЕДСКАЗАННЫМ, А НЕ ЭХОМ СЕРВЕРА.
 *
 * Жалоба: «фейсинг странно работает, как будто чуть в сторону от прицела». ЗАМЕР ПОЗЫ это НЕ
 * подтвердил: в устоявшемся состоянии таз, грудь и верх груди смотрят в прицел с точностью 0.00°.
 * Дело было в ПУТИ числа, а не в позе.
 *
 * Клиент считает фейсинг → шлёт 30 раз в секунду → сервер кладёт его К СЕБЕ КАК ЕСТЬ
 * (`p.facing = input.facing`, он его не вычисляет) → возвращает в снапшоте → рисовали ЭХО.
 * Задержка складывается из периода отправки (33 мс), пинга и периода снапшота (33 мс) — около
 * сотни миллисекунд. На ведении мыши 180°/с это ~17° отставания, и читается ровно как «чуть в сторону».
 *
 * ⚠ ПРЕДСКАЗАНИЕ ЗДЕСЬ ТОЧНОЕ, а не приблизительное: сервер фейсинг не считает, он его принимает.
 * Единственное исключение — оглушение: там ввод не проходит, и ведёт сервер.
 */
const HERE = dirname(fileURLToPath(import.meta.url));
const src = (f: string): string => readFileSync(join(HERE, f), 'utf8');

describe('свой фейсинг', () => {
  it('⭐⭐ СВОЯ КУКЛА НЕ РИСУЕТСЯ ФЕЙСИНГОМ ИЗ СНАПШОТА', () => {
    // ⚠ Мутация «вернуть `mine.facing` в вызов привода» валит это — а именно так и было.
    const s = src('online3d.ts');
    const call = /driveActor\(self,[^;]*?\);/s.exec(s);
    expect(call, 'вызов привода своей куклы не найден — тест устарел').not.toBe(null);
    expect(/mine\.facing/.test(call![0]), '⚠ своя кукла снова рисуется ЭХОМ сервера').toBe(false);
    expect(/myFacing/.test(call![0]), '⚠ своя кукла рисуется не предсказанным углом').toBe(true);
  });

  it('⚠ ПОД СТАНОМ ФЕЙСИНГ ВЕДЁТ СЕРВЕР — иначе оглушённый крутится за мышью', () => {
    // Сервер под станом ввод игнорирует (`if (input && !stunned)`), значит предсказывать нечего.
    expect(/mine\.stun\s*\|\|\s*!myFacingInit/.test(src('online3d.ts')),
      '⚠ пропала пересинхронизация фейсинга под станом').toBe(true);
  });

  it('⚠ ОТПРАВЛЯЕМ РОВНО ТО, ЧТО НАРИСОВАЛИ — один источник', () => {
    // Второй расчёт в `sendInput` означал бы, что игрок видит один угол, а сервер получает другой:
    // кадр и отправка идут с разной частотой.
    const s = src('online3d.ts');
    const send = /function sendInput\(\): void \{[\s\S]*?\n  \}/.exec(s);
    expect(send, 'sendInput не найден — тест устарел').not.toBe(null);
    expect(/const facing = myFacingInit \? myFacing/.test(send![0]), '⚠ фейсинг считается второй раз').toBe(true);
  });

  it('⭐ предсказанный угол идёт РОВНО в прицел, без отставания', () => {
    // Чистая часть: `facingFrom` с живым прицелом обязана дать точный угол на цель, а не сглаженный.
    const px = 100, pz = -50;
    for (const [ax, az] of [[200, -50], [100, 40], [0, 0]] as [number, number][]) {
      const want = Math.atan2(az - pz, ax - px);
      expect(facingFrom(0, { x: ax, y: az }, px, pz, { x: 0, y: 0 }, true)).toBeCloseTo(want, 9);
    }
  });

  it('⚠ прицел ближе мёртвой зоны — держим прошлый угол, а не дёргаемся', () => {
    const prev = 1.234;
    expect(facingFrom(prev, { x: 100, y: -50 }, 100, -50, { x: 0, y: 0 }, true)).toBe(prev);
  });
});
