import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { facingFrom } from './playerInput.js';

/**
 * ⭐⭐ СВОЙ ФЕЙСИНГ РИСУЕТСЯ ПРЕДСКАЗАННЫМ, А НЕ ЭХОМ СЕРВЕРА.
 *
 * Жалоба: «фейсинг странно работает, как будто чуть в сторону от прицела». ЗАМЕР ПОЗЫ это НЕ
 * подтвердил: в устоявшемся состоянии таз, грудь и верх груди смотрят в прицел с точностью 0.00°.
 * Дело было в ПУТИ числа, а не в позе.
 *
 * Клиент считает фейсинг → шлёт 30 раз в секунду → сервер кладёт его К СЕБЕ КАК ЕСТЬ
 * (`p.facing = input.facing`, он его не вычисляет) → возвращает в снапшоте → рисовали ЭХО.
 * Задержка складывается из периода отправки (33 мс), пинга и периода снапшота (33 мс) — около
 * сотни миллисекунд. На ведении мыши 180°/с это ~17° отставания, и читается ровно как «чуть в сторону».
 *
 * ⚠ ПРЕДСКАЗАНИЕ ЗДЕСЬ ТОЧНОЕ, а не приблизительное: сервер фейсинг не считает, он его принимает.
 * Единственное исключение — оглушение: там ввод не проходит, и ведёт сервер.
 */
const HERE = dirname(fileURLToPath(import.meta.url));
const src = (f: string): string => readFileSync(join(HERE, f), 'utf8');

describe('свой фейсинг', () => {
  it('⭐⭐ СВОЯ КУКЛА НЕ РИСУЕТСЯ ФЕЙСИНГОМ ИЗ СНАПШОТА', () => {
    // ⚠ Мутация «вернуть `mine.facing` в вызов привода» валит это — а именно так и было.
    const s = src('online3d.ts');
    const call = /driveActor\(self,[^;]*?\);/s.exec(s);
    expect(call, 'вызов привода своей куклы не найден — тест устарел').not.toBe(null);
    expect(/mine\.facing/.test(call![0]), '⚠ своя кукла снова рисуется ЭХОМ сервера').toBe(false);
    expect(/myFacing/.test(call![0]), '⚠ своя кукла рисуется не предсказанным углом').toBe(true);
  });

  it('⚠ ПОД СТАНОМ ФЕЙСИНГ ВЕДЁТ СЕРВЕР — иначе оглушённый крутится за мышью', () => {
    // Сервер под станом ввод игнорирует (`if (input && !stunned)`), значит предсказывать нечего.
    expect(/mine\.stun\s*\|\|\s*!myFacingInit/.test(src('online3d.ts')),
      '⚠ пропала пересинхронизация фейсинга под станом').toBe(true);
  });

  it('⚠ ОТПРАВЛЯЕМ РОВНО ТО, ЧТО НАРИСОВАЛИ — один источник', () => {
    // Второй расчёт в отправке (`pumpInput`, L2: сэмплер общий с 2D) означал бы, что игрок видит один угол, а сервер
    // получает другой: кадр и отправка идут с разной частотой.
    const s = src('online3d.ts');
    const send = /function pumpInput\(dt: number\): void \{[\s\S]*?\n  \}/.exec(s);
    expect(send, 'pumpInput не найден — тест устарел').not.toBe(null);
    expect(/const facing = myFacingInit \? myFacing/.test(send![0]), '⚠ фейсинг считается второй раз').toBe(true);
  });

  it('⭐ предсказанный угол идёт РОВНО в прицел, без отставания', () => {
    // Чистая часть: `facingFrom` с живым прицелом обязана дать точный угол на цель, а не сглаженный.
    const px = 100, pz = -50;
    for (const [ax, az] of [[200, -50], [100, 40], [0, 0]] as [number, number][]) {
      const want = Math.atan2(az - pz, ax - px);
      expect(facingFrom(0, { x: ax, y: az }, px, pz, { x: 0, y: 0 }, true)).toBeCloseTo(want, 9);
    }
  });

  it('⚠ курсор РОВНО на персонаже — держим прошлый угол, а не дёргаемся', () => {
    const prev = 1.234;
    expect(facingFrom(prev, { x: 100, y: -50 }, 100, -50, { x: 0, y: 0 }, true)).toBe(prev);
  });

  it('⭐⭐ МЁРТВАЯ ЗОНА МЯГКАЯ: власть курсора гаснет к центру, а на границе шва НЕТ', () => {
    // ⚠ Мутация «жёсткое удержание в зоне» (было до 18.09) валит это: пролетая мимо курсора, игрок входил
    // в зону с одним пеленгом, выходил с развёрнутым, и разворот отдавался ОДНИМ КАДРОМ — ЗАМЕР на проходе
    // в 4 ед: верх груди 2666 / 5068 / 5922 °/с при 60 / 120 / 144 (рост ЛИНЕЙНЫЙ по кадрам = скачок за кадр).
    const D = 10, prev = 0;
    const at = (r: number): number => facingFrom(prev, { x: 0, y: r }, 0, 0, { x: 0, y: 0 }, true, D);
    // Снаружи зоны — РОВНО пеленг (бит в бит как было): курсор строго слева по оси z → +90°.
    expect(at(D + 1e-9)).toBeCloseTo(Math.PI / 2, 9);
    // Шов на самой границе: изнутри подходим к тому же числу.
    expect(at(D - 1e-6)).toBeCloseTo(Math.PI / 2, 5);
    // Внутри — доля власти по расстоянию и МОНОТОННО: чем ближе к центру, тем меньше курсор слышен.
    const half = at(D / 2);
    expect(half, 'в середине зоны курсор ведёт, но не целиком').toBeGreaterThan(0.1);
    expect(half).toBeLessThan(Math.PI / 2 - 0.1);
    for (let r = 0.5; r < D; r += 0.5) expect(at(r), `r=${r}`).toBeLessThan(at(r + 0.5) + 1e-12);
  });

  it('⭐⭐ ВНУТРИ ЗОНЫ НЕТ ОСОБОЙ ТОЧКИ: пеленг РОВНО назад — прицел едет непрерывно, а не щёлкает', () => {
    // ⚠ Мутация «доля кладётся на ВЕКТОР» (примесь прежнего направления длиной `dead − r`, как было до
    // 19.09) валит это: на `r = dead / 2` слагаемые гасят друг друга, `atan2(0, 0)` отдаёт 0, и ЗАМЕР
    // давал 0.00° на r = 4.99 и 5.00 против 180.00° на 5.01 — пол-оборота через бесконечно малый шаг.
    const D = 10, prev = 0;                       // смотрим в +X, курсор РОВНО позади
    const at = (r: number): number => facingFrom(prev, { x: -r, y: 0 }, 0, 0, { x: 0, y: 0 }, true, D);
    // Непрерывность по радиусу: соседние радиусы не имеют права отличаться на градусы.
    let worst = 0, worstR = 0;
    for (let r = 0.01; r < D; r += 0.01) {
      const d = Math.abs(at(r + 0.01) - at(r));
      if (d > worst) { worst = d; worstR = r; }
    }
    expect(worst * 180 / Math.PI, `скачок ${(worst * 180 / Math.PI).toFixed(2)}° около r=${worstR.toFixed(2)}`).toBeLessThan(1);
    // И доля власти курсора та же, что у прежней смеси: ровно `r / dead` от поворота к пеленгу.
    expect(at(D / 2)).toBeCloseTo(Math.PI / 2, 6);
    expect(at(D / 4)).toBeCloseTo(Math.PI / 4, 6);
  });

  it('⭐ ПРОБЕГ РОВНО СКВОЗЬ КУРСОР: разворот прицела не отдаётся одним кадром', () => {
    // ⚠ Та же мутация валит это. ЗАМЕР (80 ед/с, промах 0 ед): 10 800 / 21 600 / 25 920 °/с при
    // 60 / 120 / 144 — РОВНО линейно по частоте кадров (подпись скачка за кадр). Стало 2 746 / 3 727 / 4 030.
    const wrap = (a: number): number => Math.atan2(Math.sin(a), Math.cos(a));
    const worst = (hz: number, miss: number): number => {
      const dt = 1 / hz;
      let f = 0, prev = 0, w = 0;
      for (let i = 0; i <= Math.round(1.2 * hz); i++) {
        f = facingFrom(f, { x: 0, y: miss }, -40 + 80 * i * dt, 0, { x: 0, y: 0 }, true, 10);
        if (i) w = Math.max(w, Math.abs(wrap(f - prev)) * 180 / Math.PI / dt);
        prev = f;
      }
      return w;
    };
    const v = [60, 120, 144].map((hz) => worst(hz, 0));
    expect(Math.max(...v), `сквозь курсор: ${v.map((x) => x.toFixed(0))} °/с`).toBeLessThan(5500);
    expect(Math.max(...v) / Math.min(...v), 'рост с частотой кадров').toBeLessThan(1.8);
    // Промах 0.05 ед — та же особая точка задевается вскользь.
    const u = [60, 120, 144].map((hz) => worst(hz, 0.05));
    expect(Math.max(...u), `промах 0.05 ед: ${u.map((x) => x.toFixed(0))} °/с`).toBeLessThan(5500);
  });
});
