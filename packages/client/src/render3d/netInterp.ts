/**
 * ⭐⭐ СНАПШОТ → ПЛАВНОЕ ДВИЖЕНИЕ: экстраполяция по серверной скорости + рассасывание ошибки.
 *
 * Жалоба: «персонаж чуть-чуть поддёргивается, а с зажатой атакой ещё и ноги дёргаются». ЗАМЕР
 * показал, что виновата не сеть, а способ превращения снапшотов в кадры.
 *
 * КАК БЫЛО: сервер шлёт позицию 30 раз в секунду (лесенкой), клиент ГНАЛСЯ за ней экспоненциальным
 * фильтром (τ = 45 мс), а СКОРОСТЬ для походки считалась разностью этой сглаженной позиции ЗА КАДР.
 * Два следствия, оба замерены на 60 fps при ровном ходе:
 *  • вторая разность отрисованной позиции — **0.37 от шага кадра**, то есть движение не гладкое:
 *    это и есть «поддёргивается». Фильтр не может сделать из лесенки прямую, он лишь размазывает её;
 *  • скорость рябит (0.026…0.05 от полной), и на 144 fps рябь втрое больше — потому что постоянная
 *    фильтра была НА КАДР, а не на секунду.
 *
 * КАК В ИНДУСТРИИ. Догонять последний снапшот фильтром не принято ни в одном сетевом движке: либо
 * интерполяция с буфером и задержкой (Valve, Overwatch — для ЧУЖИХ актёров, задержка ~2 тика), либо
 * dead reckoning — экстраполяция по известной скорости с плавным гашением ошибки (для СВОЕГО, где
 * задержку добавлять нельзя). Здесь взят второй путь: он не добавляет ни кадра лага, а при ровном
 * ходе даёт математически точную прямую.
 *
 * КАК СТАЛО:
 *  • скорость считается ПО ИНТЕРВАЛУ МЕЖДУ СНАПШОТАМИ (0.033 с), а не по кадру — она перестаёт
 *    зависеть от fps и от того, пришёл ли снапшот между кадрами;
 *  • позиция кадра = последняя серверная + скорость × время с её прихода (ограничено `EXTRAP_MAX`,
 *    иначе провал связи унесёт актёра в стену);
 *  • ошибка предсказания не «щёлкает»: в момент нового снапшота запоминается расхождение с тем, что
 *    уже нарисовано, и гасится экспонентой за `ERR_TAU`. Без этого на смене направления был бы рывок.
 *
 * ⭐⭐ 18.09: ЗНАМЕНАТЕЛЬ СКОРОСТИ — ЧАСЫ СЕРВЕРА (`tick`), А НЕ ИНТЕРВАЛ ПРИХОДА. «Интервал между
 * снапшотами» выше — это интервал их ПРИХОДА, а он дрожит вместе с сетью: ЗАМЕР (стенд `torsoJitter`)
 * дал рябь скорости 11.2–11.8 % при дрожании ±5 мс и 0.0 % при ровных приходах. Подробности — у `push`.
 *
 * ⚠ ТЕЛЕПОРТ — НЕ ОШИБКА ПРЕДСКАЗАНИЯ. Переход этажа/рывок/респавн двигают актёра на десятки единиц
 * мгновенно; гасить такое «плавно» значит ехать через полкомнаты. Прыжок больше `TELEPORT` — снап:
 * скорость и ошибка обнуляются.
 */

/** Дальше последнего снапшота не экстраполируем (сек): провал связи не должен уносить актёра. */
export const EXTRAP_MAX = 0.12;
/** За сколько рассасывается ошибка предсказания (сек). */
export const ERR_TAU = 0.08;
/** Сглаживание оценки скорости (сек). Меньше — отзывчивее, больше — ровнее. */
export const VEL_TAU = 0.05;
/** Скачок больше этого (единиц) — телепорт, а не ошибка: снап без сглаживания. */
export const TELEPORT = 120;
/**
 * Сколько СНАПШОТОВ держит окно калибровки «секунд в тике» (см. `push`). Три секунды трафика при 20 Гц.
 *
 * ⭐ МЕРЯЕМ НА ДЛИННОЙ БАЗЕ, А НЕ УСРЕДНЯЕМ КОРОТКИЕ ИНТЕРВАЛЫ. Наклон берётся между САМЫМ СТАРЫМ и самым
 * новым приходом окна, поэтому дрожание всех промежуточных приходов выпадает тождественно, а не «в среднем»:
 * ошибка = (дрожание нового − дрожание старого) / длина окна = ±10 мс / 3.2 с ≈ 0.3 %.
 *
 * ⚠ ПОЧЕМУ НЕ СРЕДНЕЕ ПО ИНТЕРВАЛАМ (как было). При РОВНОЙ каденции (Δтик всегда 1) среднее и само
 * телескопируется — соседние интервалы делят общий приход с разными знаками, — и давало те же доли
 * процента. Но боевая каденция НЕ ровная: сим 30 Гц против рассылки 20 даёт Δтик 2, 1, 2, 1, интервалы
 * делятся на РАЗНЫЕ числа, телескопирование ломается. ЗАМЕР (дрожание ±5 мс, 8 семян): рябь скорости
 * 1.12–1.57 % у среднего против 0.21–0.27 % у длинной базы; на ровных 30 Гц — 0.33 % против 0.32 %.
 * То есть длинная база не хуже нигде, а на настоящей каденции лучше впятеро.
 *
 * ⚠ СМЕНУ ТЕМПА СЕРВЕРА ЛОВИТ НЕ ОКНО, А `TICK_CAL_REJ` (восемь снапшотов, ~0.4 с): длину окна можно
 * выбирать по точности, не платя за неё отзывчивостью.
 */
export const TICK_CAL_N = 64;
/**
 * ⚠ СТОЛЬКО ЗАМЕРОВ ПОДРЯД МИМО ПОЛОСЫ — И КАЛИБРОВКА НАЧИНАЕТСЯ ЗАНОВО (см. `calibrate`).
 *
 * Без этого полоса «не дальше ×2 от текущего» была ЛОВУШКОЙ БЕЗ ВЫХОДА, и в неё попадали два живых случая:
 *  • ЗАСТРЯВШИЙ ПЕРВЫЙ ЗАМЕР. Блок главного потока на старте забега копит сокет-сообщения, и они
 *    разбираются подряд: большой Δтик при почти нулевом Δприхода. ЗАМЕР (Δтик 6, Δприход 2 мс): `tickSec`
 *    садился на 0.33 мс, дальше ВСЕ настоящие замеры шли мимо полосы, скорость молча считалась прежним
 *    путём по приходу — рябь 11.9 % вместо 0.3 %, и НИ ОДИН сторож этого не видел.
 *  • СМЕНА ТЕМПА СЕРВЕРА. `DM_SNAPSHOT_HZ`/`TICK_MS` меняются переменной окружения; 30 → 10 Гц — это ×3,
 *    мимо полосы навсегда. ЗАМЕР: скорость читалась 360 ед/с вместо 120 (втрое) и не поправлялась НИКОГДА.
 * Восемь — это ~0.4 с трафика при 20 Гц: одиночный лаг-спайк (ради которого полоса и заводилась) столько
 * подряд не живёт, а настоящая смена темпа живёт всегда.
 */
export const TICK_CAL_REJ = 8;

export interface ActorAt { x: number; z: number; vx: number; vz: number }

interface Track {
  x: number; z: number; t: number;      // последняя СЕРВЕРНАЯ позиция и время её прихода
  tick: number;                         // номер серверного тика этой позиции (−1 — снапшот его не принёс)
  vx: number; vz: number;               // сглаженная серверная скорость
  ex: number; ez: number; et: number;   // ошибка предсказания на момент `et`
}

export interface NetInterp {
  /**
   * Новый снапшот: серверная позиция актёра на момент ПРИХОДА `t` (сек). Звать РОВНО РАЗ на снапшот.
   *
   * ⭐⭐ `tick` — НОМЕР СЕРВЕРНОГО ТИКА этого снапшота (`WorldSnapshot.tick`), и он чинит рябь скорости.
   *
   * ЗАМЕР (стенд `torsoJitter.test.ts`, 30 Гц, дрожание прихода ±5 мс): при строго равных приходах
   * ошибка оценки скорости 0.0 %, при живом дрожании — 11.2–11.8 %. Вся рябь отсюда: путь делился на
   * интервал МЕЖДУ ПРИХОДАМИ, а ±10 мс на 33 мс — это ±30 % мгновенной оценки (после `VEL_TAU` ~11 %).
   * Рябью живёт всё, что растёт из скорости: `moveMag`, оси бленда, часы клипа, планировщик.
   *
   * Тик — ЧАСЫ СЕРВЕРА, и они ровные: интервал между снапшотами в тиках известен точно, а дрожание сети
   * на него не влияет. Поэтому скорость считается на `Δтик × секунд-в-тике`, а позиция по-прежнему
   * экстраполируется от ПРИХОДА (рисовать надо в клиентском времени).
   *
   * ⚠ СЕКУНД-В-ТИКЕ НЕ КОНСТАНТА, А ЗАМЕР. Клиенту неоткуда знать серверный `TICK_MS`, а вписать «1/30»
   * второй копией значит завести молчаливую поломку: сменят темп сервера — у всех разъедется КАДЕНЦИЯ НОГ,
   * и искать будут в походке. Здесь оно калибруется по самим приходам — НАКЛОНОМ МЕЖДУ КРАЯМИ ОКНА в
   * `TICK_CAL_N` снапшотов (`Δприход / Δтик` на всю его длину): дрожание промежуточных приходов выпадает
   * тождественно, а темп сервера калибровка узнаёт сама (`TICK_CAL_REJ` — и на смене темпа тоже).
   * Пока не откалибровано (первый снапшот) или тик не пришёл — работает прежний путь по приходу.
   *
   * ⚠ СЕРВЕР ШЛЁТ РЕЖЕ, ЧЕМ СЧИТАЕТ: сим 30 Гц (`scheduler.TICK_MS`), рассылка 20 (`room.SNAPSHOT_HZ`),
   * поэтому Δtick между снапшотами ЧЕРЕДУЕТСЯ 2, 1, 2, 1. Это не помеха, а наоборот: только по тику и
   * отличишь длинный интервал от короткого — сгладить сам интервал прихода было бы неверно.
   */
  push(id: string, x: number, z: number, t: number, tick?: number): void;
  /** Что рисовать в момент `t` (сек): позиция с экстраполяцией и гашением ошибки + серверная скорость. */
  at(id: string, t: number): ActorAt;
  /**
   * ⭐⭐ ПОГАСИТЬ ПРЕДСКАЗАНИЕ СКОРОСТИ — для СВОЕГО игрока, когда он отпустил кнопку.
   *
   * Клиент узнаёт об остановке РАНЬШЕ сервера: это его собственный ввод, ждать подтверждения незачем.
   * Пока ждали, предсказание уезжало вперёд, а потом разницу приходилось отдавать — персонаж заметно
   * «сдавал назад» (ЗАМЕР: перелёт 4.5 ед и 1.3 с отката). С гашением по вводу перелёт 0.9, откат 0.18.
   *
   * `rate` — ед/с²: столько же, сколько тормозит сервер (`balance.moveInertia.decel`), либо
   * `Infinity`, если инерции нет и сервер встаёт мгновенно.
   *
   * ⚠ ГАСИМ, А НЕ СНАПИМ: уже нарисованное уходит в ошибку и рассасывается той же экспонентой.
   * Обнулить скорость «в лоб» значило бы дёрнуть картинку назад на весь перелёт разом.
   */
  brake(id: string, rate: number, t: number, dt: number): void;
  /** Забыть актёра (ушёл из снапшота). */
  drop(id: string): void;
  /** Сколько актёров отслеживается — для отладки и тестов. */
  readonly size: number;
  /** Замеренная длительность серверного тика (сек); 0 — ещё не калибровалось (тики не приходят). */
  readonly tickSec: number;
}

export function makeNetInterp(): NetInterp {
  const map = new Map<string, Track>();
  // Калибровка «секунд в тике» — ОБЩАЯ на всех актёров: часы сервера одни, а снапшот несёт один тик на всех.
  // ⚠ И СЧИТАЕТСЯ РОВНО РАЗ НА СНАПШОТ, а не на актёра: в снапшоте их бывают десятки, и брать замер с каждого
  // значило бы забить окно усреднения копиями ОДНОГО интервала — окно на 32 снапшота стало бы окном на один.
  let tickSec = 0, tickN = 0, calTick = -1, calAt = 0, calRej = 0;
  // Окно приходов для длинной базы: кольцо из `TICK_CAL_N` пар (тик, время прихода).
  const ringK = new Float64Array(TICK_CAL_N), ringT = new Float64Array(TICK_CAL_N);
  let ringHead = 0, ringLen = 0;
  const ringPut = (tick: number, t: number): void => {
    ringK[ringHead] = tick; ringT[ringHead] = t;
    ringHead = (ringHead + 1) % TICK_CAL_N; ringLen = Math.min(ringLen + 1, TICK_CAL_N);
  };
  /**
   * Замер «секунд в тике» по ЧУЖОМУ для этой функции входу — потоку снапшотов. Наклон между КРАЯМИ окна
   * (`TICK_CAL_N` снапшотов): дрожание промежуточных приходов не участвует вовсе, см. `TICK_CAL_N`.
   * Выбросы (лаг-спайк, догон сервера) в окно не берём — иначе один провал связи сбил бы масштаб скорости,
   * а с ним каденцию ног у ВСЕХ актёров; но `TICK_CAL_REJ` подряд — это не выброс, а новая правда.
   *
   * ⚠ НА СМЕНЕ ЭТАЖА ТИК СБРАСЫВАЕТСЯ В НОЛЬ (`session.ts`, `w.tick = 0`). Поэтому замер берётся
   * только на РАСТУЩЕМ тике, а откат НАЧИНАЕТ ОКНО ЗАНОВО (иначе база перешагнула бы разрыв и дала бы
   * бессмыслицу); прежнее `tickSec` при этом остаётся в силе, пока новое окно не набрало вторую точку.
   * У самого актёра `dTick` в этот момент отрицателен, и скорость один раз считается прежним путём —
   * по приходу (сторож в `netInterp.test.ts`).
   *
   * ⚠ ЗОВЁТСЯ РАЗ НА АКТЁРА, А РАБОТАЕТ РАЗ НА СНАПШОТ: у второго и дальше актёров того же снапшота
   * `tick === calTick`, и обе ветки ниже мимо — остаётся безобидная переприсвока тех же `calTick`/`calAt`.
   */
  const calibrate = (tick: number, t: number): void => {
    if (tick < 0) return;
    if (calTick >= 0 && tick > calTick) {
      const s = (t - calAt) / (tick - calTick);
      if (s > 1e-4) {
        // Замер берём в окно, если он в полосе (или окна ещё нет). Подряд мимо полосы `TICK_CAL_REJ` раз —
        // это не выброс: окно начинается заново с ЭТОГО интервала, и темп подхватывается новый.
        let put = false;
        if (tickSec <= 0 || (s > tickSec * 0.5 && s < tickSec * 2)) { calRej = 0; put = true; }
        else if (++calRej >= TICK_CAL_REJ) { calRej = 0; ringHead = 0; ringLen = 0; ringPut(calTick, calAt); put = true; }
        if (put) {
          ringPut(tick, t);
          const i0 = (ringHead - ringLen + TICK_CAL_N) % TICK_CAL_N;
          const dk = tick - ringK[i0]!, dtt = t - ringT[i0]!;
          if (dk > 0 && dtt > 1e-4) { tickSec = dtt / dk; tickN = ringLen; }
        }
      }
    } else if (calTick < 0 || tick < calTick) { ringHead = 0; ringLen = 0; ringPut(tick, t); tickN = ringLen; calRej = 0; }
    calTick = tick; calAt = t;
  };
  /** Чистая позиция предсказания без гашения ошибки. */
  const base = (k: Track, t: number): { x: number; z: number } => {
    const dt = Math.min(EXTRAP_MAX, Math.max(0, t - k.t));
    return { x: k.x + k.vx * dt, z: k.z + k.vz * dt };
  };
  return {
    push(id, x, z, t, tick) {
      const tk = tick ?? -1;
      const k = map.get(id);
      if (!k) { calibrate(tk, t); map.set(id, { x, z, t, tick: tk, vx: 0, vz: 0, ex: 0, ez: 0, et: t }); return; }
      const dt = t - k.t;
      const dTick = tk >= 0 && k.tick >= 0 ? tk - k.tick : 0;
      calibrate(tk, t);
      if (Math.hypot(x - k.x, z - k.z) > TELEPORT) {        // телепорт: начинаем с чистого листа
        k.x = x; k.z = z; k.t = t; k.tick = tk; k.vx = 0; k.vz = 0; k.ex = 0; k.ez = 0; k.et = t;
        return;
      }
      // ⚠ РАСХОЖДЕНИЕ СЧИТАЕМ ДО обновления опоры: это то, что УЖЕ нарисовано, минус то, что станет
      // рисоваться теперь. Иначе новый снапшот дёргал бы картинку на величину ошибки предсказания.
      const drawn = this.at(id, t);
      // ⭐ ЗНАМЕНАТЕЛЬ СКОРОСТИ — ВРЕМЯ СЕРВЕРА, а не интервал прихода (см. `push` в интерфейсе).
      // Нет тика или калибровка ещё пуста — прежний путь по приходу.
      const dtV = dTick > 0 && tickN > 1 ? dTick * tickSec : dt;
      if (dt > 1e-4 && dtV > 1e-4) {
        const nvx = (x - k.x) / dtV, nvz = (z - k.z) / dtV;
        // ⚠ Вес фильтра — по ВРЕМЕНИ ПРИХОДА: он про «сколько прошло у клиента с прошлого обновления».
        const a = 1 - Math.exp(-dt / VEL_TAU);
        k.vx += (nvx - k.vx) * a; k.vz += (nvz - k.vz) * a;
      }
      k.x = x; k.z = z; k.t = t; k.tick = tk;
      k.ex = drawn.x - x; k.ez = drawn.z - z; k.et = t;
    },
    at(id, t) {
      const k = map.get(id);
      if (!k) return { x: 0, z: 0, vx: 0, vz: 0 };
      const b = base(k, t);
      const decay = Math.exp(-Math.max(0, t - k.et) / ERR_TAU);
      return { x: b.x + k.ex * decay, z: b.z + k.ez * decay, vx: k.vx, vz: k.vz };
    },
    brake(id, rate, t, dt) {
      const k = map.get(id); if (!k) return;
      const s = Math.hypot(k.vx, k.vz); if (s <= 1e-6) return;
      const drawn = this.at(id, t);
      const f = Math.max(0, s - rate * dt) / s;
      k.vx *= f; k.vz *= f;
      const b = base(k, t);                       // непрерывность: разницу забирает ошибка
      k.ex = drawn.x - b.x; k.ez = drawn.z - b.z; k.et = t;
    },
    drop(id) { map.delete(id); },
    get size() { return map.size; },
    get tickSec() { return tickN > 1 ? tickSec : 0; },
  };
}
