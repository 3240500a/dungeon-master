import { describe, it, expect } from 'vitest';
import { PoseDriver, FOOT_Y } from './pose.js';

/**
 * ⭐ ПЛАНИРОВЩИК ШАГОВ И ЗАЗЕМЛЕНИЕ ЦЕЛЯТ ЛОДЫЖКУ В ОДНУ ВЫСОТУ.
 *
 * Заземление (`footIk.groundFeet`) ставит кость-лодыжку в `SOLE + footLift` — у модели это её
 * собственная высота над подошвой. Планировщик шагов прибивал опорную стопу к голому `FOOT_Y = 1.5`,
 * то есть к высоте лодыжки ПРОЦЕДУРНОГО манекена.
 *
 * ЗАМЕР на рыцаре: лодыжка стоит на 2.916 над своей подошвой, то есть каждый кадр планировщик тянул
 * стопу вниз на 1.416, а заземление вверх на столько же. Глазами — «ходьба дёргается вверх-вниз»;
 * побочно нога почти всё время упиралась в предел досягаемости, и ручки походки переставали
 * что-либо менять (их вклад съедал упор).
 *
 * Сторож проверяет ровно это: высота пола — ПОЛЕ рига, и планировщик им действительно пользуется.
 */
describe('пол для лодыжки — из рига, а не константа', () => {
  /** Один шаг привода на месте: вернуть углы опорной ноги. */
  function stand(footFloor: number): { hip: number; kn: number } {
    const d = new PoseDriver();
    d.footFloor = footFloor;
    d.setMove(0);
    for (let i = 0; i < 12; i++) {            // несколько кадров: планировщик должен устояться
      d.setWorld(0, 0, 0, 0, 0);
      d.update(1 / 60);
    }
    return { hip: d.out.hipL, kn: d.out.knL };
  }

  it('умолчание — процедурная высота, поведение прежнее бит в бит', () => {
    expect(new PoseDriver().footFloor).toBe(FOOT_Y);
  });

  it('⭐ поднятый пол РЕАЛЬНО меняет решение ноги (иначе поле декоративное)', () => {
    const base = stand(FOOT_Y);
    const lifted = stand(FOOT_Y + 1.416);     // замер рыцаря: лодыжка на 2.916 над подошвой
    const d = Math.abs(base.hip - lifted.hip) + Math.abs(base.kn - lifted.kn);
    expect(d, '⚠ планировщик игнорирует пол рига — значит он снова спорит с заземлением').toBeGreaterThan(0.02);
  });

  it('чем выше пол, тем МЕНЬШЕ вытянута нога (монотонно, без скачков)', () => {
    // Поднимаем пол → лодыжка ближе к тазу → колено согнуто сильнее. Проверяем монотонность:
    // немонотонность означала бы, что где-то остался второй, несогласованный пол.
    const kn = [0, 0.5, 1.0, 1.5].map((lift) => stand(FOOT_Y + lift).kn);
    for (let i = 1; i < kn.length; i++) {
      expect(Math.abs(kn[i]!), `шаг ${i}: сгиб колена обязан расти с подъёмом пола`).toBeGreaterThanOrEqual(Math.abs(kn[i - 1]!) - 1e-9);
    }
    expect(Math.abs(kn[kn.length - 1]!) - Math.abs(kn[0]!), 'разница должна быть заметной, а не в шуме').toBeGreaterThan(0.01);
  });
});
