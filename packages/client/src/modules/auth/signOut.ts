import type { App } from '../../core/app.js';
import { logout } from './authApi.js';

/**
 * ⭐ R11-15: ВЫХОД ИЗ АККАУНТА — ОДИН ДЛЯ 2D И ВЕБ-3D. Сессия гаснет НА СЕРВЕРЕ (`POST /api/logout` удаляет её), а не только
 * в этой вкладке: «Выйти из аккаунта» веб-3D раньше лишь стирал `dm:auth`, и токен жил на сервере ещё неделю (срок
 * продлевается на каждом запросе) — у того, кто его успел унести (скопированный запрос, расширение, читающее localStorage),
 * доступ оставался после «выхода» на чужом ПК. Вход страница забывает СРАЗУ (токен для запроса взят до этого), сервер
 * недоступен — всё равно вышли, как было в 2D. Промис — когда запрос выхода отыграл (2D ждёт его перед экраном входа).
 */
export function signOut(app: Pick<App, 'auth' | 'clearAuth'>): Promise<void> {
  const token = app.auth?.token;
  app.clearAuth();
  return token ? logout(token).catch(() => { /* сервер недоступен — всё равно выходим */ }) : Promise.resolve();
}
