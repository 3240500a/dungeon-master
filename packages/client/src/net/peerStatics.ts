import type { PeerInfo } from '@dm/shared';

/**
 * Статика игроков (Ф1.1: имя, класс, макс. HP, радиус, внешность) приходит отдельно от снапшота — кадрами
 * `peerInfo`, `peerJoined` и списком `joined.peers`. Сливается по id: неполный список ничего не стирает.
 *
 * ⭐ R2-03: `joined.peers` — тоже источник. Раньше его не читал никто, а рассылка статики с R1-11 шлёт лишь
 * изменившееся: вошедший позже (и вернувшийся реконнектом) не знал тех, кто сидел в комнате до него, — они
 * рисовались безымянным «воином» с полной полоской HP, пока не сменят снаряжение. Сервер теперь шлёт вошедшему
 * полный `peerInfo`, а клиент вдобавок берёт статику из самого `joined` — ни один из двух путей не одинок.
 */
export function mergePeerStatics(into: Map<string, PeerInfo>, peers: readonly PeerInfo[] | undefined): void {
  for (const pi of peers ?? []) into.set(pi.id, pi);
}
