/**
 * ⭐ R3-08: ТЕМП ОТПРАВКИ ВВОДА — тик сервера, а не кадр рендера.
 *
 * 2D-клиент слал кадр `input` на КАЖДЫЙ кадр Phaser (rAF без потолка FPS), а сервер считал каждый кадр сокета в
 * общий потолок (`limits.wsFrames`: всплеск 120, поток 80/с). На мониторе 90 Гц соединение рвалось кодом 4008 через
 * 11 с, на 144 Гц — через 2 с, на 240 Гц — меньше чем через секунду; в подземелье герой при этом уходил в грейс.
 * Сервер всё равно берёт последний ввод за тик (30 Гц), так что лишние кадры были чистой потерей. Теперь ввод идёт
 * не чаще тика — как у веб-3D (`INPUT_PERIOD` в `online3d.ts`), — а ФРОНТ нажатия (рывок, тогл, первый удар, [E])
 * уходит в том же кадре: между отправками он бы потерялся.
 *
 * Остаток времени переносится на следующую отправку, а не обнуляется: при 60 Гц с дрожью кадра обнуление давало бы
 * то 30, то 20 Гц. Чистая логика без Phaser — её гоняет node-тест.
 */

/** Период отправки ввода, мс: тик сервера (30 Гц). */
export const INPUT_PERIOD_MS = 1000 / 30;

export class InputPacer {
  /** Время с последней отправки, мс. Стартует с полного периода — первый кадр уходит сразу. */
  private acc = INPUT_PERIOD_MS;

  /**
   * Слать ли ввод в этом кадре. `dt` — мс с прошлого кадра; `edge` — фронт нажатия: шлём, не дожидаясь периода.
   * Остаток — меньше периода: после долгого кадра (вкладка в фоне, фриз) ввод не уходит пачкой подряд.
   */
  due(dt: number, edge = false): boolean {
    this.acc += Number.isFinite(dt) && dt > 0 ? dt : 0;
    if (this.acc < INPUT_PERIOD_MS && !edge) return false;
    this.acc = this.acc >= INPUT_PERIOD_MS ? (this.acc - INPUT_PERIOD_MS) % INPUT_PERIOD_MS : 0;
    return true;
  }
}
