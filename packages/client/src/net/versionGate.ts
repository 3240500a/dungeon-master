import { PROTOCOL_VERSION } from '@dm/shared';
import { buildDiffers } from './staleBuild.js';

/**
 * ⭐ D3: ОДНО РУКОПОЖАТИЕ ВЕРСИЙ — ОДНО ПРАВИЛО «ВКЛАДКА СТАРШЕ СЕРВЕРА» НА ОБА ВЕБ-КЛИЕНТА.
 *
 * С L2 / R3-25 деплой не перезагружает вкладку: она переподключается сама и живёт со старым бандлом. Правило чинили по кускам, и каждый кусок
 * жил в своём месте: версию протокола сверял поток входа (`EntryFlow`), штамп сборки — подписка `App` на `joined` (R18-08; 2D-сцена её снимала —
 * R19-02), перечитывание конфига на входе — обработчик каждого клиента (`onJoined` 2D-сцены и веб-3D), негодный конфиг (R7-14) и разобранный
 * «не в то же» (R16 C-07) говорили сами из `syncConfig`, а отказ «Цена изменилась» решал по третьему правилу (`rereadCannotHelp`). Итог — две
 * строки «перезагрузите» на один вход (протокол + конфиг), молчание при переподключении, если 2D-сцена сняла подписку, и штамп, считавшийся по
 * сырым концам строк (R19-06).
 *
 * Теперь правило одно и живёт ЗДЕСЬ; `App` зовёт его из своих подписок (оба клиента строят один `App`, сцены в сверку не вмешиваются):
 *  • ВХОД (`joined`, КАЖДЫЙ — и после потери связи): сервер шлёт версию протокола `v`, штамп сборки `build` (хэш исходников shared, концы
 *    строк не в счёт) и ревизию конфига комнаты `cfgRev`. Код не тот (протокол или штамп) — «перезагрузите» сразу. Ревизия не та (или её нет,
 *    или конфиг сервера вкладка не разбирает) — конфиг перечитывается ОДИН раз; не разобрала его (R7-14) или разобрала не в то же (R16 C-07) —
 *    «перезагрузите». На один вход — РОВНО ОДНА строка, сколько бы причин ни сошлось; вход без причин — ни одной.
 *  • ОТКАЗ «Цена изменилась» (согласие на цену, конфиг или сборку не сошлось): конфиг перечитывается ОДИН раз, и только потом — решение. Лёг
 *    новый конфиг — отказ им объяснён, молчим (окна уже перерисованы). Нет — и вкладка старше сервера (код или конфиг) — «перезагрузите», не
 *    чаще `REFUSAL_REPEAT_MS` (зажатый клик — одна строка). Вкладка не старше (гонка двойного клика той же сборки) — молчим: перезагрузка не поможет.
 *  • ЛЕНИВЫЙ КУСОК СБОРКИ НЕ ЗАГРУЗИЛСЯ (R10-12, `staleBuild.ts`) — код вкладки старше: «перезагрузите» (с тем же пределом повтора), и дальше
 *    отказы ценой — тоже.
 * Тупика нет: отказ, который перечитывание не лечит, всегда кончается подсказкой; ложной подсказки нет: без расхождения версий она не звучит.
 *
 * Чистый класс без DOM и сети — его гоняют node-тесты (`versionGate.test.ts`), а оба клиента — через `App` (`scenes/OnlineScene.test.ts`,
 * фаззер B3 с профилем «устаревшая сборка / устаревший конфиг»).
 */

/** Строка игроку: вкладка старше сервера (код, протокол или конфиг) — перезагрузить страницу. Одна на все причины. */
export const PROTOCOL_STALE = 'Сервер обновился — перезагрузите страницу (F5): часть действий в этой вкладке может не работать';

/** R4-24: один и тот же отказ команды в лог — не чаще раза за это время, мс; и «перезагрузите» на отказ — так же (R16 C-07, R18-08, D3). */
export const REFUSAL_REPEAT_MS = 2000;

/**
 * Итог перечитывания конфига сервера (`App.syncConfig`):
 *  • `fresh` — лёг новый конфиг сервера, разобран в то же;
 *  • `same` — тот же конфиг (304);
 *  • `broken` — конфиг сервера вкладка не разбирает (R7-14: прежний цел) или разобрала не в то же (R16 C-07: схема вкладки старше);
 *  • `failed` — сервер не ответил (или мост редактора — сети нет вовсе);
 *  • `overtaken` — ответ обогнал следующий запрос: рассудит он.
 */
export type ConfigRead = 'fresh' | 'same' | 'broken' | 'failed' | 'overtaken';

/** Что сервер назвал в рукопожатии (кадр `joined`). Нет поля — сервер старше него, сравнивать нечего. */
export interface ServerVersion { v?: number; build?: string; cfgRev?: string }

export interface VersionGateDeps {
  /** Перечитать конфиг сервера (`App.syncConfig`) — один раз на вход или отказ. */
  reread(): Promise<ConfigRead>;
  /** Ревизия согласия вкладки — «с какого конфига сервера нарисованы окна» (`App.configRevision`). */
  configRevision(): string;
  /** Вкладка не разбирает конфиг сервера (R7-14) или разобрала его не в то же (R16 C-07) — по последнему перечитыванию. */
  configUnreadable(): boolean;
  /** Сказать игроку `PROTOCOL_STALE` (строкой в лог игры). */
  tell(): void;
  /** Версия протокола вкладки (тесту — своя). */
  protocol?: number;
  /** Код вкладки не той сборки, что назвал сервер (`staleBuild.buildDiffers`; тесту — своё). */
  buildDiffers?: (server: string | undefined) => boolean;
  /** Часы, мс (тесту — свои). */
  now?: () => number;
}

export class VersionGate {
  /** Последнее рукопожатие (null — входа ещё не было). */
  private server: ServerVersion | null = null;
  /** Номер входа: сверка входа, обогнанная следующим входом, решения не выносит. */
  private joinSeq = 0;
  /** Номер входа, на котором «перезагрузите» уже сказано (одна строка на вход). */
  private toldJoin = 0;
  /** Когда «перезагрузите» звучало последний раз — предел повтора на отказах. */
  private toldAt = -Infinity;
  /** Ленивый кусок сборки не загрузился (R10-12) — код вкладки старше, что бы ни назвал сервер. */
  private chunkStale = false;

  constructor(private readonly deps: VersionGateDeps) { }

  private now(): number { return this.deps.now?.() ?? Date.now(); }

  /** КОД вкладки старше сервера: другая версия протокола, чужой штамп сборки (по последнему рукопожатию) или не загрузился кусок сборки. */
  codeStale(): boolean {
    if (this.chunkStale) return true;
    const s = this.server;
    if (!s) return false;
    const protocol = this.deps.protocol ?? PROTOCOL_VERSION;
    return (typeof s.v === 'number' && s.v !== protocol) || (this.deps.buildDiffers ?? buildDiffers)(s.build);
  }

  /** Вкладка старше сервера — кодом или конфигом (его она не разбирает): перечитывание не поможет, поможет перезагрузка. */
  stale(): boolean { return this.codeStale() || this.deps.configUnreadable(); }

  /**
   * Вход в мир (кадр `joined`) — рукопожатие. Код не тот — «перезагрузите» сразу; конфиг перечитывается, если ревизия сервера не та, что у
   * вкладки (или её нет, или прежний конфиг сервера вкладка не разобрала), и после — «перезагрузите», если вкладка старше. На вход — одна строка.
   */
  async joined(f: ServerVersion): Promise<void> {
    const seq = ++this.joinSeq;
    this.server = { v: f.v, build: f.build, cfgRev: f.cfgRev };
    if (this.codeStale()) this.sayOnJoin(seq);   // перечитывание конфига код не догонит — не ждём его
    if (!f.cfgRev || f.cfgRev !== this.deps.configRevision() || this.deps.configUnreadable()) await this.deps.reread();
    if (seq !== this.joinSeq) return;   // следующий вход рассудит сам
    if (this.stale()) this.sayOnJoin(seq);
  }

  /**
   * Отказ «Цена изменилась» (согласие на цену, конфиг или сборку не сошлось). Конфиг перечитывается ОДИН раз; лёг новый (или ответ обогнан
   * следующим перечитыванием — рассудит оно) — отказ объяснён, молчим. Иначе вкладка старше сервера — «перезагрузите» (не чаще предела повтора).
   */
  async refused(): Promise<void> {
    const r = await this.deps.reread();
    if (r === 'fresh' || r === 'overtaken') return;
    if (this.stale()) this.sayAgain();
  }

  /** Ленивый кусок сборки не загрузился (R10-12): код вкладки старше — «перезагрузите», и дальше отказы ценой — тоже. */
  chunkFailed(): void {
    this.chunkStale = true;
    this.sayAgain();
  }

  private sayOnJoin(seq: number): void {
    if (this.toldJoin === seq) return;
    this.toldJoin = seq;
    this.toldAt = this.now();
    this.deps.tell();
  }

  private sayAgain(): void {
    const now = this.now();
    if (now - this.toldAt < REFUSAL_REPEAT_MS) return;
    this.toldAt = now;
    this.deps.tell();
  }
}
