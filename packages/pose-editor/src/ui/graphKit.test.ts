import { describe, it, expect } from 'vitest';
import { clickTracker } from './graphKit.js';

/**
 * ВХОД ВНУТРЬ УЗЛА ПО ДВОЙНОМУ КЛИКУ.
 *
 * Поймано живьём: «жму два раза, ничего не происходит». Причина не в порогах, а в том, что событие
 * `dblclick` здесь не приходит вовсе — первый клик перерисовывает холст, узел пересоздаётся, и у
 * пары кликов нет общего элемента. Проверить это тестом нельзя (DOM-окружения в наборе нет), но
 * можно проверить сам счётчик, который заменил событие, — и записать рядом, почему он существует.
 *
 * ⚠ Синтетический `dblclick`, посланный прямо на узел, проходит прекрасно. Первая проверка была
 * именно такой и ничего не поймала: тест «работает», а мышью не работает.
 */
describe('двойной клик по узлу', () => {
  it('два клика подряд по одному узлу — вход', () => {
    const c = clickTracker(400);
    expect(c.hit('a', 1000)).toBe('select');
    expect(c.hit('a', 1200)).toBe('enter');
  });

  it('медленная пара — это два выбора, а не вход', () => {
    const c = clickTracker(400);
    expect(c.hit('a', 1000)).toBe('select');
    expect(c.hit('a', 1500)).toBe('select');
  });

  it('быстро, но по РАЗНЫМ узлам — выбор', () => {
    const c = clickTracker(400);
    expect(c.hit('a', 1000)).toBe('select');
    expect(c.hit('b', 1050)).toBe('select');
  });

  it('третий клик подряд не считается ещё одним входом', () => {
    const c = clickTracker(400);
    c.hit('a', 1000);
    expect(c.hit('a', 1100)).toBe('enter');
    expect(c.hit('a', 1200), 'иначе тройной клик проваливался бы на два уровня вглубь').toBe('select');
  });

  it('перетаскивание сбрасывает счётчик: тащить — не кликать', () => {
    const c = clickTracker(400);
    c.hit('a', 1000);
    c.reset();
    expect(c.hit('a', 1100)).toBe('select');
  });

  it('первый клик за всю жизнь холста — всегда выбор', () => {
    expect(clickTracker(400).hit('a', 0)).toBe('select');
  });
});
