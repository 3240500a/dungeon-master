/**
 * ⭐⭐ ПЕРЕНОС ВЕСА (помощь баланса) — ЧИСТОЕ ЯДРО.
 *
 * Жалоба: «правлю позы у загруженной анимации, а таз улетает в бок и корёжит позу». ЗАМЕР в живом
 * редакторе (воин, мах ногой — одна стопа в воздухе) на каждую правку:
 *
 * | правка | кость X | записано в `balanceOff` | ЖЕЛАНИЕ (сама поза) |
 * |---|---|---|---|
 * | 1 | −1.74 | −1.74 | 0.00 |
 * | 2 | −3.48 | −1.74 | −1.74 |
 * | 3 | −5.22 | −1.74 | −3.48 |
 * | 5 | −8.62 | −1.74 | −6.88 |
 *
 * ДВЕ ПРИЧИНЫ, и обе здесь лечатся.
 *
 * **1. Помощь не помнила, что уже сделала.** Запись сдвига обнулялась в начале, а САМ СДВИГ оставался
 * в кости. Дальше `желание = кость − запись` недовычитало, и сдвиг въедался в авторскую позу —
 * по 1.74 за правку, без предела (потолок `BAL_MAX` считался ЗА ВЫЗОВ, а не за позу). Лечится
 * РЕБЕЙЗОМ: сперва снять прошлый сдвиг, потом решать заново. Тогда правка идёт от авторской позы,
 * а не от предыдущего промаха, и повтор даёт ТОТ ЖЕ ответ.
 *
 * **2. Опора ехала вместе с тазом — цель убегала ровно со скоростью погони.** ЗАМЕР: двигаем таз на
 * +3 и +6, «ЦМ минус центр опоры» = **4.00 / 4.00 / 4.00**. Стопы — дети таза, и пока ноги не
 * доре́шиваются, они едут с ним один к одному. То есть сдвиг НИЧЕГО не исправлял, а displacement
 * оставался. Лечится проверкой «помогло ли»: шаг остаётся, только если зазор реально уменьшился;
 * не уменьшился — откат, и помощь честно ничего не делает.
 *
 * ⚠ Ядро вынесено сюда из `pose-editor.ts` не ради красоты: в редакторе оно живёт среди DOM и
 * three-сцены, а такой файл в node-vitest не импортируется вовсе — сторожа было бы не написать.
 * Мир задаётся тремя замыкающими функциями, поэтому тест подсовывает СВОЙ мир: и «стопы едут с
 * тазом», и «стопы прибиты».
 */

/** Как помощь видит мир. Все величины — в плане (XZ), в единицах сцены. */
export interface BalanceProbe {
  /** Центр масс СЕЙЧАС — после всех уже применённых сдвигов. */
  com(): { x: number; z: number };
  /** Опора в плане СЕЙЧАС; `null` — стоять не на чем, помощь молчит. */
  sup(): { x0: number; x1: number; z0: number; z1: number } | null;
  /** Сдвинуть таз на (dx, dz) и пересчитать мир. */
  move(dx: number, dz: number): void;
}

export const BAL_MARGIN = 0.75;    // целимся не в край опоры, а внутрь неё
export const BAL_TRANSFER = 0.65;  // доля массы выше таза: сдвинув таз на X, центр масс едет примерно на 0.65X
export const BAL_MAX = 9;          // дальше таз не едет — это уже шаг, а не перенос веса
export const BAL_EPS = 0.05;       // мельче этого не двигаем и «улучшением» не считаем

const clamp = (v: number, a: number, b: number): number => (v < a ? a : v > b ? b : v);

/**
 * Решить перенос веса ОТ АВТОРСКОЙ ПОЗЫ и вернуть сдвиг, который остался в кости.
 *
 * `prev` — сдвиг, применённый прошлым решением (он будет снят первым делом). Вызывающий ОБЯЗАН
 * звать это и когда помощь выключена (`weightShift` = 0): иначе прошлый сдвиг останется в кости
 * навсегда, и выключатель ничего не выключит.
 */
export function solveBalance(p: BalanceProbe, weightShift: number, prev: { x: number; z: number }): { x: number; z: number } {
  if (prev.x !== 0 || prev.z !== 0) p.move(-prev.x, -prev.z);          // РЕБЕЙЗ: решаем от авторской позы
  const off = { x: 0, z: 0 };
  if (weightShift <= 0) return off;

  /** Насколько ЦМ вне цели (0 — уже над опорой). */
  const gap = (): { x: number; z: number } | null => {
    const s = p.sup(); if (!s) return null;
    const c = p.com();
    const ix = (s.x1 - s.x0) * (1 - BAL_MARGIN) * 0.5, iz = (s.z1 - s.z0) * (1 - BAL_MARGIN) * 0.5;
    return { x: clamp(c.x, s.x0 + ix, s.x1 - ix) - c.x, z: clamp(c.z, s.z0 + iz, s.z1 - iz) - c.z };
  };
  const len = (g: { x: number; z: number }): number => Math.hypot(g.x, g.z);

  for (let it = 0; it < 2; it++) {
    const g = gap(); if (!g) break;
    const dx = g.x / BAL_TRANSFER * weightShift, dz = g.z / BAL_TRANSFER * weightShift;
    if (Math.hypot(dx, dz) < BAL_EPS) break;
    const nx = clamp(off.x + dx, -BAL_MAX, BAL_MAX), nz = clamp(off.z + dz, -BAL_MAX, BAL_MAX);
    p.move(nx - off.x, nz - off.z);
    const after = gap();
    // ⚠ ШАГ ОСТАЁТСЯ, ТОЛЬКО ЕСЛИ ПОМОГ. Стопы — дети таза: пока ноги не доре́шиваются, опора едет
    // с тазом один к одному, зазор не меняется, и «помощь» превращается в чистое смещение позы.
    if (!after || len(after) >= len(g) - BAL_EPS) { p.move(off.x - nx, off.z - nz); break; }
    off.x = nx; off.z = nz;
  }
  return off;
}
