/**
 * ⭐⭐ КАКОЙ УДАР ИГРАТЬ СЛЕДУЮЩИМ — порядок плюс разнообразие.
 *
 * Жалоба: «если зажать мышку, он повторяет один и тот же удар, не чередует». ПРИЧИНА была
 * арифметическая: счётчик пула крутили ДВА источника — автосцепка по окну комбо и настоящий свинг
 * сервера, — и на каждый цикл он прибавлялся ДВАЖДЫ. На пуле из двух клипов «+2» это тождество:
 * всегда один и тот же удар. Плюс счётчик прибавлялся даже тогда, когда свинг был подавлен
 * перехватом (`COMBO_REGRAB`) и клип не запускался вовсе — то есть удар «расходовался» вхолостую.
 *
 * Лечится не подкруткой счётчика, а сменой модели: **состояние — это ПОСЛЕДНИЙ СЫГРАННЫЙ КЛИП,
 * а не номер в счётчике**. Тогда неважно, кто спрашивает и сколько раз: ответ всегда «следующий
 * после того, что реально играло».
 *
 * ⚠ ХРАНИМ ИМЯ, А НЕ ИНДЕКС. Пул меняется на ходу: у скила свои `poseClips`, у базовой атаки — все
 * `hit_*` оружия, и смена оружия меняет и длину, и состав. Индекс в таком пуле означает разное в
 * разные моменты, а имя — всегда одно и то же.
 */

/**
 * Индекс следующего удара в пуле. `-1` — пул пуст.
 *
 * Порядок по кругу + шанс `vary` уйти на случайный ДРУГОЙ удар, чтобы цепочка не читалась как
 * заученная. ⚠ Случайность имеет смысл только с ТРЁХ клипов: на двух строгое чередование уже даёт
 * максимум разнообразия, а «случайный другой» там может быть только предыдущим — то есть повтором.
 * Поэтому на паре шанс сознательно не действует.
 *
 * ⚠ ПОДРЯД ОДИН И ТОТ ЖЕ УДАР НЕ ВЫПАДАЕТ НИКОГДА (пока в пуле есть из чего выбрать): повтор — это
 * ровно то, на что жалуются, и отдавать его на волю случая нельзя.
 */
export function pickAttack(pool: readonly string[], last: string | null, vary: number, rnd: () => number = Math.random): number {
  const n = pool.length;
  if (n === 0) return -1;
  if (n === 1) return 0;
  const li = last === null ? -1 : pool.indexOf(last);
  const next = (li + 1) % n;                       // нет прошлого (li = −1) → начинаем с первого
  if (n < 3 || vary <= 0 || rnd() >= vary) return next;
  // Отклонение: любой удар, кроме только что сыгранного И кроме очередного по порядку.
  const alt: number[] = [];
  for (let i = 0; i < n; i++) if (i !== li && i !== next) alt.push(i);
  if (!alt.length) return next;
  return alt[Math.min(alt.length - 1, Math.floor(rnd() * alt.length))]!;
}

/**
 * Доля ударов, уходящих из строгого порядка (0 — всегда по кругу, 1 — всегда вразнобой).
 *
 * Треть выбрана намеренно: последовательность остаётся ЧИТАЕМОЙ (глаз ловит, что удары идут по
 * кругу), но не заученной. На пуле меньше трёх клипов число ни на что не влияет — см. `pickAttack`.
 */
export const ATTACK_VARY = 1 / 3;
