/**
 * Boot редактора конфигов: СНАЧАЛА вход администратора, потом сам редактор.
 *
 * Раньше вход спрашивался лениво — когда человек жал «Применить» и получал 401. То есть страница
 * открывалась кому угодно, кто дотянулся до порта, а отказ прилетал уже после правки. Теперь
 * инструмент не показывается, пока не вошли админом.
 *
 * `main.ts` не выносит проверку сам, потому что тянет на себя всё дерево редактора уже на импорте
 * (fetch конфига, первый `render()`). Отдельный boot — единственное место, где можно встать ДО этого.
 * Тот же приём, что у поз-редактора (`render3d/pose-editor-boot.ts`).
 */
import { ensureAdmin } from '@dm/client/devAuth.js';

void (async (): Promise<void> => {
  // `null` = сервер не поднят. Не запираем: без сервера редактор всё равно показывает встроенные
  // дефолты и ничего сохранить не может — сервер сам откажет, когда поднимется.
  const me = await ensureAdmin();
  if (!me) console.warn('[editor] сервер недоступен — показаны встроенные дефолты, сохранить не выйдет');
  await import('./main.js');
})();
