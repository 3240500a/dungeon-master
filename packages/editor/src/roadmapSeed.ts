/** Свежее наполнение = снимок + все правки. Первое открытие вкладки видит то же, что обновлённая копия. */
export const SEED = (): RoadmapDoc => {
  const d = BASE_SEED();
  migrateRoadmap(d);
  return d;
};

const findItem = (doc: RoadmapDoc, id: string): Item | undefined => {
  for (const m of doc.milestones) { const it = m.items.find((x) => x.id === id); if (it) return it; }
  return undefined;
};

/** Отметить сделанным. Счётчики не трогаем — они меряют себя сами. Заметку не перезаписываем, если своя уже есть. */
function markDone(doc: RoadmapDoc, id: string, note?: string): void {
  const it = findItem(doc, id);
  if (!it) return;                               // пункт удалили руками — не воскрешаем
  if (!isCounter(it)) it.done = true;
  if (note && !it.note) it.note = note;
}

/** Заметка без галки — для частично сделанного. Свою заметку пользователя не перезаписываем. */
function noteOnly(doc: RoadmapDoc, id: string, note: string): void {
  const it = findItem(doc, id);
  if (it && !it.note) it.note = note;
}

/** Добавить пункт в веху, если его там ещё нет (по id). Веху удалили руками — не воскрешаем. */
function addItem(doc: RoadmapDoc, milestoneId: string, item: Item): void {
  const m = doc.milestones.find((x) => x.id === milestoneId);
  if (!m || findItem(doc, item.id)) return;
  m.items.push({ ...item });                   // копия: документ правится в UI, а константа правки должна остаться целой
}

/** Переименовать, только если название всё ещё исходное: свою формулировку пользователя не затираем. */
function retitle(doc: RoadmapDoc, id: string, from: string, to: string): void {
  const it = findItem(doc, id);
  if (it && it.title === from) it.title = to;
}


