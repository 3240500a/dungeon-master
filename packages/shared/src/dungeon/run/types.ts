import type { FloorAlgoParams, RunNodeType, FloorRole, FloorFeatures } from '../../config/schemas.js';

/**
 * Контракты генератора забегов v2 (headless). Два слоя:
 *  - RunPlan (макро): ветвящийся слоистый граф узлов-этажей (см. generateRunPlan).
 *  - FloorSpec (микро): детерминированная спецификация геометрии одного узла (см. generateFloor).
 * Всё детерминировано от `RunConfig.seed` — граф НЕ сохраняется, а регенерируется (как этаж из seed^depth).
 */

/** Полная спецификация одного этажа: биом + выбранный этаж + алгоритм/параметры + сид + модификаторы. */
export interface FloorSpec {
  biomeId: string;
  /** id выбранного конфига этажа (из `floors`) — трассировка/редактор. */
  floorId: string;
  /** Роль выбранного этажа (combat/elite/boss/treasure/…). */
  role: FloorRole;
  /** Фичи этажа (портал/сундук/лавка/босс-комната/чемпионы/сокровищницы). */
  features: FloorFeatures;
  /** Множитель плотности пачек. */
  packDensity: number;
  /** Тайлсет (с учётом variants биома по глубине). */
  tileset: string;
  algoParams: FloorAlgoParams;
  /** Сид именно этого этажа (детерминирован от сида забега и узла). */
  seed: number;
  /** id модификаторов (run + node), влияющих на этот этаж. Применение к спавну/луту — Ф4. */
  modifiers: string[];
  /** Число выходов на следующие этажи (= число исходящих рёбер узла; finale = 0). */
  exitCount: number;
  /** Гейтить ли выход замком дверь↔рычаг (только boss-этажи; простые — false). */
  locked: boolean;
  /** Особый тип этажа: 'town' (rest-узел — портал в город, без монстров; сундук — в самом городе, R7-11) | 'normal'. */
  kind: 'normal' | 'town';
  /** ⭐ 08.10: биом без процедурных колонн (`biomes[].pillars`) — только `false`, иначе поля нет. */
  pillars?: false;
  /** ⭐ 08.10: биом без процедурных стоячих факелов (`biomes[].torches`) — только `false`, иначе поля нет. */
  torches?: false;
}

/**
 * Направленное ребро к узлу следующего слоя.
 * ⚠⚠ 13.10 (Г2): ребро ПОСЛЕДНЕГО слоя окна (`RunWindow`) смотрит за его край — узла с этим id в `RunPlan.nodes`
 * нет. Так и задумано: число выходов этажа = число рёбер, и обрезка рёбер по краю окна делала бы один и тот же узел
 * разным (а край — тупиком). Читатель, уходя за край, достраивает слой сам (`Room.enterNode`, `runSessionSim`).
 */
export interface RunEdge {
  to: string;
}

/**
 * ⭐⭐ 13.10 (Г2, Р2): ОКНО СЛОЁВ ГРАФА — глубины включительно. Спуск бесконечен, целого графа не существует:
 * `generateRunPlan` строит ровно эти слои, и слой 500 стоит столько же, сколько слой 1 (у каждого свой сид от
 * глубины, Р1). Умолчание — `{ from: 1, to: 1 + balance.dungeonAccess.lookahead }`.
 */
export interface RunWindow {
  from: number;
  to: number;
}

/** Узел забега = один этаж (или город-rest). */
export interface RunNode {
  id: string;
  type: RunNodeType;
  /** Слой в графе: 0 = start. Растёт вглубь. */
  depth: number;
  /** Индекс внутри слоя (для раскладки схемы). */
  lane: number;
  biomeId: string;
  floorSpec: FloorSpec;
  /** id узловых модификаторов (affliction/boon) — «реклама вперёд» на схеме. */
  modifiers: string[];
  /** Куда можно пойти дальше (узлы следующего достижимого слоя). */
  edges: RunEdge[];
  /**
   * ⭐⭐ Г8-2 (15.10): РАНГ БОССА — только у боссового узла (`type: 'boss'`), иначе поля нет. Решает лестница полосы
   * (`balance.dungeonAccess.bossLadder`): мини / крепкий / актовый. По нему заселение берёт надбавку уровня и
   * множитель жизни (`bossRanks`), а карта забега может подписать «актовый».
   * ⚠ Поле ОПЦИОНАЛЬНОЕ и добавочное: кадр `runPlan` старого клиента его просто не читает.
   */
  bossRank?: BossRank;
}

/** ⭐ Г8-2: ранги боссов лестницы — мини (середина ступени), крепкий, актовый (конец круга). */
export type BossRank = 'mini' | 'strong' | 'act';

/**
 * Готовая структура забега — ОКНО слоёв графа (⭐⭐ Г2: спуск бесконечен, целого графа нет).
 * ⚠ `finaleId` УДАЛЁН (Р3): финального узла генератор больше не ставит. Забег кончается смертью или уходом в город
 * через портал привала (`kind: 'town'`), а не «пройденным финалом».
 */
export interface RunPlan {
  biomeId: string;
  /** id тира сложности (из difficulties). */
  tier: string;
  seed: number;
  /** Вход в окно = нулевая полоса его первого слоя (`n{from}_0`). */
  startId: string;
  nodes: RunNode[];
  /** Активные на весь забег модификаторы (выбраны в алтаре). */
  runModifiers: string[];
}

/**
 * Вход генератора структуры = настройки алтаря. Необязательные поля переопределяют форму забега из баланса
 * (`balance.dungeonAccess`); отсутствующие берутся оттуда же.
 *
 * ⚠ Ф1 (16.10): `templateId` СНЯТ — шаблона забега больше нет (растворён в балансе), и забег больше не ссылается
 * на строку, которой не существует.
 */
export interface RunConfig {
  biomeId: string;
  tier: string;
  seed: number;
  /**
   * ⭐ R9-01: личность забега (`randomUUID`, ставит сервер на старте) — ключ свода его записей в базе (`run_ledger`): что
   * взято на узлах, принадлежит ЗАБЕГУ, а не тому, у кого ещё жива копия. Граф и этажи от неё не зависят. Нет (старый сейв,
   * сим, редактор) — ключ из сида и того, из чего пересобирается граф.
   */
  id?: string;
  /**
   * ⭐ R14-10: КЛЮЧ ЭТАЖЕЙ ЗАБЕГА (128 бит, ставит сервер на старте, `Room.buildRunConfig`) — сид этажа узла у сервера берётся из него
   * (`runPlanOf` сервера), а не из сида забега: граф (и сид забега, который по нему подбирается) клиенту виден, а этажи наперёд (сундуки
   * развилки) собираться не должны. Клиенту не уходит, как и `seed`. Нет (старый сейв, сим, редактор) — этажи от сида забега.
   */
  floorKey?: string;
  /**
   * ⚠⚠ 13.10 (Г2, Р3): `length` и `returnEvery` УДАЛЕНЫ ОТСЮДА. Длины у забега больше нет (спуск бесконечен, слои
   * строятся окном), а каденция привала — одно число баланса на всю игру (`balance.dungeonAccess.waypointStep`), не
   * переопределяемое забегом: иначе метка перестала бы быть чистой функцией глубины. В сейвах старых забегов поля
   * могли лежать — схема сейва их молча отбрасывает (никто их не читал бы).
   */
  /** Максимальная ширина слоя; иначе — из шаблона. */
  widthMax?: number;
  branching?: number;
  /**
   * ⭐⭐ Г8-2 (15.10): БЫВАЮТ ЛИ В ЗАБЕГЕ БОССЫ. Где они стоят и какой силы — решает лестница полосы
   * (`balance.dungeonAccess.bossLadder`), одна на игру; прежнее `bossEvery` (каденция забега) снято: с ним
   * каденция и цикл контента жили бы врознь, и во втором круге боссы встали бы не там, где в первом.
   * ⚠ В сейвах старых забегов `bossEvery` мог лежать — схема сейва его молча отбрасывает, читателя нет.
   */
  bosses?: boolean;
  nodeTypeWeights?: Record<string, number>;
  /**
   * Мощь персонажа-игрока = эфф. уровень (уровень + гир + пассивы).
   * ⚠⚠ 13.10 (Г1): ПОЛЕ НИКТО НЕ ЧИТАЕТ. «Влияет на уровни монстров» — ИСТОРИЯ: уровень решает одна глубина
   * (`floorMonsterLevel`), `generateRunPlan` эту мощь не смотрит, `sameRun` её не сравнивает (отпечаток забега —
   * сид/шаблон/биом/тир/модификаторы). Пишет её только ползунок «Забеги v2» редактора, да zod-схема сейва её
   * пропускает. Не удалено, потому что лежит в сейвах и в колонке Postgres (удаление = миграция).
   */
  power?: number;
  /** Выбранные в алтаре run-модификаторы (scope:'run'). */
  modifiers: string[];
}

/**
 * ⭐ R4-01: ЧТО НА УЗЛЕ УЖЕ ВЗЯТО. Узел пересобирается из сида на каждое продолжение забега («в город → спуск
 * продолжает узел»), и без этой записи сундуки, боссы и уники вставали заново — добыча фармилась по кругу. R4-04: запись
 * держится у КАЖДОГО пройденного узла (`RunState.nodes`), а не только у текущего. См. `nodeState.ts`.
 */
export interface RunNodeState {
  /** Узел, к которому относится запись: на другом узле она не действует. */
  id: string;
  /**
   * Мощь пати НА ВХОДЕ в узел (эфф. уровень сильнейшего героя забега), записанная на первом входе.
   * ⚠ 13.10 (Г1): это уже НЕ «по кому заселён этаж» — уровни монстров и броски генератора от мощи не зависят вовсе.
   * ⚠ 14.10 (Г3, правка 7): ВОРОТ ПРОГРЕССА `power <= el + NODE_POWER_SLACK` БОЛЬШЕ НЕТ (были мёртвым
   * условием: на новом узле `el` — тот же максимум, что и `power`). Осталась ОДНА живая роль —
   * воспроизводимость записи узла; поле лежит в сейве и в колонке Postgres, поэтому не удаляется
   * (это была бы миграция).
   */
  el: number;
  /** id открытых сундуков. */
  chests: number[];
  /** Номера убитых монстров в списке заселения узла (порядок `spawnPacksEl`), по возрастанию. */
  killed: number[];
  /** id дёрнутых рычагов (их двери открыты). */
  levers: number[];
}

/** Состояние забега в сейве (Ф4). Граф регенерится из `config.seed` — здесь только указатель. */
/**
 * ⭐⭐ Ф4 (16.10, решение владельца): ОТРЕЗОК — «модификаторы действуют ДО СЛЕДУЮЩЕЙ МЕТКИ, а не на весь забег».
 *
 * `from` — первый этаж отрезка (следующий за меткой, на которой стоял алтарь), `to` — следующая метка
 * ВКЛЮЧИТЕЛЬНО. Этаж самой метки в отрезок не входит: он уже сгенерирован и заселён, когда игрок по нему дошёл до
 * алтаря, и применить к нему настройку значило бы перегенерировать этаж под ногами.
 */
export interface RunSegment {
  /**
   * ⭐⭐ 17.10 (правка по ревизии): ЛИЧНОСТЬ ЗАБЕГА, КОТОРОМУ ОТРЕЗОК ПРИНАДЛЕЖИТ (`RunConfig.id`).
   *
   * ⚠⚠ Без неё границы «от 4 до 6» подходят ЛЮБОМУ забегу: замер ревизии нашёл круг «оплатил на метке 3 →
   * портал в город → новый забег с метки 3», где одна оплата работала на всех последующих забегах, пока
   * жива комната. Границы по глубине — не личность; личность — именно `RunConfig.id`.
   *
   * Нет поля (отрезок из сейва старше этой правки) — отрезок считается ЧУЖИМ и не применяется: для игрока это
   * потеря одной оплаты один раз, а без проверки — бесплатные печати навсегда.
   */
  runId?: string;
  from: number;
  to: number;
  /**
   * ⭐⭐ Ф5-3 (17.10): СВЯЗКА ПЕЧАТЕЙ — КЛЮЧ «вид@ступень» → сколько штук вставлено.
   *
   * ⚠⚠ ЗДЕСЬ НЕ СПИСОК id МОДИФИКАТОРОВ (так было в Ф4, пока печатей не было): иначе отрезок можно
   * было бы настроить ДВУМЯ способами — бесплатным выбором и печатью, и первый обесценил бы второй.
   * Модификаторы остались тем, что вешает ГЕНЕРАТОР (узловые и плановые), и они едут своим путём.
   */
  seals: Record<string, number>;
}

export interface RunState {
  config: RunConfig;
  /**
   * ⭐⭐ Решение владельца 17.10: КТО НАЧАЛ ЗАБЕГ (`charId`) — только он настраивает отрезок на алтаре.
   *
   * Отрезок один на пати, и без владельца любой спутник мог бы настроить его за всех (или испортить чужой
   * забег). Право решает СЕРВЕР по своему полю; здесь оно живёт для ОКНА: клиент сравнивает с своим
   * `charId` и не предлагает того, что сервер всё равно отвергнет. Нет поля — старый сейв (или соло-забег без
   * владельца): алтарь открыт всем, как было до правки.
   */
  starter?: string;
  /** ⭐⭐ Ф4: оплаченный отрезок (нет поля — идём на умолчаниях). Ставит алтарь метки, снимает выход за `to`. */
  segment?: RunSegment;
  currentNodeId: string;
  /**
   * Пройденные узлы этого забега.
   * ⭐⭐ 13.10 (Г2, Р5): это ОКНО самых глубоких (`RUN_VISITED_MAX` = 64), а не вся история: спуск бесконечен, вверх
   * дороги нет, и список рос бы на запись за этаж в каждой записи сейва. Ведёт окно `noteVisited`; читает — только
   * `visitedNode` и только про узел, в который входят (`Room.enterNode`).
   */
  visited: string[];
  /** R4-01: что взято на текущем узле. Нет — узел ещё не тронут (или сейв старше записи). */
  node?: RunNodeState;
  /**
   * R4-04: что взято на ПРОЙДЕННЫХ узлах этого забега (кроме текущего — он в `node`). Узел из `visited` без записи —
   * сейв старше записей: он считается взятым целиком.
   * ⭐⭐ Г2 (Р5): тоже ОКНО (`RUN_NODES_MAX`) — переполнение вытесняет самую мелкую запись, а не отказывает новой.
   */
  nodes?: RunNodeState[];
  /**
   * ⭐ R8-04: наибольшая мощь героя (эффективный уровень с тем, что он мог надеть), которую он показывал в ЭТОМ забеге: на
   * входе в узлы и после своих команд (надел, поднял). Пишет и читает только сервер (`net/room.ts`). Нет — забег ещё не мерили.
   *
   * ⚠ 13.10 (Г1): «новый узел заселяется не слабее неё» — ИСТОРИЯ: заселение мощь не читает вовсе. Живая роль осталась у
   * того же числа: `peak` не даёт ЗАНИЗИТЬ `RunNodeState.el` — записанную мощь ВХОДА в узел (её берёт `Room.partyLevel`
   * по сильнейшему из пати, включая этот `peak`, а в записи она потом неизменна: свод базы при слиянии держит первую,
   * `mergeRunLedger`). Снаряжение, отданное между узлами альту, запись больше не удешевляет. Саму `el` читают ворота
   * воспроизводимость записи узла (⚠ 14.10: ворот прогресса по мощи больше нет — прогресс держит ШАГ МЕТКИ за
   * вход, `Room.enterNode`).
   */
  peak?: number;
  /**
   * ⭐ V1: герой ПОГИБ в коопе на этом узле и с тех пор не жил — штраф за эту смерть уже в ЭТОМ сейве (ставится вместе со штрафом: в базе
   * одно без другого не бывает). «Завершить», похороны и страховка по сейву с меткой второго штрафа не берут; живым в забеге (новый узел,
   * город, вход живым) метка снимается. Раньше «мёртв, оплачено» жило только в памяти комнаты — и терялось с ней: сессию погибшего сняла
   * запись (4009), и «Завершить» по строке базы брало штраф второй раз. Пишет и читает только сервер (`net/room.ts`, `roomManager.ts`).
   */
  deadAt?: string;
}
