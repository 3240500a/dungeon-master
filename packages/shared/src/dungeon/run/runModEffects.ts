import type { ConfigRegistry } from '../../config/registry.js';
import { RUN_MOD_STAT_SEAMS, type RunModifier } from '../../config/schemas.js';

/**
 * ⭐⭐ Ф5-0 (16.10): СТАТЫ МОДИФИКАТОРОВ, КОТОРЫЕ ИГРА ДЕЙСТВИТЕЛЬНО ПРИМЕНЯЕТ.
 *
 * ⚠⚠ ЗАМЕР, С КОТОРОГО ЭТО НАЧАЛОСЬ. До Ф5-0 `RUN_MOD_LIVE_STATS` было ПУСТЫМ множеством: алтарь фильтровал
 * предложение по нему (`altarModifiers`) и потому не показывал НИ ОДНОГО модификатора, а `effects` не читал никто
 * — id ехали только подписью этажа. То есть вся ветка «настрой забег» была обещанием без исполнения. Печати (Ф5)
 * поверх такой основы дали бы вторую обманку, только теперь за предмет, — поэтому статы подключаются ПЕРВЫМИ.
 *
 * ⚠ ПОЧЕМУ РОВНО ЭТИ ДЕСЯТЬ. Это статы, у которых УЖЕ ЕСТЬ ШОВ в игре: заселение этажа (`spawnPacksEl`), вывод
 * монстра (`generateMonster`) и награда за убийство (`GameSession`). Остальные из первого наброска (комнаты с
 * элитой, число сундуков, обзор/туман, ловушки, лечение колбами) — это не «внести стат в множество», а построить
 * механику; они ждут своей фазы и в живой набор не входят, чтобы алтарь снова не обещал несделанного.
 */
export const RUN_MOD_STAT_LIST = RUN_MOD_STAT_SEAMS;

export type RunModStat = (typeof RUN_MOD_STAT_LIST)[number];

/**
 * ⭐⭐ ЖИВЫЕ СТАТЫ = ШВЫ КОДА ∩ ВКЛЮЧЁННЫЕ В КОНФИГЕ (`run-mod-stats`, правится в редакторе).
 *
 * ⚠ Данные могут только СУЗИТЬ набор. Выдумать стат, которого игра не применяет, нельзя — схема таблицы принимает
 * лишь id из `RUN_MOD_STAT_SEAMS`, и это намеренно: именно так алтарь перестал обещать несделанное.
 */
export function liveModStats(reg: ConfigRegistry): ReadonlySet<string> {
  const rows = reg.get('run-mod-stats');
  return new Set(rows.filter((s) => s.enabled !== false).map((s) => s.id));
}

/**
 * ⭐⭐ Ф5-6″ (23.10): МНОЖИТЕЛЬ СЧЁТНОГО СТАТА → ШТУКИ, ПО ЦЕНЕ ОДНОГО СОБЫТИЯ. Одно правило на шов заселения,
 * тултип печати, окно алтаря (Unity), счёт опасности (`sealBuffs`) и замер: разойдутся — окно обещает одно,
 * игра делает другое, а опасность зачтётся третья.
 *
 * ⚠⚠ ПЛАТИШЬ ЦЕНУ — ПОЛУЧАЕШЬ СОБЫТИЕ, И НИКАКИХ СПАСАТЕЛЬНЫХ ПОРОГОВ (правка 23.10 по ревизии). Было:
 * «любая доля от 0.25 даёт хотя бы одно событие» — и замер показал, что это ДАРОВОЕ СОБЫТИЕ: печать зачитывала
 * 0.6 единицы опасности, а на этаж выходило логово ценой 1.4 (×2.33 к оплаченному), причём вторая и третья
 * копии не добавляли НИ ОДНОГО события, но растили награду. Теперь округление вниз по цене: сколько цен
 * оплатил — столько событий и вышло, и то же число зачитывается опасностью.
 *
 * ⚠ Чтобы правило вниз не рождало ловушку «печать списана, события нет», вид со ценой выше своей прибавки
 * просто НЕ ЖИВЁТ (`sealLive`): данные не могут собрать печать, которая платится и не делает ничего.
 */
export function runModCount(mul: number, perUnit = 1): number {
  const add = Number.isFinite(mul) ? mul - 1 : 0;
  const price = Number.isFinite(perUnit) && perUnit > 0 ? perUnit : 1;
  // ⚠ СРАВНЕНИЕ С ЗАПАСОМ, не строгое: двоичная арифметика даёт `1 + 0.9 - 1 = 0.8999999999999999`,
  // и ровно оплаченная цена считалась бы недоплатой (замер: «Сторожевой» с ценой 0.9 не ставил чемпиона вовсе).
  if (add + 1e-9 < price) return 0;
  return Math.floor(add / price + 1e-9);
}

/** Множители модификаторов отрезка: 1 — «как обычно». */
export type RunModBuffs = Readonly<Record<RunModStat, number>>;

/** Нейтральные множители (ни один модификатор не действует). */
export const NO_RUN_BUFFS: RunModBuffs = Object.freeze(
  Object.fromEntries(RUN_MOD_STAT_LIST.map((s) => [s, 1])) as Record<RunModStat, number>,
);

type Mod = Pick<RunModifier, 'id' | 'effects'>;

/**
 * Сводные множители выбранных модификаторов.
 *
 * ⚠ `op: 'mul'` умножает, `op: 'add'` прибавляет К МНОЖИТЕЛЮ (и то и другое встречается в данных). Статы вне
 * живого списка игнорируются молча — так настройка может нести задел, который игра ещё не исполняет, не делая
 * вид, что исполняет: предложение алтаря всё равно фильтруется `runModifierLive`.
 *
 * ⚠ Отрицательный результат зажимается нулём: множитель награды или жизни меньше нуля не имеет смысла ни в одном
 * шве, а порченые данные не должны превращать монстра в целителя.
 */
export function runModBuffs(mods: readonly Mod[], ids: readonly string[] | undefined, live?: ReadonlySet<string>): RunModBuffs {
  const out: Record<RunModStat, number> = { ...NO_RUN_BUFFS };
  if (!ids || !ids.length) return out;
  // ⚠ Без явного набора считаем по ШВАМ кода: так старый вызов не станет тихо сильнее настройки.
  const liveSet = live ?? new Set<string>(RUN_MOD_STAT_LIST);
  const byId = new Map(mods.map((m) => [m.id, m]));
  for (const id of ids) {
    const m = byId.get(id);
    if (!m) continue;
    for (const e of m.effects) {
      if (!liveSet.has(e.stat)) continue;
      const k = e.stat as RunModStat;
      out[k] = e.op === 'mul' ? out[k] * e.value : out[k] + e.value;
    }
  }
  for (const s of RUN_MOD_STAT_LIST) out[s] = Math.max(0, out[s]);
  return out;
}

/**
 * ⭐⭐ Ф5-3 (17.10): СЛОЖЕНИЕ ДВУХ НАБОРОВ МНОЖИТЕЛЕЙ — УМНОЖЕНИЕМ, по статам.
 *
 * На этаже сходятся два источника: модификаторы, которые повесил ГЕНЕРАТОР (узловые/плановые), и ПЕЧАТИ,
 * которые вставил ИГРОК. Умножение, а не сложение прибавок: иначе потолок печатей можно было бы обойти
 * узловым модификатором того же стата, а потолок — про СВЯЗКУ, не про этаж.
 */
export function mergeRunBuffs(a: RunModBuffs, b: RunModBuffs): RunModBuffs {
  const out: Record<RunModStat, number> = { ...NO_RUN_BUFFS };
  for (const s of RUN_MOD_STAT_LIST) out[s] = Math.max(0, a[s] * b[s]);
  return out;
}

/**
 * ⭐⭐ Ф5-0 (16.10): СТАТЫ, РАЗРЕШЁННЫЕ УЗЛОВЫМ МОДИФИКАТОРАМ (`scope: 'node'`) — ПОКА НИ ОДНОГО.
 *
 * ⚠⚠ ПОЧЕМУ ОТДЕЛЬНО ОТ ЗАБЕГОВЫХ. Узловой модификатор вешается генератором САМ (бросок по типу узла), без выбора
 * игрока и без платы. Среди них есть чистое благо — `boon-cache` (`dropBias ×1.5`), и, подключи мы узловые тем же
 * списком, правило владельца «благо только в паре с опасностью» нарушилось бы молча: бесплатная награда на узле
 * появилась бы сама собой. Поэтому узловым нужен СВОЙ набор, и открывать его — отдельное решение с балансом.
 */
export const RUN_MOD_NODE_LIVE_STATS: ReadonlySet<string> = new Set<string>();

/**
 * ⭐⭐ Живые статы УЗЛОВЫХ модификаторов — тоже из конфига: `run-mod-stats[].node` (и, разумеется, `enabled`).
 * По умолчанию столбец пуст, то есть узловые не действуют — см. причину у поля схемы.
 */
export function liveNodeModStats(reg: ConfigRegistry): ReadonlySet<string> {
  const rows = reg.get('run-mod-stats');
  return new Set(rows.filter((s) => s.enabled !== false && s.node === true).map((s) => s.id));
}

/** Действует ли на этаже хоть что-то (быстрый выход там, где модификаторов нет). */
export function anyRunBuff(b: RunModBuffs): boolean {
  return RUN_MOD_STAT_LIST.some((s) => b[s] !== 1);
}
