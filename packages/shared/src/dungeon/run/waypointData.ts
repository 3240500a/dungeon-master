/** Биом глазами сторожа: id, имя для текста и тумблер. */
export interface WaypointBiomeLite {
  id: string;
  name?: string;
  enabled?: boolean;
}
/** Этаж глазами сторожа: роль, биом, тумблер и членство в шаблонах (пустой список = «во всех»). */
export interface WaypointFloorLite {
  id: string;
  role: string;
  biomeId: string;
  enabled?: boolean;
}
/** Шаблон забега глазами сторожа. */
export interface WaypointTemplateLite {
  id: string;
  name?: string;
  enabled?: boolean;
}
/** Строка отчёта — в точности форма, которую ждёт список проблем редактора. */
export interface WaypointWarning {
  section: string;
  id: string;
  msg: string;
}

/** Роль этажа-привала: ровно её ищет генератор забега, когда решает, бывает ли на этой глубине метка. */
export const WAYPOINT_FLOOR_ROLE = 'rest';

const on = (x: { enabled?: boolean }): boolean => x.enabled !== false;
/** Роль боссового этажа — её ищет генератор, когда ставит босса лестницы. */
export const BOSS_FLOOR_ROLE = 'boss';

/**
 * Предупреждения о контенте круга: у каждого ВКЛЮЧЁННОГО биома обязан быть включённый этаж роли `rest` (привал) и
 * роли `boss` (боссовая арена).
 *
 * ⚠⚠ Г8-4 (15.10, решение владельца): ПОСЛЕДСТВИЕ ДРУГОЕ, ЧЕМ БЫЛО. Прежде отсутствие этажа-привала означало спуск
 * БЕЗ ЕДИНОЙ МЕТКИ, а отсутствие боссового (или невхождение его в шаблон) — забег БЕЗ БОССОВ: генератор спрашивал
 * «есть ли такой этаж», и молча отменял метку или босса. Владелец потребовал обратного — «боссы на этажах боссов,
 * вейпоинты на этажах вейпоинтов согласно таблице», — поэтому место круга теперь решает ВСЁ, и узел на нём будет в
 * любом случае. Нехватка контента больше не отменяет узел, а ПОРТИТ ЕГО ВИД: привал встанет на обычном этаже (без
 * комнаты-привала), боссовый узел — на обычном этаже (а значит без боссовой комнаты, то есть и без самого босса).
 * Это и есть то, о чём предупреждение: не «метки не будет», а «метка будет не та».
 *
 * ⚠ ЧЛЕНСТВО ЭТАЖА В ШАБЛОНЕ СНЯТО СОВСЕМ (Г8-4): оно было третьим молчаливым условием и съело боссов крипты в
 * «Короткой вылазке». Аргумент `templates` больше не нужен и не принимается.
 */
export function waypointWarnings(
  biomes: readonly WaypointBiomeLite[],
  floors: readonly WaypointFloorLite[],
): WaypointWarning[] {
  const out: WaypointWarning[] = [];
  const need: { role: string; what: string; tail: string }[] = [
    {
      role: WAYPOINT_FLOOR_ROLE, what: 'привал',
      tail: 'метки круга всё равно встанут (их место решает таблица), но привал будет на ОБЫЧНОМ этаже — без '
        + 'комнаты-привала. Включите (или добавьте) этаж-привал этого биома.',
    },
    {
      role: BOSS_FLOOR_ROLE, what: 'боссовая арена',
      tail: 'места боссов круга всё равно встанут, но узел будет на ОБЫЧНОМ этаже — без боссовой комнаты, то есть '
        + 'БЕЗ САМОГО БОССА. Включите (или добавьте) боссовый этаж этого биома.',
    },
  ];
  for (const b of biomes) {
    if (!on(b)) continue;   // выключенный биом в забег не попадает — и спрашивать с него нечего
    const who = b.name ? `«${b.name}»` : b.id;
    for (const n of need) {
      if (floors.some((f) => on(f) && f.role === n.role && f.biomeId === b.id)) continue;
      out.push({
        section: 'biomes', id: b.id,
        msg: `у биома ${who} нет включённого этажа роли «${n.role}» (${n.what}) — ${n.tail}`,
      });
    }
  }
  return out;
}
