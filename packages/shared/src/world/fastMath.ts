/**
 * Быстрые замены дорогих встроенных функций для ГОРЯЧИХ циклов симуляции (задача Ф0.11).
 *
 * Замерено на V8 (Node 24, i7-11800H):
 *   Math.hypot(dx, dy)              12,8 нс   ← защищён от переполнения, поэтому идёт «длинным» путём
 *   Math.sqrt(dx*dx + dy*dy)         1,5 нс   ← в 8,7 раза дешевле
 *   Math.atan2(Math.sin a, Math.cos a) 38,3 нс ← три тригонометрические функции ради нормализации угла
 *   a − 2π·round(a / 2π)             3,0 нс   ← в 13 раз дешевле
 *
 * Защита от переполнения в `Math.hypot` нужна для величин порядка 1e300; наши координаты —
 * это игровые пиксели этажа (тысячи), поэтому она стоит впустую. На тик приходятся сотни таких
 * вызовов: восприятие, дистанции боя, расталкивание тел.
 *
 * ВНЕ горячих циклов (генерация этажа, разовые расчёты, тесты) выигрыш незаметен — там можно
 * оставлять привычные `Math.hypot`/`Math.atan2`, читаемость важнее.
 */

const TAU = Math.PI * 2;

/** Длина вектора. Замена `Math.hypot(dx, dy)` для игровых величин. */
export function vecLen(dx: number, dy: number): number {
  return Math.sqrt(dx * dx + dy * dy);
}

/** Расстояние между точками. */
export function dist(ax: number, ay: number, bx: number, by: number): number {
  const dx = bx - ax;
  const dy = by - ay;
  return Math.sqrt(dx * dx + dy * dy);
}

/**
 * Квадрат расстояния — когда нужно только сравнить с порогом. Сравнивайте с `r * r`,
 * и корень не понадобится вовсе.
 */
export function dist2(ax: number, ay: number, bx: number, by: number): number {
  const dx = bx - ax;
  const dy = by - ay;
  return dx * dx + dy * dy;
}

/**
 * Нормализация угла в (−π, π]. Замена `Math.atan2(Math.sin(a), Math.cos(a))`.
 *
 * Отличие ровно одно и на границе: при `a` кратном ровно π знак получается по правилу
 * округления половин вверх, тогда как `atan2(sin, cos)` вернёт +π из-за ошибки представления.
 * Для игровых углов (взгляд, конус зрения, разворот) это неразличимо.
 */
export function wrapAngle(a: number): number {
  return a - TAU * Math.round(a / TAU);
}
