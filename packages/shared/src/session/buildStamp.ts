/**
 * ⭐ R18-08: ШТАМП СБОРКИ — «с какого кода общего фундамента собраны вкладка и сервер».
 *
 * С L2 / R3-25 деплой не перезагружает вкладку: она переподключается сама и живёт со СТАРЫМ бандлом. Согласие на конфиг (`cfgRev`,
 * V-B3-07, R16 C-07) ловит правку ДАННЫХ, `PROTOCOL_VERSION` — несовместимую правку провода, а правку КОДА цены (`forgeGold`, цена скупки,
 * выход разбора, множитель формы) при том же теле конфига не ловило ничто: карточки старой вкладки считали цену старой формулой, сервер —
 * новой, и каждая платная команда получала «Цена изменилась», перечитывание конфига — 304, а игрок не слышал, что нужна перезагрузка.
 *
 * Штамп — хэш ИСХОДНИКОВ `packages/shared/src` (там вся математика цен и исходов — клиент и сервер считают одним кодом): сборка клиента
 * вписывает его в бандл (`__DM_BUILD__`, `client/vite.config.ts`), сервер считает его на старте по тем же файлам, с которых он и работает
 * (`server/src/buildStamp.ts`), и шлёт в кадре `joined` (`build`). Не сошлись — код вкладки старше сервера (`App` говорит «перезагрузите»).
 * Только исходники рантайма: тесты и фаззеры (`*.test.ts`, папки `fuzz/`) штамп не двигают, данные конфига (`config/data/*.json`) — тоже:
 * их правку догоняет перечитывание конфига.
 *
 * Здесь — чистая часть (отбор файлов и хэш), без `node:fs`: её зовут обе стороны, каждая со своим чтением папки.
 */

/** Файл исходников `shared/src` (путь относительно неё, любой разделитель) — часть штампа. */
export function isBuildStampSource(path: string): boolean {
  const p = path.replace(/\\/g, '/');
  return p.endsWith('.ts') && !p.endsWith('.test.ts') && !p.endsWith('.d.ts') && !/(^|\/)fuzz\//.test(p);
}

/**
 * Штамп по файлам `[путь, текст]` (путь относительно `shared/src`): чужие отбрасываются (`isBuildStampSource`), порядок и разделитель путей
 * не важны. FNV-1a по полным кодам знаков пути и текста (как ревизия конфига, `configRev`). Файлов нет — пустая строка: сравнивать нечего.
 * ⚠ R19-06: концы строк и BOM в начале файла — не код: текст приводится к LF без BOM (`sourceText`). Выгрузка Windows (`core.autocrlf=true`
 * — CRLF) и Linux (LF) одного коммита давали разные штампы: клиент, собранный на рабочей машине, против сервера из `git pull` — каждой
 * вкладке «перезагрузите», и перезагрузка не помогала никогда.
 */
export function buildStampOf(files: Iterable<readonly [path: string, text: string]>): string {
  const list = [...files]
    .map(([p, t]) => [p.replace(/\\/g, '/'), sourceText(t)] as const)
    .filter(([p]) => isBuildStampSource(p))
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  if (!list.length) return '';
  let h = 0x811c9dc5;
  let len = 0;
  const eat = (s: string): void => {
    for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 0x01000193); }
    len += s.length;
  };
  for (const [p, t] of list) { eat(p); eat('\u0000'); eat(t); eat('\u0000'); }
  return `${list.length.toString(36)}-${len.toString(36)}-${(h >>> 0).toString(36)}`;
}

/** ⚠ R19-06: текст исходника, как его видит штамп: без BOM в начале, концы строк — LF (CRLF и одиночный CR — туда же). */
function sourceText(t: string): string {
  return (t.charCodeAt(0) === 0xfeff ? t.slice(1) : t).replace(/\r\n?/g, '\n');
}
