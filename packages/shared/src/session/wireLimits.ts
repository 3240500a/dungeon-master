/**
 * ⭐ R3-02 / R3-14: ЧТО В СТРОКЕ С ПРОВОДА НЕ ДОПУСКАЕТСЯ — управляющие символы (Cc: U+0000…U+001F, U+007F…U+009F)
 * и НЕПАРНЫЕ суррогаты (Cs под флагом `u`: парный суррогат — это один астральный символ, в класс он не попадает).
 *
 * JSON их пропускает (экраны `\u0000`, `\ud800`), длина — тоже, а Postgres — нет: jsonb отвергает U+0000 (22P05) и
 * непарный суррогат (22P02), текстовый параметр — байт 0x00 (22021). Бинд `"x\u0000"` ложился в сейв, и КАЖДАЯ
 * следующая запись героя падала: он играл из памяти, а рестарт откатывал его к сейву до бинда — дюп через соседа
 * по аккаунту и откат неудачных бросков. Честному id (узел древа, uid, квест, токен) такие символы не нужны никогда.
 */
const WIRE_TEXT_BAD = /[\p{Cc}\p{Cs}]/u;

/** Годна ли строка для провода (и для базы): без управляющих символов и непарных суррогатов (R3-02). */
export function isWireText(s: string): boolean {
  return !WIRE_TEXT_BAD.test(s);
}

/**
 * ⭐ R3-14 / R4-02: ТОКЕН СЕССИИ И ID ГЕРОЯ — их настоящий вид. Токен — `randomBytes(32).toString('hex')` (`db.createSession`),
 * charId — `randomUUID()` (`POST /api/characters`; буквы, цифры, дефис и подчёркивание — и для старых id). Один вид на
 * провод WebSocket (`netSchemas.ts`) и на HTTP (`server/net/accountRoutes.ts`): кривой — отказ на границе, до базы.
 */
export const WIRE_TOKEN_RE = /^[0-9a-f]{64}$/;
export const WIRE_CHAR_ID_RE = /^[A-Za-z0-9_-]{1,64}$/;
