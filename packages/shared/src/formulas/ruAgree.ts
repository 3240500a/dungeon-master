/** Основы, после которых идёт твёрдое окончание: «широкий → широкое», «тугой → тугие». */
const HARD_STEM = /[кгхжшчщ]$/;

/**
 * Согласует прилагательное в МУЖСКОМ роде с согласованием имени: «поздний» → «поздняя», «широкий» →
 * «широкое». Слова, которые не прилагательные («с», «долом»), не трогает. Работает по словам.
 *
 * `agreement` — токены словаря `i18n/forms.ts` (`m`/`f`/`n`/`pl`); старое `p` конфига принимается как `pl`.
 */
export function ruAgree(phrase: string, agreement: string | undefined): string {
  if (!phrase || !agreement || agreement === 'm') return phrase;
  const plural = agreement === 'pl' || agreement === 'p';
  return phrase.split(' ').map((w) => {
    const m = /^(.*?)(ый|ий|ой)$/.exec(w);
    if (!m || m[1]!.length < 2) return w;
    const stem = m[1]!, end = m[2]!;
    const soft = end === 'ий' && !HARD_STEM.test(stem); // поздний, ранний, синий
    if (plural) return stem + (soft || HARD_STEM.test(stem) ? 'ие' : 'ые');
    if (agreement === 'f') return stem + (soft ? 'яя' : 'ая');
    if (agreement === 'n') return stem + (soft ? 'ее' : end !== 'ой' && /[жшчщ]$/.test(stem) ? 'ее' : 'ое');
    return w;
  }).join(' ');
}
