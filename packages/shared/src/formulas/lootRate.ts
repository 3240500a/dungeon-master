/**
 * ⭐⭐ 13.10 НАГРАДА С МОНСТРА ЕДЕТ ПО ЕГО КРИВОЙ ЖИЗНИ (шаг 8 плана «Монстры: план по силе»).
 *
 * РЕШЕНИЕ ВЛАДЕЛЬЦА: «глубина в любой игре так или иначе становится фармом, нужно просто сделать это
 * интересным». Отсюда числовое требование: НАГРАДА В ЧАС не должна проседать с глубиной, иначе спускаться
 * невыгодно и глубина превращается в наказание.
 *
 * ЗАМЕР 13.10 (бот сима против среднего монстра своего уровня, `closedFormTtk`):
 *   ур.10 — ttk 2.7 с, 1346 убийств/ч, 162 вещи/ч
 *   ур.80 — ttk 44.2 с,   81 убийство/ч, 9.8 вещи/ч
 * То есть жизнь монстра выросла ×160, урон игрока — ×9.7, и время убийства ×16.5. Шанс дропа был ПЛОСКИМ
 * (0.12 на любом уровне), поэтому поток вещей падал ровно в те же ×16.5.
 *
 * ЛЕЧЕНИЕ: за убийство бросается НЕ ОДИН раз, а `шанс × масштаб` раз, где масштаб = `(ур/10)^rewardPower`
 * (точка опоры — 10-й уровень, как и у кривой жизни) × отношение `tierHp` этого тира к среднему. Второй
 * множитель — то же правило для разброса внутри пачки: босс с ×10 жизни убивается ×10 дольше и обязан
 * отдавать ×10 награды, иначе бить его невыгодно.
 *
 * ⚠ ПОЧЕМУ НЕ ВСЕ КАНАЛЫ. Применять это ко всему нельзя — часть наград УЖЕ едет по кривой, и масштаб
 * удвоил бы счёт (замеры 13.10):
 *   · ЗОЛОТО уже линейно по уровню (`rng.int(1, 5 + level*2)`): ×16 за 10→80 — почти ровно нужные ×16.5;
 *   · СЫРЬЁ едет размером кучи (она из НАДЕТОГО, а надетое растёт по ступеням снаряжения, ×5.04 за 10→80):
 *     его поток падает не в 16.5, а в 3.3 раза — и лечить его надо своим числом, а не этим;
 *   · ВЕЩИ и КОЛБЫ — плоские шансы, им масштаб и нужен.
 */

/**
 * Масштаб награды за убийство: точка опоры — 10-й уровень; `power` 0 — награда плоская, как было.
 *
 * ⚠ ТОЛЬКО ВВЕРХ (не ниже 1). Без этого степень срезала награду НИЖЕ 10 уровня: на 1-м (1/10)^1.35 ≈ 0.045,
 * то есть вещи стали бы падать в 22 раза реже, чем сегодня (поймали сторожа сессии 13.10). Правило плана —
 * «глубже не беднее», а не «мелко беднее»: раннюю игру план не трогает вовсе, и на уровнях ≤ 10 поток бит-в-бит
 * тот же, что до правки (один бросок `chance` — тот же поток `rng`).
 */
export function rewardScaleOf(level: number, tierHpRatio: number, power: number): number {
  if (power <= 0) return 1;
  return Math.max(1, Math.pow(Math.max(1, level) / 10, power) * Math.max(0, tierHpRatio));
}

/**
 * Сколько раз бросать канал награды: целая часть — гарантированные броски, остаток — вероятностный
 * (как у `salvageFromItem`: обычное округление на малых числах превращало бы множитель в ступеньку).
 */
export function rewardRolls(chance: number, scale: number, chanceRoll: (p: number) => boolean): number {
  const expected = Math.max(0, chance) * Math.max(0, scale);
  const whole = Math.floor(expected);
  return whole + (chanceRoll(expected - whole) ? 1 : 0);
}
