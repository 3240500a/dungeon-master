/**
 * UUIDv7 — идентификатор предмета (Ф2).
 *
 * ЗАЧЕМ ИМЕННО ОН. Старые id вида `it_<время>_<счётчик>` глобально уникальными НЕ были:
 * счётчик обнулялся на рестарте процесса, а время бралось в миллисекундах — два предмета,
 * рождённые в одну миллисекунду в разных процессах, получали один id. Для журнала
 * происхождения это смертельно: невозможно отличить «та же вещь» от «другая вещь с тем же
 * номером», а значит нельзя ни доказать дюп, ни откатить его точечно.
 *
 * v7 против v4: первые 48 бит — время в миллисекундах, поэтому идентификаторы РАСТУТ. Индекс
 * в базе не разъезжается случайными вставками, а по самому id видно, когда вещь появилась.
 *
 * Раскладка (RFC 9562): 48 бит времени | версия 7 | 12 бит случайных | вариант | 62 бита
 * случайных. Случайной части 74 бита — коллизия внутри одной миллисекунды невозможна на
 * практике.
 */
export function uuidv7(): string {
  const ms = Date.now();
  const b = new Uint8Array(16);
  // 48 бит времени, старший байт первым.
  b[0] = (ms / 2 ** 40) & 0xff;
  b[1] = (ms / 2 ** 32) & 0xff;
  b[2] = (ms / 2 ** 24) & 0xff;
  b[3] = (ms / 2 ** 16) & 0xff;
  b[4] = (ms / 2 ** 8) & 0xff;
  b[5] = ms & 0xff;
  for (let i = 6; i < 16; i++) b[i] = (Math.random() * 256) & 0xff;
  b[6] = 0x70 | (b[6]! & 0x0f);   // версия 7
  b[8] = 0x80 | (b[8]! & 0x3f);   // вариант RFC 4122
  let s = '';
  for (let i = 0; i < 16; i++) s += b[i]!.toString(16).padStart(2, '0');
  return `${s.slice(0, 8)}-${s.slice(8, 12)}-${s.slice(12, 16)}-${s.slice(16, 20)}-${s.slice(20)}`;
}

/** Похоже ли на UUID (любой версии). Нужен аудиту: старые id предметов сюда не пройдут. */
export function isUuid(s: string): boolean {
  return /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/.test(s);
}
