import { describe, it, expect } from 'vitest';
import { ConfigRegistry } from '../config/registry.js';
import { Localizer, SOURCE_LANG } from '../i18n/index.js';
import { nameSweeps } from './itemName.testkit.js';

/**
 * ⭐ i18n Ф3, решение владельца 07.11: РУССКИЕ ИМЕНА ВЕЩЕЙ И ФОРМУЛА КОВКИ БЕЗ ПОВТОРА КОРНЯ. Английский сторож (`itemName.en.test.ts`) вычистил
 * свои повторы данными перевода, а у русского источника были свои: «Ядовитый Жезл яда», «Грозовой Молот-гроза», «Молот-гроза Гроза жажды»,
 * в формуле — «щекавицы без щекавиц», «хват хват у пяты», «хват хват посередине». Лечится данными источника: база переименована
 * (venom-wand «Жезл яда» → «Жезл отравы», maul «Молот-гроза» → «Кувалда», ж. р.), значение тега не повторяет ярлык («нет», «у пяты»,
 * «посередине»). Обход — тот же, что у английского (`itemName.testkit.ts`), правило корня — русское (окончания, суффиксы прилагательных,
 * сложные слова).
 *
 * ⚠ ЖДЁТ ВЛАДЕЛЬЦА (`PENDING`): сторож нашёл ещё шесть повторов, которых нет в решении 07.11, — их не трогаем, но держим поимённо: новый
 * повтор или исчезнувший из списка — провал.
 */
const reg = new ConfigRegistry();
reg.loadAll();
const SRC = new Localizer(undefined, SOURCE_LANG);

/** Служебные слова (предлоги, союзы, отрицание) — не корни. */
const STOP = new Set(['без', 'у', 'с', 'со', 'на', 'в', 'во', 'и', 'к', 'ко', 'по', 'от', 'из', 'для', 'о', 'об', 'при', 'за', 'над', 'под', 'до', 'или', 'не', 'нет', 'только']);
/** Окончания прилагательного (сперва длинные) — после них снимается и суффикс (`DERIV`): «грозовой» → «грозов» → «гроз». */
const ADJ = ['ого', 'его', 'ому', 'ему', 'ыми', 'ими', 'ый', 'ий', 'ой', 'ая', 'яя', 'ое', 'ее', 'ые', 'ие', 'ым', 'им', 'ую', 'юю', 'ых', 'их'];
/** Окончания существительного: «щекавицы» → «щекавиц», «яда» → «яд». */
const NOUN = ['ами', 'ями', 'ов', 'ев', 'ей', 'ам', 'ям', 'ах', 'ях', 'ом', 'ем', 'а', 'я', 'ы', 'и', 'у', 'ю', 'е', 'о', 'ь'];
/** Суффиксы прилагательного от существительного: ядОВИТый, грозОВой, пламЕННый, охотНИЧий, мифИЧЕСКий… — только у прилагательных. */
const DERIV = ['ическ', 'овит', 'евит', 'нич', 'еск', 'енн', 'онн', 'янн', 'ист', 'чат', 'лив', 'ов', 'ев', 'ит', 'ан', 'ян', 'ин', 'ат', 'ив', 'ск', 'н'];
const cut = (w: string, list: readonly string[]): string | undefined => {
  for (const e of list) if (w.endsWith(e) && w.length - e.length >= 2) return w.slice(0, -e.length);
  return undefined;
};
/** Основа (без окончания) и корень (у прилагательного — ещё и без суффикса). */
function stemOf(w: string): { stem: string; root: string } {
  const a = cut(w, ADJ);
  if (a !== undefined) return { stem: a, root: cut(a, DERIV) ?? a };
  const n = cut(w, NOUN) ?? w;
  return { stem: n, root: n };
}
/** Значимые слова: строчные, ё = е, составное через дефис — два слова («молот-гроза» → молот, гроза). */
const words = (s: string): string[] => s.toLowerCase().replace(/ё/g, 'е').split(/[^а-яa-z]+/).filter((w) => w && !STOP.has(w));
/**
 * Общий корень: та же основа или тот же корень (щекавицы/щекавиц, хват/хват, ядовитый/яда, грозовой/гроза, охотничий/охоты); или сложное
 * слово на корень другого (≥ 4 букв) с соединительной о/е — пламЕгашения ← пламя.
 * ⚠ Не корень (сверено на живых данных): вой/войны (вой ≠ война), древке/древних (древко — от «древо», древний — от «древле»),
 * грозовой/громостойкости (гроза ≠ гром), перо/перекладина, короткий/короля — общее начало, разные слова.
 */
function sameRoot(a: string, b: string): boolean {
  const A = stemOf(a), B = stemOf(b);
  if (A.stem === B.stem || A.root === B.root) return true;
  const compound = (r: string, s: string): boolean => r.length >= 4 && s.length > r.length + 3 && s.startsWith(r) && /[ое]/.test(s[r.length]!);
  return compound(A.root, B.stem) || compound(B.root, A.stem);
}
function rootClash(text: string): string | undefined {
  const w = words(text);
  for (let i = 0; i < w.length; i++) for (let j = i + 1; j < w.length; j++) if (sameRoot(w[i]!, w[j]!)) return `${w[i]}~${w[j]}`;
  return undefined;
}
const keyOf = (clash: string): string => clash.slice(0, clash.indexOf(':'));

/**
 * ⚠ Повторы, найденные сторожем 07.11 вне решения владельца — ждут его (вопрос в `i18n/README.md`). Ключ — пара слов, как её пишет
 * `rootClash`; значение — где живёт. Решение владельца — правка данных; тогда строка уходит отсюда.
 */
const PENDING: Readonly<Record<string, string>> = {
  'рок~рока': 'рар любой базы: основа «Рок» (rok) × эпитет «рока» (roka) — обе нейтральные, выпадают вещи без темы и без группы',
  'щит~щита': 'рар «Деревянный щит» / «Башенный щит» × эпитет «щита» (schita, группа defense — у щита почти всегда)',
  'клинок~клинок': 'рар «Клинок ассасина» × основа «Клинок» (klinok, тема physical)',
  'гнили~гниль': 'рар «Посох гнили» × основа «Гниль» (gnil, тема poison)',
  'палача~палача': 'рар «Секира палача» × эпитет «палача» (palacha, нейтральный)',
  'охотничий~охоты': 'рар «Охотничий лук» × эпитет «охоты» (ohoty, группа finesse)',
};
const S = nameSweeps(reg, SRC, rootClash);

describe('⭐ i18n Ф3, решение владельца 07.11: русские имена вещей и формула ковки без повтора корня', () => {
  it('сторож корня ловит прежние беды и не ловит соседей (иначе он ничего не доказывает)', () => {
    for (const bad of ['щекавицы без щекавиц', 'хват хват у пяты', 'хват хват посередине', 'Ядовитый Жезл яда', 'Грозовой Молот-гроза',
      'Молот-гроза Гроза жажды', 'Жезл яда Яд крови', 'Кинжал Рок рока', 'Охотничий лук Коготь охоты', 'Посох гнили Гниль крови',
      'Деревянный щит Пепел щита', 'Секира палача Клык палача', 'Клинок ассасина Клинок жажды', 'Пламенный кинжал Пламегашения']) {
      expect(rootClash(bad), bad).toBeDefined();
    }
    for (const ok of ['Ядовитый Жезл отравы', 'Грозовая Кувалда', 'Кувалда Гроза жажды', 'Жезл отравы Яд крови', 'щекавицы нет', 'хват у пяты',
      'хват посередине', 'Кинжал Вой войны', 'Секира на древке Пепел древних', 'Грозовой Жезл молний Громостойкости', 'Короткое копьё Пепел короля',
      'крепление перекладина', 'Морозный Моргенштерн', 'Кинжал Клык крови']) {
      expect(rootClash(ok), ok).toBeUndefined();
    }
  });

  it('⭐ рар: каждая база × каждая основа × каждый эпитет — повторяют корень только сочетания, ждущие владельца', () => {
    const r = S.rare();
    expect(r.n).toBeGreaterThan(100_000);
    expect([...new Set(r.clashes.map(keyOf))].sort()).toEqual(Object.keys(PENDING).sort());
  });

  it('⭐ рар: основы и эпитеты различны между собой; общий корень пары — только «Рок рока» (ждёт владельца)', () => {
    const all = [...S.pool.nouns.map((x) => x.t), ...S.pool.epithets.map((x) => x.t)].map((w) => w.toLowerCase());
    expect(all.filter((w, i) => all.indexOf(w) !== i)).toEqual([]);
    const pairs = S.pool.nouns.flatMap((a) => S.pool.epithets.filter((b) => sameRoot(a.t.toLowerCase(), b.t.toLowerCase())).map((b) => `${a.t}/${b.t}`));
    expect(pairs).toEqual(['Рок/рока']);
  });

  it('⭐ магия и ступень: каждое слово аффикса × каждая база, которой он выпадает; каждая ступень × каждая база', () => {
    const r = S.affixAndTier();
    expect(r.n).toBeGreaterThan(2_000);
    expect(r.clashes).toEqual([]);
  });

  it('⭐ настоящий шов: дроп рара и магии → `itemDisplayName` на русском — испечённое имя, повтор корня — только ждущий владельца', () => {
    const d = S.drops();
    expect(d.length).toBe(600);
    expect(d.filter((x) => x.shown !== x.item.name).map((x) => x.item.name)).toEqual([]);
    const bad = d.map((x) => ({ c: rootClash(x.shown), name: x.shown })).filter((x) => x.c && !(x.c in PENDING)).map((x) => `${x.c}: ${x.name}`);
    expect(bad).toEqual([]);
  });

  it('⭐ формула ковки: ярлык и значение не повторяют друг друга («щекавицы нет», не «щекавицы без щекавиц») — все значения и каждая деталь', () => {
    const v = S.formulaValues();
    expect(v.n).toBeGreaterThan(200);
    expect(v.clashes).toEqual([]);
    const p = S.formulaParts();
    expect(p.n).toBeGreaterThan(500);
    expect(p.clashes).toEqual([]);
  });
});
