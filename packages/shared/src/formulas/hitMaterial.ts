/**
 * ⭐⭐ ВО ЧТО ПОПАЛИ — материал цели удара. Одно правило на игру, а не по копии в каждом клиенте.
 *
 * Жалоба: «звук удара играет всегда, даже если никого не бьёшь; и надо привязать его к типу брони
 * на монстре — латы одно, кожа другое». Первая половина чинится тем, что звук едет от СОБЫТИЯ удара,
 * а не от метки в клипе (метка не знает, попал ли ты). Вторая — вот этим: сервер кладёт в событие
 * материал цели, и оба клиента звучат одинаково, ничего не выводя у себя заново.
 *
 * ⚠ Значения — ровно id классов брони из конфига (`armor-classes`), плюс `flesh` на «брони нет».
 * Выдумывать свою шкалу материалов нельзя: класс брони уже есть у предмета, его правит редактор,
 * и вторая шкала рядом с ним разъехалась бы на первой же новой броне.
 */
export type HitMaterial = 'quilted' | 'leather' | 'chain' | 'segmented' | 'plate' | 'flesh';

/** Все материалы (порядок = от мягкого к твёрдому) — для тестов и подбора тембра. */
export const HIT_MATERIALS: readonly HitMaterial[] = ['flesh', 'quilted', 'leather', 'chain', 'segmented', 'plate'];

const KNOWN = new Set<string>(HIT_MATERIALS);

/**
 * Первый ИЗВЕСТНЫЙ класс брони из переданных (нагрудник важнее шлема), иначе `flesh`.
 *
 * ⚠ Незнакомый id — это `flesh`, а не ошибка: класс брони живёт в конфиге, и молча падать из-за
 * новой строки там звук не должен. Зато и тихо звенеть латами на неизвестной броне он не будет.
 */
export function hitMaterialOf(...armorClasses: (string | undefined)[]): HitMaterial {
  for (const c of armorClasses) if (c && KNOWN.has(c) && c !== 'flesh') return c as HitMaterial;
  return 'flesh';
}
