import type { Attribute, StatModifier } from './attributes.js';
import type { DamageType } from './combat.js';

export type Rarity = 'normal' | 'magic' | 'rare' | 'unique';

export const RARITY_ORDER: Rarity[] = ['normal', 'magic', 'rare', 'unique'];

/** Слоты экипировки. `offhand` — щит ИЛИ второе одноручное оружие. */
export type EquipSlot =
  | 'weapon'
  | 'offhand'
  | 'helm'
  | 'chest'
  | 'gloves'
  | 'boots'
  | 'belt'
  | 'ring'
  | 'amulet';

/** Тип атаки: ближний взмах vs снаряд. Задаёт паттерн базовой атаки (ЛКМ) и фолбэк-атрибут. */
export type AttackType = 'melee' | 'ranged';
/** Вид урона: физический (physSub-статусы, вес по Сила/Ловк) vs магический (стихия, вес=Инт, болт тратит ману). */
export type DamageKind = 'physical' | 'magical';

/** Вид предмета — дискриминатор базы (совпадает со схемой items.base). */
/**
 * ⚠ `material` — ОТДЕЛЬНЫЙ вид, а не «предмет со стеком». Сделать стек свойством любого предмета
 * значило бы тянуть количество в продажу, разделение стека, слияние в сундуке, пояс с колбами
 * и журнал происхождения предметов. Материалу же экипировка, аффиксы, кузница, магазин и леджер
 * запрещены по построению, поэтому стек живёт только у него и не протекает наружу.
 */
export type ItemKind = 'weapon' | 'armor' | 'shield' | 'jewelry' | 'consumable' | 'material';

/** Эффект применения расходника (зелья/колбы). */
export interface ConsumableUse {
  /** Мгновенное лечение (плоское HP). */
  heal?: number;
  /** Лечение долей от макс. HP (0..1). */
  healPct?: number;
  /** Мгновенное восстановление маны (плоское). */
  mana?: number;
  /** Мана долей от макс. (0..1). */
  manaPct?: number;
  /** Снять все дебаффы. */
  cure?: boolean;
  /** Временные стат-моды и длительность (сек). */
  buffMods?: StatModifier[];
  buffDurationSec?: number;
}

/** Класс щита (вес) — задаёт профиль требований (лёгкий/средний/тяжёлый). */
export type ShieldClass = 'light' | 'medium' | 'heavy';

/** Класс оружия — ветвь дерева редактора + подпись в тултипе. */
export type WeaponClass =
  | 'sword' | 'axe' | 'mace' | 'dagger' | 'spear' | 'halberd'
  | 'bow' | 'crossbow' | 'wand' | 'staff';

/** Вес оружия — id из конфига weapon-weights (power/finesse/доли скейла — в конфиге). */
export type WeaponWeight = string;

/** Подтип физ. урона — id из конфига phys-subtypes (какой статус вешает — в конфиге). */
export type PhysSubtype = string;

/** Класс брони — id из конфига armor-classes (data-driven: штрафы/шум/выдержка в конфиге). */
export type ArmorClass = string;

/**
 * Сигнатурные свойства оружия (сверх baseStats). Все опциональны; масштабом тира
 * НЕ трогаются — это механика, а не числа урона. Читаются боевым контроллером.
 */
export interface WeaponSignature {
  weaponClass?: WeaponClass;
  /** Вес (профиль/требования/масштаб сигнатур). */
  weight?: WeaponWeight;
  /** Подтип физ. урона (стаковый дебафф). */
  physSub?: PhysSubtype;
  /** Шанс оглушить цель (0..1). */
  stunChance?: number;
  /** Игнор доли брони цели (0..1). */
  armorPenPct?: number;
  /** Множитель ширины дуги базовой атаки (топоры > 1). */
  arcMult?: number;
  /** Множитель дальности базовой атаки (копья > 1). */
  reachMult?: number;
  /**
   * Множитель УДАРА этим оружием — у скованной вещи от формы клинка (тяжёлый ×1.10, лёгкий ×0.90).
   * Бой множит на него весь удар — урон оружия ВМЕСТЕ с вкладом атрибутов, иначе атрибуты размывали
   * бы форму и тяжёлый клинок проигрывал лёгкому. Подсказка показывает цифры урона уже умноженными.
   */
  damageMult?: number;
  /** Доп. урон по целям с низким HP (0..1). */
  lowHpBonusPct?: number;
  /** Сила отбрасывания цели (px, 0 — нет). */
  knockback?: number;
}

/** Определение базы предмета из конфига (items.base). */
export interface ItemBase extends WeaponSignature {
  /** Класс брони (для брони/щитов). */
  armorClass?: ArmorClass;
  id: string;
  name: string;
  /** Род названия для согласования тир-префикса (м/ж/с/мн). */
  gender?: 'm' | 'f' | 'n' | 'p';
  /** Слот экипировки. У расходников отсутствует. */
  slot?: EquipSlot;
  /** Кол-во быстрых слотов пояса (для брони-пояса). */
  beltSlots?: number;
  /** Эффект применения (для kind='consumable'). */
  use?: ConsumableUse;
  /** Тип атаки (ближний/дальний). Только для оружия. */
  attackType?: AttackType;
  /** Вид урона (физический/магический). Только для оружия. */
  damageKind?: DamageKind;
  /** Тип базового урона оружия (physical для мили/луков, стихия для посохов). */
  damageType?: DamageType;
  /** Сколько рук занимает оружие (1 или 2). Двуручное блокирует offhand — кроме полуторного. */
  hands?: number;
  /** Полуторное: двуручное, но можно держать и одной рукой со щитом, за штраф (`versatile.ts`). */
  versatile?: boolean;
  itemLevel: number;
  /** Базовые модификаторы, которые даёт сама база (без аффиксов). */
  baseStats: StatModifier[];
  /** Требования по атрибутам для надевания. */
  requirements: Partial<Record<Attribute, number>>;
  /** Размер в клетках инвентаря. */
  gridW: number;
  gridH: number;
  /** id 3D-модели (конфиг models) для меша брони/оружия. Нет → база слота / процедурка. */
  modelId?: string;
}

/** Скатанный на предмете аффикс (конкретное значение из диапазона тира). */
/** Прок «шанс каста» (D2 chance-to-cast): с шансом `chance` кастуется скилл `skillId` уровня `level`.
 *  `trigger`: 'hit' — когда сам бьёшь (наносишь урон); 'struck' — когда бьют тебя (получаешь урон). */
export interface ProcSpec {
  skillId: string;
  level: number;
  chance: number;
  trigger?: 'hit' | 'struck';
}
export interface RolledAffix {
  affixId: string;
  kind: 'prefix' | 'suffix';
  /** Стат-мод (у прок-аффиксов отсутствует). */
  modifier?: StatModifier;
  /** Прок каста при ударе (у стат-аффиксов отсутствует). */
  proc?: ProcSpec;
}

/** Конкретный экземпляр предмета (в мире/инвентаре/экипировке). */
export interface Item extends WeaponSignature {
  armorClass?: ArmorClass;
  /** Класс щита (для kind='shield'). */
  shieldClass?: ShieldClass;
  /** Вид предмета (оружие/броня/щит/украшение) — с базы. */
  kind?: ItemKind;
  /** Уникальный runtime-id экземпляра. */
  uid: string;
  baseId: string;
  name: string;
  /** Слот экипировки. У расходников отсутствует. */
  slot?: EquipSlot;
  /** Кол-во быстрых слотов пояса (для брони-пояса). */
  beltSlots?: number;
  /** Эффект применения (для kind='consumable'). */
  use?: ConsumableUse;
  attackType?: AttackType;
  damageKind?: DamageKind;
  damageType?: DamageType;
  hands?: number;
  /** Полуторное: двуручное, но держится и одной рукой со щитом, за штраф (`formulas/versatile.ts`). */
  versatile?: boolean;
  rarity: Rarity;
  /**
   * ТИР КАЧЕСТВА базы (`item-tiers`): Убогий → … → Мифический. До Ч5 тира в предмете НЕ БЫЛО
   * вовсе — он применялся при генерации и дальше существовал только приставкой в названии,
   * из-за чего кузница физически не могла его поднять и вместо этого множила статы ×1.2 без
   * предела. Теперь тир — свойство вещи, и лестница конечна по построению (`base.maxTier`).
   * Необязательное: старый сейв читается как есть, отсутствие = тир выводится по уровню.
   */
  tier?: string;
  /**
   * СКОЛЬКО РАЗ ВЕЩЬ УЖЕ ПЕРЕКАТЫВАЛИ в кузнице. Предел — `forgePrices.rerollLimit`.
   * Детерминированные шаги (подъём тира) ограничены `maxTier` сами по себе, а вот перекатка
   * крутит случайность: без предела её жмут, пока не выпадет идеал, и редкость аффиксов
   * перестаёт что-либо значить.
   * Считаем ПОТРАЧЕННОЕ, а не остаток: тогда отсутствие поля = «ни разу», и миграции не нужно.
   */
  rerolls?: number;
  itemLevel: number;
  requirements: Partial<Record<Attribute, number>>;
  /** База + скатанные аффиксы, готовые к суммированию. */
  affixes: RolledAffix[];
  baseStats: StatModifier[];
  /** Размер в клетках инвентаря. */
  gridW: number;
  gridH: number;
  /** Позиция в сетке инвентаря (клетки). null — не размещён/на земле. */
  pos?: { x: number; y: number } | null;
  /** id 3D-модели (конфиг models) для меша брони/оружия. Нет → база слота / процедурка. */
  modelId?: string;
  /**
   * СЛОМАНО: снято с трупа и в таком виде НЕ НАДЕВАЕТСЯ. Чинится у кузнеца за материалы
   * либо разбирается — в этом и есть выбор (docs/ECONOMY.md, ч4).
   *
   * ⚠ Отдельный флаг, а НЕ нижний тир (он зовётся «Убогий» и значит КАЧЕСТВО, а не
   * состояние): стартовый комплект персонажа создаётся с тирами,
   * и на первом уровне единственный доступный — как раз t0. Сделай t0 неносибельным, и новый
   * персонаж не сможет надеть собственную одежду.
   * Необязательное поле: старый сейв читается как есть, отсутствие = вещь целая.
   */
  broken?: boolean;
  /**
   * СКОЛЬКО ШТУК В СТЕКЕ — только у `kind:'material'`. У остальных видов поля нет вовсе:
   * стекирования в игре нет и не планируется (см. комментарий к `ItemKind`).
   * Отсутствие поля = одна штука, поэтому старые сейвы читаются без миграции.
   */
  count?: number;
  /** id материала из конфига `craft-materials` — только у `kind:'material'`. */
  materialId?: string;
  /**
   * ДЕТАЛИ СКОВАННОЙ ВЕЩИ (docs/CRAFT_WEAPONS.md): четыре варианта из `weapon-parts`, у каждого —
   * своя ступень материала. Только ИД — значения выводятся из конфига. У найденной вещи поля нет:
   * её детали выводятся детерминированно (`partsOf`), так что старые сейвы читаются без миграции.
   */
  parts?: CraftParts;
  /**
   * ДЕТАЛИ НАЙДЕННОЙ ВЕЩИ, записанные в момент выпадения (§26): у меча, клинок которого несёт статы
   * своей геометрии, набор деталей больше не выводится заново при каждом чтении — иначе подъём тира
   * или новый вариант в пуле подменили бы клинок, а статы остались бы от старого. Отдельно от `parts`:
   * по `parts` вещь считается скованной (переплавка вместо разбора).
   */
  foundParts?: CraftParts;
  /**
   * РАЗБРОС УРОНА ОТ ШИРИНЫ КЛИНКА (§26): мин и макс базы разведены вокруг той же середины ×s
   * (0.4 — широкий, ровный удар; 1.6 — узкий, вразнобой). Лежит на вещи, чтобы подъём тира и вывод тира
   * старых сейвов пересчитывали мин/макс с той же формой. Нет поля — ×1, числа базы.
   */
  spreadMult?: number;
  /**
   * БРОСОК БАЗЫ — доля q ∈ [0, 1] для каждой катаемой статы (урон мин/макс, броня): где в вилке
   * своего тира легла ЭТА вещь. Числа при этом лежат в `baseStats` готовыми — бой и тултип бросок
   * не читают. Храним долю, а не число: подъём тира в кузнице пересчитывает статы «база × тир × q»
   * и вещь остаётся на том же месте вилки. Нет поля (старые сейвы, стартовый комплект) — q = 0.5,
   * то есть ровно прежние числа.
   */
  baseRoll?: BaseRoll;
  /**
   * ВИЛКА ВМЕСТО ЧИСЕЛ — только у предпросмотра ковки: до ковки игрок видит «от и до», результат —
   * после. У настоящих вещей поля нет.
   */
  rollPreview?: Partial<Record<RolledStat, [number, number]>>;
  /**
   * ИСТОРИЧЕСКИЙ ТИП скованной вещи — id правила из `weapon-types.names` на момент ковки
   * («Ранний меч»). Нет поля — имя собрано фолбэком или вещь найдена. Статов не несёт.
   */
  typeId?: string;
  /**
   * ЁМКОСТЬ АФФИКСОВ, объявленная при ковке: сколько префиксов и суффиксов вещь примет при
   * зачаровании. ⚠ Обязана лежать НА ПРЕДМЕТЕ: иначе перекатка пересчитала бы слоты по редкости
   * и снесла купленную форму. Нет поля = слоты по редкости, как у любого дропа.
   */
  affixCap?: { prefix: number; suffix: number };
}

/** Статы, которые катаются в вилке при выпадении и ковке (то, что масштабирует тир). */
export type RolledStat = 'minDamage' | 'maxDamage' | 'armor';
/** Доли броска базы по статам, q ∈ [0, 1]. */
export type BaseRoll = Partial<Record<RolledStat, number>>;

/** Деталь скованной вещи: вариант из `weapon-parts` и ступень материала (1..5), из которого она сделана. */
export interface CraftPartPick {
  id: string;
  step: number;
}

/** Четыре гнезда скованной вещи. Ступень ВЕЩИ выводится из ступеней деталей (`tierOfSteps`). */
export interface CraftParts {
  strike: CraftPartPick;
  grip: CraftPartPick;
  bind: CraftPartPick;
  head: CraftPartPick;
}
