import type { Item } from './items.js';

/**
 * Общий на аккаунт городской сундук (shared stash, в духе D2R). Живёт ВНЕ `SaveState`
 * — на уровне аккаунта (одна истина на всех персонажей пользователя), чтобы можно было
 * перекладывать шмот между своими героями. Каждая вкладка — независимая сетка предметов
 * (`pos` в координатах этой вкладки; размер вкладки задаёт `balance.stash`).
 */
export interface AccountStash {
  version: number;
  tabs: Item[][];
  /**
   * ⭐ СЫРЬЁ АККАУНТА — общее для всех героев, как вкладка валюты в PoE. Лежит здесь, а не в
   * `SaveState`, ровно по той же причине, что и сундук: перекладывать между своими персонажами.
   *
   * ⚠ Это НЕ вкладка `tabs`: материалы не предметы (нет uid, позиции и размера), их нельзя
   * таскать мышью, и они не должны попадать в журнал происхождения предметов, который слепо
   * разворачивает `tabs` двойным циклом (`server/src/db/items.ts`).
   * Необязательное: старый сундук читается как есть, отсутствие = пусто.
   */
  materials?: Record<string, number>;
}

export const STASH_VERSION = 1;
